"""Перезапрос сводки: не чаще двух минут и только в видимой вкладке.

**Это запасной путь при выключенных живых обновлениях** (`docs/ustroystvo/12-zhivye-obnovleniya.md`
§11), и стережётся он потому, что ломается тихо и дорого.

Сводка — самая дорогая ручка в системе: замерено 23 запроса к базе против
четырёх у списка бумаг. Она нарочно не стоит под потолком `tests/test_speed.py`
(её цена растёт с данными, абсолютный потолок был бы мигающим сторожем) — то
есть **рост цены здесь заметить нечем, кроме этой проверки**.

Две беды, и обе выглядят как улучшение:

- **интервал укоротили.** «Пусть обновляется раз в десять секунд, так живее» —
  и одна вкладка даёт 8280 запросов в час вместо 690;
- **проверку видимости сняли.** Десять забытых вкладок на фирму начинают
  перезапрашивать самую дорогую ручку круглосуточно. В проекте это уже
  случалось: команда, безобидная в руках человека, из цикла отрисовки дала 240
  запросов в час и уронила боевое обновление.
"""

import pathlib
import re

from tests.test_fonovye_perezaprosy import (
    _telo_effekta,
    sprashivaet_vidimost,
    telo_tajmera,
)

KOREN = pathlib.Path(__file__).resolve().parent.parent
SVODKA = KOREN / "web" / "frontend" / "crm" / "src" / "screens" / "Dashboard.tsx"

#: Ниже этого перезапрос сводки опускать нельзя. Две минуты — из плана работ.
MINIMUM_MS = 120_000


def _tekst() -> str:
    return SVODKA.read_text(encoding="utf-8")


def test_perebor_vidit_ekran():
    """Сторож, ничего не нашедший, зеленеет на любой беде."""
    assert "setInterval" in _tekst(), (
        "на экране сводки нет ни одного таймера — перезапрос убрали целиком, "
        "и проверки ниже стерегут пустоту"
    )


def test_perezapros_ne_chashche_dvukh_minut():
    tekst = _tekst()
    nayd = re.search(r"const SVODKA_POLL_MS = ([\d_]+);", tekst)
    assert nayd, "не нашёл, с каким сроком перезапрашивается сводка"
    srok = int(nayd.group(1).replace("_", ""))
    assert srok >= MINIMUM_MS, (
        f"сводка перезапрашивается раз в {srok / 1000:.0f} с, а нижняя граница — "
        f"{MINIMUM_MS / 1000:.0f} с. Замерено: один заход стоит 23 запроса к базе, "
        "и минутный срок дал бы 1380 запросов в час с ОДНОЙ вкладки"
    )


def test_perezapros_tolko_v_vidimoy_vkladke():
    """Спрашивать обязан САМ таймер, а не файл где-нибудь.

    Первая редакция искала слово `visibilityState` по всему файлу — и находила
    его в определении `vidno`, даже если таймер эту функцию не звал. Снять
    `if (vidno())` из таймера, оставив слушателя `visibilitychange`, — самая
    естественная правка, и она сторожа не красила. Разбор общий с
    `tests/test_fonovye_perezaprosy.py`, там же его собственная самопроверка.
    """
    tekst = _tekst()
    stroki = tekst.splitlines()
    nomera = [n for n, st in enumerate(stroki) if "setInterval" in st]
    assert nomera, "в сводке не нашлось повторяющегося таймера вовсе"

    for nomer in nomera:
        telo = _telo_effekta(stroki, nomer)
        assert sprashivaet_vidimost(telo, telo_tajmera(telo)), (
            f"таймер сводки (строка {nomer + 1}) не спрашивает, видна ли вкладка. "
            "Десять забытых вкладок на фирму дают десять потоков перезапросов "
            "самой дорогой ручки круглосуточно"
        )

    assert "visibilitychange" in tekst, (
        "возвращение на вкладку не перечитывает сводку. Человек вернулся именно "
        "затем, чтобы посмотреть, — и увидел бы утренние числа под свежим "
        "заголовком"
    )


def test_dorogi_za_dannymi_odna():
    """Второй способ получать те же данные разошёлся бы с первым.

    Запрет из плана (задача 7.4): механизм обновления, живущий параллельно
    основному, — это два места, где чинить. Здесь одна `load`, а тихий заход от
    громкого отличается только тем, как обходится с отказом.
    """
    # Ищем сам вызов, а не цепочку целиком: `api` и `.get` стоят на разных
    # строках, и регулярка по «api.get» их не видит.
    skolko = len(re.findall(r'\.get\("/dashboard"\)', _tekst()))
    assert skolko == 1, (
        f"за сводкой ходят из {skolko} мест. Дорога обязана быть одна, иначе "
        "фоновый перезапрос и первая загрузка разойдутся"
    )


def test_zapasnoy_put_nazvan_zapasnym():
    """Второй механизм обновления обязан знать о первом.

    Комментарий у таймера обязан говорить, что он запасной путь при выключенных
    живых обновлениях, и ссылаться на их устройство. Без этого через полгода
    таймер примут за основной путь и начнут «улучшать».
    """
    tekst = _tekst()
    assert "12-zhivye-obnovleniya.md" in tekst and "выключены" in tekst, (
        "у таймера сводки не сказано, что он запасной путь при выключенных живых "
        "обновлениях и где их устройство"
    )
