"""Перезапрос сводки: не чаще двух минут и только в видимой вкладке.

**Это запасной путь при выключенных живых обновлениях** (`docs/ustroystvo/12-zhivye-obnovleniya.md`
§11), и стережётся он потому, что ломается тихо и дорого.

Сводка — самая дорогая ручка в системе: замерено 23 запроса к базе против
четырёх у списка бумаг. Она нарочно не стоит под потолком `tests/test_speed.py`
(её цена растёт с данными, абсолютный потолок был бы мигающим сторожем) — то
есть **рост цены здесь заметить нечем, кроме этой проверки**.

Три беды, и все три выглядят как улучшение:

- **интервал укоротили.** «Пусть обновляется раз в десять секунд, так живее» —
  и одна вкладка даёт 8280 запросов в час вместо 690;
- **проверку видимости сняли.** Десять забытых вкладок на фирму начинают
  перезапрашивать самую дорогую ручку круглосуточно. В проекте это уже
  случалось: команда, безобидная в руках человека, из цикла отрисовки дала 240
  запросов в час и уронила боевое обновление;
- **завели ВТОРОЙ такой же.** Именно это и было до 07.09.2026: у сводки стоял
  свой таймер с тем же сроком и своим слушателем видимости, а `useLiveTopic`
  вёл точно такой же. При выключенной живости самая дорогая ручка дёргалась по
  два раза подряд каждые две минуты и ещё по два при каждом возврате на
  вкладку. Отсюда правило: **запасной путь один, и живёт он в `lib/live.tsx`**,
  а экраны к нему подписываются.
"""

import pathlib
import re

from tests.test_fonovye_perezaprosy import (
    _telo_effekta,
    sprashivaet_vidimost,
    telo_tajmera,
)

KOREN = pathlib.Path(__file__).resolve().parent.parent
ISTOCHNIK = KOREN / "web" / "frontend" / "crm" / "src"
#: Где живёт сам запасной перезапрос — один на все экраны.
ZHIVOST = ISTOCHNIK / "lib" / "live.tsx"
#: Кто им пользуется. Проверяется отдельно: таймер целый, а подписка снята —
#: и сводка не обновляется вовсе, притом что сторож на таймер зелен.
SVODKA = ISTOCHNIK / "screens" / "Dashboard.tsx"

#: Ниже этого перезапрос сводки опускать нельзя. Две минуты — из плана работ.
MINIMUM_MS = 120_000


def _zhivost() -> str:
    return ZHIVOST.read_text(encoding="utf-8")


def _svodka() -> str:
    return SVODKA.read_text(encoding="utf-8")


def test_perebor_vidit_zapasnoy_put():
    """Сторож, ничего не нашедший, зеленеет на любой беде."""
    assert "setInterval" in _zhivost(), (
        "в живом слое нет ни одного таймера — запасной перезапрос убрали "
        "целиком, и проверки ниже стерегут пустоту"
    )


def test_perezapros_ne_chashche_dvukh_minut():
    nayd = re.search(r"export const ZAPASNOY_MS = ([\d_]+);", _zhivost())
    assert nayd, "не нашёл, с каким сроком идёт запасной перезапрос"
    srok = int(nayd.group(1).replace("_", ""))
    assert srok >= MINIMUM_MS, (
        f"экран перезапрашивается раз в {srok / 1000:.0f} с, а нижняя граница — "
        f"{MINIMUM_MS / 1000:.0f} с. Замерено: один заход в сводку стоит 23 запроса "
        "к базе, и минутный срок дал бы 1380 запросов в час с ОДНОЙ вкладки"
    )


def test_perezapros_tolko_v_vidimoy_vkladke():
    """Спрашивать обязан САМ таймер, а не файл где-нибудь.

    Первая редакция искала слово `visibilityState` по всему файлу — и находила
    его в определении `vidno`, даже если таймер эту функцию не звал. Снять
    `if (vidno())` из таймера, оставив слушателя `visibilitychange`, — самая
    естественная правка, и она сторожа не красила. Разбор общий с
    `tests/test_fonovye_perezaprosy.py`, там же его собственная самопроверка.
    """
    tekst = _zhivost()
    stroki = tekst.splitlines()
    nomera = [n for n, st in enumerate(stroki) if "setInterval" in st]
    assert nomera, "в живом слое не нашлось повторяющегося таймера вовсе"

    for nomer in nomera:
        telo = _telo_effekta(stroki, nomer)
        assert sprashivaet_vidimost(telo, telo_tajmera(telo)), (
            f"запасной таймер (строка {nomer + 1}) не спрашивает, видна ли вкладка. "
            "Десять забытых вкладок на фирму дают десять потоков перезапросов "
            "самой дорогой ручки круглосуточно"
        )

    assert "visibilitychange" in tekst, (
        "возвращение на вкладку не перечитывает экран. Человек вернулся именно "
        "затем, чтобы посмотреть, — и увидел бы утренние числа под свежим "
        "заголовком"
    )


def test_svodka_podpisana_na_zapasnoy_put():
    """Таймер целый, а подписка снята — и сводка не обновляется вовсе.

    Проверка стоит отдельно от таймера нарочно: они в разных файлах, и сторож
    на один из них зеленеет, когда сломан другой.
    """
    tekst = _svodka()
    assert "useLiveTopic" in tekst, (
        "сводка не подписана на живой слой — ни намёков, ни запасного "
        "перезапроса у неё не осталось"
    )
    assert "load(true)" in tekst, "подписка сводки ничего не перечитывает"


def test_u_svodki_net_svoego_takogo_zhe():
    """Второго запасного пути быть не должно: они удваивают запросы.

    Свой такой же у сводки стоял, и это была не подстраховка: при выключенной
    живости самая дорогая ручка дёргалась по два раза подряд.
    """
    assert "setInterval" not in _svodka(), (
        "у сводки завёлся собственный повторяющийся таймер. Запасной перезапрос "
        "один и живёт в lib/live.tsx: два механизма с одним сроком — это удвоение "
        "запросов к самой дорогой ручке, а не надёжность"
    )


def test_dorogi_za_dannymi_odna():
    """Второй способ получать те же данные разошёлся бы с первым.

    Запрет из плана (задача 7.4): механизм обновления, живущий параллельно
    основному, — это два места, где чинить. Здесь одна `load`, а тихий заход от
    громкого отличается только тем, как обходится с отказом.
    """
    # Ищем сам вызов, а не цепочку целиком: `api` и `.get` стоят на разных
    # строках, и регулярка по «api.get» их не видит.
    skolko = len(re.findall(r'\.get\("/dashboard"\)', _svodka()))
    assert skolko == 1, (
        f"за сводкой ходят из {skolko} мест. Дорога обязана быть одна, иначе "
        "фоновый перезапрос и первая загрузка разойдутся"
    )


def test_zapasnoy_put_nazvan_zapasnym():
    """Запасной путь обязан знать, что он запасной.

    Комментарий у срока обязан говорить, что это путь при выключенных живых
    обновлениях, и ссылаться на их устройство. Без этого через полгода таймер
    примут за основной путь и начнут «улучшать».
    """
    tekst = _zhivost()
    assert "12-zhivye-obnovleniya.md" in tekst and "выключен" in tekst, (
        "у запасного перезапроса не сказано, что он путь при выключенных живых "
        "обновлениях и где их устройство"
    )
