"""Выгруженную миграцию не правят. Никогда.

**Это сторож на ошибку, которая уже стоила отката боевого сервера.** В уже
применённую ревизию дописали колонку — вместо того, чтобы добавить новую.
Alembic применённое заново не гоняет: колонка в базе не появилась, модель её
требовала, сверка схемы отказалась поднимать приложение, обновление откатилось
вместе с базой. Одиннадцать минут простоя.

**Почему этого не ловят соседние проверки.** И сверка схемы с моделями, и
автогенератор строят базу С НУЛЯ, прогоняя всю цепочку. Правленая миграция при
таком построении выглядит целой — колонка-то в ней есть. Расхождение появляется
ровно там, где ревизия уже отмечена применённой, то есть на всякой живой
установке, и только на ней.

Отсюда признак: **файл миграции трогали после того, как он уехал**. Миграция
пишется один раз и уезжает; всё, что понадобилось потом, — это новая ревизия, а
не правка старой.

Слово «уехал» здесь считается не по всей истории, а от **точки отсчёта** — того
коммита, которым завели этот самый файл. До неё миграции правились пачками
(переезд на MySQL, язык данных, засев номеров), живых установок ещё не было, и
предъявлять им сторожа не за что. Точка не задаётся руками: она спрашивается у
git, иначе была бы выключателем в одну строку. Разбор — у `TOCHKA_OTSCHYOTA` и
`_kogda_zaveli_storozha`.

Проверка смотрит в историю git, потому что в самом файле следов правки нет.

**И требует историю ЦЕЛИКОМ.** В мелком клоне (`--depth 1`, а это умолчание
`actions/checkout`) граница обрезки выглядит для git корневым коммитом, а в
корневом коммите добавлены все файлы разом. То есть `git log -- файл` отвечает
«один коммит» про КАЖДУЮ миграцию, включая правленую трижды. Проверка при этом
зеленела, и зеленела же проверка «сторож видит историю» — ровно двадцать с
лишним файлов с историей, как и требуется. Замерено клоном `--depth 1` этого
самого репозитория.

Полтора месяца в CI это выглядело работающим и не проверяло ничего — сторож,
поставленный ПОСЛЕ отката боевого сервера, ни разу не сработал. Поэтому
мелкость репозитория теперь спрашивается прямо, и на мелком клоне проверка
отказывается, а не зеленеет.
"""

import pathlib
import subprocess

import pytest

ROOT = pathlib.Path(__file__).resolve().parent.parent
VERSII = ROOT / "database" / "migrations" / "versions"

#: Есть ли рядом история git. В воротах деплоя её нет: репозиторий копируется в
#: образ без `.git`, и это правильно — история весит больше самого кода.
#:
#: Значит проверка работает там, где история есть: в CI (полная выкладка) и на
#: машине разработчика. Пропуск объявляется вслух: молчаливо зелёная проверка
#: без истории хуже отсутствующей — она создаёт впечатление, что стерегут.
EST_ISTORIYA = (ROOT / ".git").exists()


def _git(*argv: str) -> str:
    """Спросить git и вернуть вывод. Пусто — не отработал."""
    itog = subprocess.run(
        ["git", *argv], cwd=ROOT, capture_output=True, text=True, check=False
    )
    return itog.stdout if itog.returncode == 0 else ""


#: Коммит, с которого миграции считаются выгруженными.
#:
#: Это коммит, которым завели саму проверку — тот, что закрывал откат боевого
#: сервера. Всё, что до него, — предыстория: миграции тогда правились пачками
#: (переезд на MySQL, язык данных, засев номеров), живых установок ещё не было,
#: и предъявлять их этому сторожу не за что. Требовать чистоты задним числом
#: значило бы либо переписать историю, либо занести семнадцать файлов в список
#: законных правок — и список перестал бы что-либо значить.
#:
#: Точка отсчёта не двигается. Сдвинуть её вперёд — значит простить правку,
#: которая уже уехала на сервер; ровно то, ради чего сторож и стоит.
TOCHKA_OTSCHYOTA = "c28a3b2fea1a6e53228291ef8573399e30a9b3f8"


def _kogda_zaveli_storozha() -> str:
    """Коммит, которым завели ЭТОТ файл. Он и есть точка отсчёта.

    Спрашиваем у git, а не верим константе. Константа — выключатель сторожа в
    одну строку: сдвинь её на сегодняшний коммит, и правленая выгруженная
    миграция зеленеет, не оставив следа в наборе. Это самый короткий способ
    погасить красный CI, и именно поэтому он не должен работать.

    Проверено подлогом: коммит A правит выгруженную миграцию (набор красный),
    коммит B меняет только константу на хеш A — набор снова зелёный.
    """
    vyvod = _git(
        "log", "--diff-filter=A", "--format=%H", "--", "tests/test_migratsii_ne_pravyat.py"
    )
    stroki = [s.strip() for s in vyvod.splitlines() if s.strip()]
    return stroki[-1] if stroki else ""


def _repozitoriy_melkiy() -> bool:
    """Обрезана ли история. На мелком клоне проверять нечего.

    Спрашиваем прямо, а не по косвенным признакам: косвенные и обманули. В
    мелком клоне граница обрезки — «корневой» коммит, где добавлены все файлы,
    и по числу коммитов мелкий репозиторий неотличим от свежего.
    """
    return _git("rev-parse", "--is-shallow-repository").strip() == "true"


def _tochka_na_meste() -> bool:
    """Есть ли в этой копии коммит, от которого ведётся отсчёт."""
    return bool(_git("cat-file", "-t", TOCHKA_OTSCHYOTA).strip() == "commit")


bez_istorii = pytest.mark.skipif(
    not EST_ISTORIYA,
    reason="рядом нет .git — историю миграций не прочитать (в воротах деплоя её и нет)",
)

#: Файл ворот CI. В образе его тоже нет: `.dockerignore` исключает `.github/`
#: вместе с `.git/`. Условие пропуска пишем своё, а не опираемся на `bez_istorii`:
#: пропуск по чужой причине держится ровно до дня, когда чужую причину уберут.
VOROTA = ROOT / ".github" / "workflows" / "tests.yml"

bez_vorot = pytest.mark.skipif(
    not VOROTA.exists(),
    reason="рядом нет .github/workflows — ворота CI не прочитать (в образе их и нет)",
)

#: Ревизии, которые правились законно, и чем это оправдано.
#:
#: Законный повод ровно один: правка, которая НИЧЕГО не меняет в схеме —
#: комментарий, докстрока, опечатка в тексте. Всё остальное (колонка, индекс,
#: ограничение, порядок шагов) означает, что на уже обновившихся установках
#: этого не произойдёт никогда.
#:
#: Запись сюда — обещание, что правка бессхемная. Проверить это машинно нельзя,
#: поэтому цена записи — объяснение, за которое отвечает пишущий.
#: Пуст, и это ПРАВИЛЬНОЕ состояние, а не забытая уборка.
#:
#: Здесь стояла запись про `c7f2a91d4e08_telegram.py` — ту самую ревизию, в
#: которую дописали колонку и которая стоила отката боевого сервера. Со сменой
#: признака (счёт от точки отсчёта, а не по всей истории) её основание отпало:
#: все три коммита файла лежат ДО точки, и сторож про него и так молчит.
#:
#: Оставленная запись превратилась бы в ПОСТОЯННОЕ СЛЕПОЕ ПЯТНО ровно на том
#: файле, правка которого уже стоила аварии: цикл ниже делает `continue` и на
#: файл не смотрит вовсе. Проверено подлогом — дописанная в эту ревизию строка
#: проходила молча, тогда как та же строка в соседней краснела.
PRAVLENY_ZAKONNO: dict[str, str] = {}


def _skolko_raz_trogali(imya: str) -> int:
    """Сколько коммитов касалось файла миграции ОТ точки отсчёта до сюда.

    Не «всего за историю»: до точки отсчёта миграции правились пачками, живых
    установок ещё не было, и предъявлять их этому сторожу не за что. Разбор — у
    `TOCHKA_OTSCHYOTA`.
    """
    vyvod = _git(
        "log", "--oneline", f"{TOCHKA_OTSCHYOTA}..HEAD",
        "--", f"database/migrations/versions/{imya}",
    )
    return len([s for s in vyvod.splitlines() if s.strip()])


def _byl_na_tochke(imya: str) -> bool:
    """Существовал ли файл миграции уже на точке отсчёта."""
    itog = subprocess.run(
        ["git", "cat-file", "-e", f"{TOCHKA_OTSCHYOTA}:database/migrations/versions/{imya}"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    return itog.returncode == 0


def _pravili_posle_vygruzki(imya: str) -> int:
    """Сколько раз файл правили ПОСЛЕ того, как он уехал. Ноль — чисто.

    Одним числом коммитов это не решается, и попытка решить им уже дала дыру:
    миграция, написанная ДО точки отсчёта и правленая ПОСЛЕ неё, имела ровно
    один коммит в окне и выглядела свежей. Поймано подлогом в полном клоне —
    правка выгруженной ревизии прошла мимо сторожа.

    Считаем поэтому раздельно:

    - файл был на точке отсчёта — значит он уже выгружен, и **любая** правка
      после неё незаконна;
    - файла не было — первый коммит в окне это его написание, и незаконно всё,
      что после первого.
    """
    v_okne = _skolko_raz_trogali(imya)
    if _byl_na_tochke(imya):
        return v_okne
    return max(0, v_okne - 1)


@bez_istorii
def test_vygruzhennuyu_migratsiyu_ne_pravili():
    """Ни одну миграцию не правили ПОСЛЕ того, как она уехала.

    Признак не «сколько всего коммитов у файла», а «сколько их после точки
    отсчёта, и был ли файл на ней»:

    - файл был на точке отсчёта — он уже выгружен, и незаконна ЛЮБАЯ правка
      после неё;
    - файла не было — первый коммит в окне это его написание, незаконно всё,
      что дальше.

    Раздельно, потому что одним числом это не решается, и попытка решить им уже
    дала дыру: миграция, написанная ДО точки и правленая ПОСЛЕ, имела в окне
    ровно один коммит и выглядела свежей. Поймано подлогом в полном клоне.

    Разбор самой точки отсчёта — у `TOCHKA_OTSCHYOTA`.
    """
    # Отказываемся САМИ, а не полагаемся на соседний тест.
    #
    # На мелком клоне точки отсчёта в копии нет, `git log ТОЧКА..HEAD` молчит, у
    # всех файлов ноль правок — и эта проверка зеленеет, ничего не проверив.
    # Пока гоняют весь файл, красным становится сосед `test_istoriya_ne_obrezana`
    # и набор всё же красный; но точечный прогон одного теста (или отбор по
    # имени в будущей джобе) дал бы зелень на пустоте. Сторож обязан отвечать за
    # себя.
    assert not _repozitoriy_melkiy(), (
        "история обрезана (мелкий клон) — правки миграций считать не от чего"
    )
    assert _tochka_na_meste(), (
        f"коммита {TOCHKA_OTSCHYOTA[:12]}, от которого ведётся отсчёт, в копии нет"
    )

    fayly = sorted(p.name for p in VERSII.glob("*.py") if p.name != "__init__.py")
    assert len(fayly) > 20, f"миграций найдено {len(fayly)} — проверка смотрит не туда"

    # Ноль правок в окне — обычное дело: сегодня так у большинства миграций,
    # написанных до точки отсчёта. Новая миграция в рабочем дереве, ещё не
    # закоммиченная, тоже даёт ноль — и её править можно сколько угодно.
    pravlenye = []
    for imya in fayly:
        if imya in PRAVLENY_ZAKONNO:
            continue
        raz = _pravili_posle_vygruzki(imya)
        if raz:
            pravlenye.append(f"{imya} — правок после выгрузки: {raz}")

    assert pravlenye == [], (
        "выгруженную миграцию правили:\n  "
        + "\n  ".join(pravlenye)
        + "\n\nAlembic применённую ревизию заново не гоняет. На установках, где "
        "она уже накатана, правка не выполнится НИКОГДА — и расхождение "
        "обнаружится отказом приложения подняться.\n"
        "Нужна новая ревизия. Если правка бессхемная (комментарий, опечатка) — "
        "внесите файл в PRAVLENY_ZAKONNO с объяснением."
    )


def test_v_spiske_pravlennykh_net_ukazyvayushchikh_v_pustotu():
    """Названный файл обязан существовать.

    Иначе запись переживёт свою миграцию и станет памяткой о прошлом, а
    настоящая правка пройдёт мимо проверки.
    """
    est = {p.name for p in VERSII.glob("*.py")}
    propavshie = sorted(set(PRAVLENY_ZAKONNO) - est)
    assert propavshie == [], (
        "в списке законных правок записи без файла: " + ", ".join(propavshie)
    )


@bez_istorii
def test_istoriya_ne_obrezana():
    """История обязана быть целой, иначе проверять нечего.

    **Эта проверка стоит вместо прежней, которую мелкий клон обманывал.**
    Прежняя считала файлы с непустой историей и требовала «больше двадцати» — а
    в мелком клоне граница обрезки выглядит корневым коммитом, где добавлены
    все файлы разом. То есть история «была видна» у всех до единого, и обе
    проверки зеленели, ничего не проверяя. Полтора месяца в CI.

    Мелкость спрашивается у git прямо. По косвенным признакам её не отличить —
    косвенные и обманули.
    """
    assert not _repozitoriy_melkiy(), (
        "история обрезана (мелкий клон) — сторож правленых миграций не работает "
        "и молча зеленеет.\n"
        "В CI это лечится `fetch-depth: 0` у `actions/checkout`, локально — "
        "`git fetch --unshallow`."
    )
    assert _tochka_na_meste(), (
        f"коммита {TOCHKA_OTSCHYOTA[:12]}, от которого ведётся отсчёт, в этой "
        "копии нет — считать правки не от чего"
    )


@bez_istorii
def test_storozh_chitaet_git():
    """И сам `git log` обязан отвечать, а не молчать кодом возврата.

    Молчащий git даёт ноль коммитов у каждого файла — правленых нет — зелено.
    Ровно так проверка умирает, продолжая выглядеть рабочей.
    """
    # Смотрим ВСЮ историю, а не от точки отсчёта: после неё миграции никто не
    # правил, и «ноль» там — правда, а не молчание.
    vyvod = _git("log", "--oneline", "--", "database/migrations/versions")
    assert len(vyvod.splitlines()) > 10, (
        "git log по каталогу миграций почти ничего не вернул — проверка не "
        "читает историю и потому не проверяет ничего"
    )


@bez_vorot
def test_vorota_ci_prosyat_istoriyu_tselikom():
    """`actions/checkout` по умолчанию берёт ОДИН коммит — этого мало.

    CI — единственное место, где сторож запускается сам. Пропади здесь
    `fetch-depth`, и он снова станет зелёным украшением, а узнать об этом будет
    неоткуда: набор останется зелёным.
    """
    stroki = VOROTA.read_text(encoding="utf-8").splitlines()

    # Ищем `uses: actions/checkout` В ЛЮБОЙ ФОРМЕ ЗАПИСИ, а не только слитную
    # `- uses: …`. Форма из документации GitHub — `- name: Checkout` отдельной
    # строкой, `uses:` следующей, — её и копируют; прежняя проверка её попросту
    # не видела, и ворота могли вернуться к мелкому клону молча. Проверено
    # подлогом ровно в той джобе, где сторож миграций и запускается.
    shagi = [
        nomer for nomer, stroka in enumerate(stroki)
        if "uses:" in stroka and "actions/checkout" in stroka
    ]
    assert shagi, "в воротах нет шага checkout — проверка смотрит не туда"
    for nomer in shagi:
        # `with: fetch-depth: 0` идёт следом за шагом; до начала СЛЕДУЮЩЕГО шага
        # (строка, начинающаяся с `- ` на том же отступе) или через шесть строк.
        okno = []
        for dalshe in stroki[nomer + 1 : nomer + 8]:
            if dalshe.lstrip().startswith("- "):
                break
            okno.append(dalshe)
        assert any("fetch-depth: 0" in s for s in okno), (
            f"шаг checkout в строке {nomer + 1} берёт историю по умолчанию "
            "(один коммит) — сторож правленых миграций на такой копии зеленеет "
            "впустую"
        )


@bez_istorii
def test_tochka_otschyota_ne_sdvinuta():
    """Точка отсчёта — это коммит, которым завели ЭТОТ файл. Не любой другой.

    **Иначе у сторожа есть выключатель в одну строку.** Сдвинь константу на
    сегодняшний коммит — и всякая правленая выгруженная миграция окажется «до
    точки», то есть простится задним числом. Красный CI гасится строкой, следа
    в наборе не остаётся, а на боевом сервере приложение не поднимется.

    Проверено подлогом: коммит A правит выгруженную миграцию (набор красный),
    коммит B меняет ТОЛЬКО константу на хеш A — набор снова зелёный.
    """
    zaveli = _kogda_zaveli_storozha()
    assert zaveli, "не нашлось коммита, которым завели файл сторожа — проверять не с чем"
    assert TOCHKA_OTSCHYOTA == zaveli, (
        f"точка отсчёта сдвинута: в файле {TOCHKA_OTSCHYOTA[:12]}, "
        f"а сторожа завели коммитом {zaveli[:12]}.\n"
        "Сдвиг вперёд прощает правки, уже уехавшие на сервер, — ровно то, ради "
        "чего сторож и стоит."
    )


@bez_istorii
def test_okno_otscheta_ne_pustoe():
    """Окно `ТОЧКА..HEAD` обязано хоть что-то отдавать.

    Замолчи именно эта форма команды — а считает правки только она, — у всех
    файлов выйдет ноль, главная проверка зазеленеет, и оба надзирателя останутся
    зелёными: `test_istoriya_ne_obrezana` смотрит лишь на наличие коммита, а
    `test_storozh_chitaet_git` спрашивает git БЕЗ диапазона ревизий.
    """
    vyvod = _git("log", "--oneline", f"{TOCHKA_OTSCHYOTA}..HEAD")
    assert [s for s in vyvod.splitlines() if s.strip()], (
        f"`git log {TOCHKA_OTSCHYOTA[:12]}..HEAD` не вернул ни одного коммита — "
        "правки миграций считать нечем, а проверка при этом зелёная"
    )
