"""Отметка сборки фронтенда: по ней открытая вкладка узнаёт про обновление.

**Беда, ради которой это написано.** Боевой сервер обновляется сам
(`deploy/updater.py`). Новый `index.html` браузер переспросит — он отдаётся с
`no-cache` (`web/main.py`), — но переспрашивает он его только при ЗАГРУЗКЕ
страницы. У того, у кого CRM просто открыта, продолжает работать вчерашняя
сборка: она уже в памяти вкладки, и обновляться ей неоткуда.

Дальше по-разному. Иногда старый экран просто отстаёт от нового сервера и
показывает неправду — новый блок без подписи, поле, которого он не знает.
Иногда бандл, на который он сошлётся, обновление уже унесло, и вкладка встаёт
насмерть. И то и другое человек читает как «программа сломалась», а лечится
это нажатием F5, о котором надо догадаться. Найдено владельцем 07.09.2026: на
экране блоков появилась строка без названия, и виновата была открытая с ночи
вкладка.

Отметка — имя собранного файла со скриптом: у него в имени хэш содержимого, то
есть оно меняется ровно тогда, когда меняется сам фронтенд, и не меняется от
перезапуска. Считается один раз на процесс: процесс и так перезапускается
обновлением.
"""

from __future__ import annotations

import re
from functools import lru_cache
from pathlib import Path

DIST = Path(__file__).parent / "frontend" / "crm" / "dist"

#: `<script ... src="/assets/index-Ab12Cd.js">` — имя с хэшем содержимого.
_SKRIPT = re.compile(r"/assets/(index-[A-Za-z0-9_-]+\.js)")

#: Отметка, когда сборки нет вовсе: разработка, где фронт поднят отдельно.
#: Пустая строка не годится — по ней не отличить «сборки нет» от «заголовок
#: потерялся по дороге», а второе значило бы молчаливо выключенное обновление.
BEZ_SBORKI = "dev"


@lru_cache(maxsize=1)
def otmetka() -> str:
    """Имя собранного скрипта или `dev`. Считается один раз на процесс."""
    try:
        stranitsa = (DIST / "index.html").read_text(encoding="utf-8")
    except OSError:
        return BEZ_SBORKI
    nayden = _SKRIPT.search(stranitsa)
    return nayden.group(1) if nayden else BEZ_SBORKI
