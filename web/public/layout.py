"""Модульная сетка витрины: готовые композиции на 1–7 работ.

Работы раскладываются не в masonry, а в «модуль» — заранее нарисованную
композицию с фиксированными местами под каждую работу. Плитки слегка
перекрывают друг друга: это и даёт живую, «собранную руками» страницу вместо
ровных колонок. Соотношение сторон работы при этом не сохраняется — форму
задаёт модуль, картинка кадрируется (``object-fit: cover``).

Координаты — проценты от рамки модуля (0..100 по обеим осям), сама рамка задана
отношением сторон ``ratio`` (ширина / высота). Каждая композиция заполняет рамку
целиком: слева 0, сверху 0, справа 100, снизу 100 — пустых полей по краям нет.

Работ на доске может быть больше семи: тогда они разбиваются на несколько
модулей подряд (см. :func:`split_counts`).

**Длинные работы** (лонгрид, инфографика — вытянутые вниз сильнее чем 1:3.4) в
обычные места не помещаются: от картинки 1:10 в почти квадратном месте остаётся
случайная полоса. У них свои композиции (:data:`LONG_MODULES`) — тот же почерк:
перекрытие, разные размеры, вертикальный сдвиг, — но каждое место ровно 1:3.4.
Именно на этой высоте работа и обрезается, дальше идёт размытие (`showcase.html`).
Порядок работ при этом сохраняется: подряд идущие длинные собираются в свою
композицию, подряд идущие обычные — в свою.
"""

from dataclasses import dataclass

MAX_MODULE = 7
# длинных мест в одной композиции: пятая колонка была бы уже нечитаемо узкой
MAX_LONG_MODULE = 4

# С какой вытянутости работа уходит в длинную композицию. Совпадает с высотой
# места (1:3.4) — работа считается длинной ровно тогда, когда в него не влезает.
TALL_RATIO = 3.4


@dataclass(frozen=True)
class Tile:
    """Место под одну работу внутри модуля (проценты рамки)."""

    x: float
    y: float
    w: float
    h: float
    z: int


# ratio = ширина / высота рамки модуля.
# Порядок плиток = порядок работ на доске (его задаёт менеджер перетаскиванием).
MODULES: dict[int, tuple[float, tuple[Tile, ...]]] = {
    # одна работа — крупный кадр во всю ширину, без пустого пространства вокруг
    1: (1.60, (
        Tile(0, 0, 100, 100, 1),
    )),
    # две — вертикальная слева, крупная горизонтальная справа поверх неё
    2: (1.50, (
        Tile(0, 14, 42, 86, 1),
        Tile(34, 0, 66, 88, 2),
    )),
    # три — левая вертикальная, крупная сверху по центру, средняя справа снизу
    3: (1.45, (
        Tile(0, 10, 30, 62, 1),
        Tile(24, 0, 52, 74, 2),
        Tile(64, 44, 36, 56, 3),
    )),
    # четыре — «вертушка»: узкая слева, крупная сверху, широкая справа, высокая снизу
    4: (1.08, (
        Tile(0, 8, 26, 42, 1),
        Tile(20, 0, 50, 50, 3),
        Tile(64, 18, 36, 30, 2),
        Tile(26, 44, 38, 56, 4),
    )),
    # пять — та же вертушка + нижняя левая; правый нижний угол намеренно пуст
    5: (0.98, (
        Tile(0, 6, 25, 36, 1),
        Tile(19, 0, 48, 44, 3),
        Tile(62, 16, 38, 26, 2),
        Tile(25, 38, 36, 48, 4),
        Tile(0, 58, 28, 42, 2),
    )),
    # шесть — правый нижний угол закрывается крупной плиткой
    6: (0.95, (
        Tile(0, 6, 25, 34, 1),
        Tile(19, 0, 48, 42, 4),
        Tile(62, 15, 38, 25, 2),
        Tile(25, 36, 34, 44, 5),
        Tile(0, 54, 27, 38, 2),
        Tile(55, 52, 45, 48, 3),
    )),
    # семь — самая плотная композиция, замыкающая плитка по центру снизу
    7: (0.92, (
        Tile(0, 5, 24, 32, 1),
        Tile(18, 0, 46, 40, 4),
        Tile(60, 14, 40, 24, 2),
        Tile(24, 34, 32, 40, 5),
        Tile(0, 48, 26, 34, 2),
        Tile(53, 46, 42, 34, 3),
        Tile(30, 70, 30, 30, 6),
    )),
}


# Композиции для длинных работ. Высота каждого места подобрана так, чтобы оно
# было ровно 1:3.4: h = 3.4 · w · ratio (проверяется тестом). Отсюда и дробные
# значения — их нельзя «округлить для красоты», не сломав пропорцию.
LONG_MODULES: dict[int, tuple[float, tuple[Tile, ...]]] = {
    # одна — колонка во всю рамку; ширину рамке задаёт потолок высоты (150vh)
    1: (0.2941, (
        Tile(0, 0, 100, 100, 1),
    )),
    # две — левая чуть выше, правая шире и опущена; перекрываются серединой
    2: (0.50, (
        Tile(0, 0, 52, 88.4, 1),
        Tile(44, 4.8, 56, 95.2, 2),
    )),
    # три — центральная самая крупная и поднята, боковые опущены на разную высоту
    3: (0.75, (
        Tile(0, 3.1, 34, 86.7, 1),
        Tile(30, 0, 38, 96.9, 3),
        Tile(64, 8.2, 36, 91.8, 2),
    )),
    # четыре — «волна»: каждая следующая колонка ниже предыдущей, последняя шире
    4: (0.62, (
        Tile(0, 0, 25, 52.7, 1),
        Tile(22, 19.9, 27, 56.9, 3),
        Tile(46, 8.1, 26, 54.8, 2),
        Tile(70, 36.8, 30, 63.2, 4),
    )),
}


def split_counts(total: int) -> list[int]:
    """Разбивает работы на модули по 1–7 штук.

    Остаток в одну-две работы выглядел бы обрывком страницы, поэтому такой
    хвост добирается из предыдущего модуля: 8 → 4+4, 9 → 5+4, 15 → 7+4+4.
    """
    if total <= 0:
        return []
    if total <= MAX_MODULE:
        return [total]

    chunks: list[int] = []
    rest = total
    while rest > MAX_MODULE:
        chunks.append(MAX_MODULE)
        rest -= MAX_MODULE
    if rest == 0:
        return chunks
    if rest >= 3:
        chunks.append(rest)
        return chunks

    merged = chunks.pop() + rest
    chunks.append(merged - merged // 2)
    chunks.append(merged // 2)
    return chunks


def split_long_counts(total: int) -> list[int]:
    """Разбивает длинные работы на композиции по 1–4.

    Одна длинная работа — законная композиция (высокая колонка), поэтому хвост
    добирается только из единицы: 5 → 3+2, 9 → 4+3+2.
    """
    if total <= 0:
        return []
    if total <= MAX_LONG_MODULE:
        return [total]

    chunks: list[int] = []
    rest = total
    while rest > MAX_LONG_MODULE:
        chunks.append(MAX_LONG_MODULE)
        rest -= MAX_LONG_MODULE
    if rest == 0:
        return chunks
    if rest >= 2:
        chunks.append(rest)
        return chunks

    merged = chunks.pop() + rest
    chunks.append(merged - merged // 2)
    chunks.append(merged // 2)
    return chunks


def long_indexes(works: list[dict]) -> set[int]:
    """Номера работ, которые не помещаются в обычное место композиции."""
    return {
        index
        for index, work in enumerate(works)
        if work.get("kind") == "image"
        and work.get("width")
        and work.get("height")
        and work["height"] >= work["width"] * TALL_RATIO
    }


def build_modules(count: int, longs: set[int] | None = None) -> list[dict]:
    """Готовая раскладка для шаблона: список модулей с плитками по порядку работ.

    Каждая вторая композиция отражается по горизонтали — на длинной доске
    одинаковые модули подряд читались бы как повтор шаблона.

    Работы из `longs` собираются в свои композиции (:data:`LONG_MODULES`), но
    порядок не нарушается: доска читается сверху вниз ровно так, как её собрал
    менеджер.
    """
    tall = {index for index in (longs or set()) if 0 <= index < count}
    modules: list[dict] = []
    position = 0  # номер композиции подряд: каждая вторая отражается

    def place(table: dict, first: int, size: int, long: bool) -> None:
        nonlocal position
        ratio, tiles = table[size]
        mirrored = position % 2 == 1
        modules.append(
            {
                "ratio": ratio,
                "long": long,
                "tiles": [
                    {
                        "index": first + offset,
                        "x": round(100 - tile.x - tile.w, 2) if mirrored else tile.x,
                        "y": tile.y,
                        "w": tile.w,
                        "h": tile.h,
                        "z": tile.z,
                    }
                    for offset, tile in enumerate(tiles)
                ],
            }
        )
        position += 1

    start = 0
    while start < count:
        long = start in tall
        end = start
        while end < count and (end in tall) == long:
            end += 1
        table = LONG_MODULES if long else MODULES
        split = split_long_counts if long else split_counts
        cursor = start
        for size in split(end - start):
            place(table, cursor, size, long)
            cursor += size
        start = end
    return modules
