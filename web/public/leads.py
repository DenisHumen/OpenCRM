"""Приём заявки с сайта — единственная пишущая ручка, открытая наружу.

Сессии здесь нет и быть не может: запрос шлёт сайт, а не браузер сотрудника.
Значит всё, что обычно делают права и вход, приходится делать здесь:

* **ключ приёма** — кто вообще имеет право сюда писать
  (`lead_service.check_intake_key`; там же о том, почему ключ, а не подпись);
* **ограничитель по адресу** — сколько раз с одного места можно постучаться;
* **ловушка в форме** — отсеивает ботов, заполняющих всё подряд (внутри
  сервиса: правило про данные, а не про транспорт);
* **потолок тела** — стоит выше нас, в `web/middleware.py`, и работает по
  заголовку `Content-Length`, то есть ДО чтения тела. Сюда огромный запрос
  просто не доходит.

**Ручка живёт под `/api/`, хотя лежит в `web/public/`.** Так задумано: под этим
префиксом режим обслуживания отвечает JSON'ом, а не HTML-заглушкой (сайту,
который шлёт заявку с сервера, страница с картинкой бесполезна), и catch-all
SPA сюда не заглядывает. Слово `public` в самом адресе — обещание: сессии здесь
не спрашивают и никогда не будут.

**Заявку шлёт сервер сайта, а не страница в браузере.** Причин две, и обе
жёсткие: ключ, вставленный в HTML, знает каждый посетитель; а `Content-Type`,
отличный от JSON, проходит мимо потолка тела. Поэтому принимаем только JSON.
"""

from fastapi import APIRouter, Depends, Request
from pydantic import BaseModel
from sqlalchemy.orm import Session

from core import exceptions as errors
from core.ratelimit import SlidingWindowLimiter
from core.security import tokens
from core.services import lead_service
from web.api.deps import client_ip, get_db

# Полный префикс, а не кусок: роутер подключается одной строкой и не зависит от
# того, что у соседей за переменная `api_prefix`.
router = APIRouter(prefix="/api/v1/public", tags=["public"])

#: Сколько раз с одного адреса можно прислать заявку.
#:
#: Считаем ВСЕ обращения, а не одни отказы, — ровно как страница состояния
#: заказа (`web/api/deps.DOCUMENT_STATUS_MAX_LOOKUPS`). Считай мы промахи, поток
#: с верным ключом не ограничивался бы вовсе, а это и есть самый дорогой случай:
#: каждая такая заявка пишет в базу.
#:
#: Тридцать за десять минут выбраны по обеим сторонам. Живой человек шлёт форму
#: один раз, ну два. Сервер сайта шлёт со своего адреса заявки ВСЕХ посетителей
#: сразу — и три обращения в минуту это уже очень бойкий сайт для малого дела.
#: Кто перерастёт этот потолок, упрётся в него заметно (429 с внятным кодом), а
#: не молча.
LEAD_MAX_PER_IP = 30
LEAD_WINDOW_SECONDS = 600
lead_limiter = SlidingWindowLimiter(LEAD_MAX_PER_IP, LEAD_WINDOW_SECONDS, name="lead")


class LeadIn(BaseModel):
    """Поля формы.

    Потолков длины здесь нет намеренно — их ставит сервис, и ставит по-разному:
    имя и текст обрезает, адрес и номер отвергает (обрезанный адрес это другой
    адрес). Продублируй мы их тут, два места разошлись бы, и человек получал бы
    отказ вместо принятой заявки. Сверху всё это накрыто потолком тела.

    Состав полей назван ещё и в сервисе (`lead_service.INTAKE_FIELDS` и
    `HONEYPOT_FIELD`): по нему экран настроек рисует готовый пример запроса для
    того, кто пишет форму на сайте. Два места держит сторож
    (`tests/test_leads.py`) — разойдись они молча, и в интерфейсе висела бы
    инструкция, по которой форма не работает.
    """

    name: str = ""
    email: str = ""
    phone: str = ""
    message: str = ""
    #: Ловушка. В форме поле скрыто стилями: человек его не видит, бот —
    #: заполняет. Разбор — в `lead_service.receive`.
    website: str = ""


@router.post("/leads", status_code=202)
def submit_lead(payload: LeadIn, request: Request, db: Session = Depends(get_db)):
    """Принять заявку с сайта.

    **Ответ всегда один и тот же.** Ни идентификатора клиента, ни номера
    заявки, ни слова о том, завели карточку или узнали своего. Причин две.
    Первая: ловушка обязана выглядеть как успех, иначе бот за десяток попыток
    поймёт, какое поле его выдаёт. Вторая: по разнице ответов «завели» и
    «узнали» кто угодно проверял бы наличие адреса в базе — то есть форма стала
    бы способом узнать, ваш ли клиент такой-то человек.

    Порядок проверок: сначала поток, потом ключ. Обратный означал бы, что
    подбирающий ключ не считается вовсе.
    """
    # Ключ ограничителя — хэш адреса, а не сам адрес: список ключей наполняется
    # с улицы и живёт в памяти процесса, а адрес посетителя это персональные
    # данные (так же сделано у вебхука АТС).
    visitor = tokens.hash_ip(client_ip(request))
    # Проверка и отметка — одной операцией. Двумя между ними оставалось окно:
    # пачка одновременных обращений проходила порог целиком, а форма открыта в
    # интернет, и шлют в неё именно пачками.
    if lead_limiter.proverit_i_zanyat(visitor):
        raise errors.RateLimitedError(
            "Too many requests from this address", code="lead_rate_limited"
        )

    lead_service.check_intake_key(db, request.headers.get(lead_service.INTAKE_KEY_HEADER, ""))
    lead_service.receive(db, payload.model_dump())
    return {"status": "accepted"}
