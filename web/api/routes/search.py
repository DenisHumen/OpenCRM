from typing import Callable

from fastapi import APIRouter, Depends, Query
from sqlalchemy.orm import Session

from core import exceptions as errors
from core import permissions
from core.services import modules_service, permissions_service
from database.models import User
from database.repositories import boards as boards_repo
from database.repositories import clients as clients_repo
from database.repositories import deals as deals_repo
from web.api import cards, schemas
from web.api.deps import MAX_SEARCH, get_db, require_staff

router = APIRouter(prefix="/search", tags=["search"])

#: Сколько строк в ОДНОЙ странице группы.
#:
#: Это размер страницы, а не потолок выдачи. Раньше он был потолком, и стоил
#: беды: на «be» палитра показывала ровно шесть досок, а досок было больше —
#: седьмую нельзя было увидеть ничем. Ни прокрутки, ни «показать ещё», ни
#: продолжения в API не было вовсе, и цифра «6» была последним словом системы.
#:
#: Поднимать её было бы той же бедой через год — с числом побольше. Поэтому
#: заведено продолжение (`GET /search/{area}?page=`), а шестёрка осталась ровно
#: тем, чем и была: сколько строк палитра показывает СРАЗУ, чтобы открываться
#: короткой и быстрой.
#:
#: Размер один и для первой страницы, и для продолжения — намеренно. Смещение
#: считается как `(page - 1) * per_page`, и две разные величины на одной выдаче
#: означали бы, что часть строк пропускается или приезжает дважды, в зависимости
#: от того, какой страницей их спросили. Клиент про этот размер не знает вовсе:
#: он просит следующий НОМЕР страницы, а сколько в ней строк — дело сервера.
GROUP_LIMIT = 6

EMPTY = {"items": [], "total": 0, "has_more": False}


def _clients_group(db: Session, user: User, query: str | None, page: int) -> dict:
    found, has_more = clients_repo.search_top(
        db, q=query, page=page, per_page=GROUP_LIMIT
    )
    return {
        "items": [schemas.client_out(c) for c in found],
        "total": len(found),
        "has_more": has_more,
    }


def _deals_group(db: Session, user: User, query: str | None, page: int) -> dict:
    """Заявки — стержень системы, и в палитре их ищут чаще всего остального.

    Сужение приходит из прав, а не из запроса: у кого нет `deals.view_others`,
    тот и здесь находит только свои. Это не повтор проверки со списка заявок, а
    её обязательная вторая половина — поиск иначе становится самым удобным
    способом обойти ограничение: список показывает три карточки, а Ctrl+K по
    тому же слову — все тридцать, вместе с именами чужих клиентов.

    Суммы прячет то же право (`deals.view_amounts`), что и в карточке. Иначе
    цену работы можно было бы прочесть прямо из выдачи, не открывая заявку, —
    то есть запрет закрывал бы экран, а не деньги.
    """
    found, has_more = deals_repo.search_top(
        db,
        q=query,
        page=page,
        per_page=GROUP_LIMIT,
        only_manager_id=permissions_service.deals_scope(db, user),
    )
    # Имя клиента — одним запросом на всю группу, как в списке заявок. Палитра
    # подписывает им строку: две «Доставки» разных заказчиков иначе не различить.
    names = clients_repo.names_by_ids(db, [deal.client_id for deal in found])
    amounts = permissions_service.sees_amounts(db, user)
    return {
        "items": [
            # Ответственного не спрашиваем: палитра его не показывает, а ради
            # одного поля это ещё один запрос на каждую выдачу.
            schemas.deal_out(deal, names.get(deal.client_id), amounts=amounts)
            for deal in found
        ],
        "total": len(found),
        "has_more": has_more,
    }


def _boards_group(db: Session, user: User, query: str | None, page: int) -> dict:
    boards, has_more = boards_repo.search_top(
        db, q=query, page=page, per_page=GROUP_LIMIT
    )
    # Клиент нужен и здесь: палитра подписывает им доску, и без подписи две
    # «Витрины» разных заказчиков в списке не различить.
    return {
        "items": cards.board_cards(db, boards, with_client=True),
        "total": len(boards),
        "has_more": has_more,
    }


#: Чем собирается каждая группа. Один список на оба входа — общий поиск и
#: продолжение отдельной группы.
#:
#: Реестром, а не перечислением по месту: продолжение обязано собирать строку
#: ровно так же, как первая страница. Разъедься эти двое — и «показать ещё»
#: дописывало бы к выдаче карточки другого вида: без имени клиента у заявки, с
#: суммой у того, кому её видеть нельзя. Заметить это можно было бы только
#: глазами и только на второй странице.
#:
#: Подпись у всех одна, поэтому `user` берут и те группы, которым он не нужен.
#: Своя подпись у каждой означала бы разбор по месту вызова — то есть ровно то
#: перечисление групп руками, от которого реестр и избавляет.
#:
#: Порядок здесь тот же, что в левой колонке: клиенты, заявки, доски.
BUILDERS: dict[str, Callable[[Session, User, str | None, int], dict]] = {
    "clients": _clients_group,
    "deals": _deals_group,
    "boards": _boards_group,
}


def _group(db: Session, user: User, area: str, build: Callable[[], dict]) -> dict:
    """Группа выдачи — или пустота, если её этому сотруднику видеть не положено.

    Порядок проверок тот же, что в `require_perm`: сначала блок, потом право.

    Блок берётся из реестра прав, а не выписывается рядом с каждой группой.
    Список, набранный руками, разошёлся бы с реестром на первом же новом
    разделе — и разошёлся бы молча: лишняя группа в поиске ничем себя не
    выдаёт, она просто продолжает находить то, чего в системе больше нет.
    У несущих блоков (клиенты, заявки) проверка истинна всегда, и это не повод
    делать их исключением: исключение и есть то место, про которое забудут.
    """
    module = permissions.module_of(area)
    if module is not None and not modules_service.is_enabled(db, module):
        return EMPTY
    if not permissions_service.has(db, user, area, permissions.VIEW):
        return EMPTY
    return build()


@router.get("")
def global_search(
    q: str = Query(default="", max_length=MAX_SEARCH),
    user: User = Depends(require_staff),
    db: Session = Depends(get_db),
):
    """Общий поиск для командной палитры (Ctrl+K).

    Пустой запрос — недавние записи, чтобы палитра открывалась не пустой.

    Группа приходит пустой, а не отсутствует: форма ответа одна при любом наборе
    блоков и прав, и клиенту не приходится знать, какие ключи сегодня бывают.

    Пустеет она по двум причинам, и обе обязательны. Выключенный блок — иначе
    доски продолжали бы находиться поиском и уводить в раздел, которого нет ни в
    меню, ни в маршрутах. Отсутствие права — по той же причине и с добавкой:
    поиск иначе стал бы обходом доступов, через который видно имена и названия
    записей из закрытого раздела. Обе проверки собраны в `_group`.

    Номера страницы здесь по-прежнему нет, и это не отказ от продолжения выдачи,
    а разделение обязанностей. Этот вход отвечает на вопрос «что вообще нашлось»
    и отдаёт по первой странице каждой группы разом. Продолжение — вопрос про
    ОДНУ группу («доски кончились, а клиенты нет»), и живёт оно в
    `search_group`. Сложи их в один вход — и один `page` пришлось бы прикладывать
    ко всем трём группам сразу: страница вторая у досок, у которых нашлось
    двадцать, и она же у клиентов, у которых нашлось два, то есть пустота вместо
    уже показанного. Раздельно у каждой группы свой счёт, и кончаются они
    независимо.

    **Точного числа найденного здесь больше нет и не будет.** `total` — это
    длина показанного (не больше `GROUP_LIMIT`), а «есть ли ещё» отвечает
    `has_more`. Точный счёт означал второй полный проход по таблице на каждую
    группу и стоил ровно столько же, сколько сама выборка: на 400 000 заявок
    3128 мс против 3165 мс — то есть секунды на число, которое клиент выбрасывал
    не глядя. Полноту выдачи это не ограничивает: листается она по `has_more`, а
    не по остатку от `total`, и лишнего прохода по таблице не стоит.
    Точный `total` живёт на экранах разделов — там из него считается номер
    последней страницы.
    """
    query = q.strip() or None
    # Группы перебираются по реестру, а не выписываются здесь ещё раз: список,
    # набранный по месту, разошёлся бы с `BUILDERS` на первом же новом разделе —
    # и разошёлся бы молча. Порядок в реестре тот же, что в левой колонке.
    #
    # `build=build` — не украшение: `_group` зовёт переданное позже, уже после
    # обхода, и замыкание без этого поймало бы последнюю группу цикла. Тогда все
    # три группы собирались бы досками, причём молча.
    found = {
        area: _group(db, user, area, lambda build=build: build(db, user, query, 1))
        for area, build in BUILDERS.items()
    }
    return {"query": q, **found}


@router.get("/{area}")
def search_group(
    area: str,
    q: str = Query(default="", max_length=MAX_SEARCH),
    page: int = Query(default=1, ge=1),
    user: User = Depends(require_staff),
    db: Session = Depends(get_db),
):
    """Продолжение ОДНОЙ группы выдачи — то самое «показать ещё».

    Заведён по беде: палитра показывала шесть находок и на этом заканчивалась.
    Досок под «be» было больше шести, а достать седьмую было нечем — ни
    прокруткой, ни страницей, ни отдельным запросом. Сервер при этом честно
    отвечал `has_more: true`, но продолжения, которое можно попросить, не
    существовало.

    Отвечает ровно той же формой, что группа в общем поиске (`items`, `total`,
    `has_more`), — клиент дописывает `items` к уже показанным и смотрит на
    `has_more`, чтобы решить, оставлять ли «показать ещё».

    Собирает строку тот же `BUILDERS`, что и первую страницу. Это не экономия
    строк: вторая страница, собранная своими руками, разошлась бы с первой в
    мелочах — у заявки пропало бы имя клиента, а сумма приехала бы тому, кому её
    видеть нельзя, — и заметить это можно было бы только глазами и только
    долистав.

    Проверки — те же и в том же порядке: сначала блок, потом право (`_group`).
    Второй вход в те же данные обязан быть закрыт ровно так же, как первый,
    иначе он и есть обход: закрытый раздел не отдаёт первую страницу, но охотно
    отдаёт вторую.

    Неизвестная область — 404, а не пустая группа. Пустота означала бы «такое
    есть, но ничего не нашлось», и опечатка в имени группы выглядела бы как
    работающий поиск без находок.

    `page` сторожится здесь (`ge=1`), а не в `database/query.py`: нулевая
    страница дала бы `OFFSET -6`, а это для MySQL синтаксическая ошибка, то есть
    пятисотка. Общий слой её тоже не пропускает (`offset_for` не бывает
    отрицательным), но отказ на границе понятнее молчаливого показа первой
    страницы вместо запрошенной.
    """
    build = BUILDERS.get(area)
    if build is None:
        raise errors.NotFoundError("Unknown search group", code="search_group_not_found")
    query = q.strip() or None
    return _group(db, user, area, lambda: build(db, user, query, page))
