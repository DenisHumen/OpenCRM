const dicts: Record<Locale, typeof en> = { en, ru };

export type TFunc = (key: keyof typeof en, vars?: Record<string, string | number>) => string;

export function makeT(locale: Locale): TFunc {
  const dict = dicts[locale] ?? en;
  return (key, vars) => {
    let value: string = dict[key] ?? en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) value = value.replace(`{${k}}`, String(v));
    }
    return value;
  };
}
