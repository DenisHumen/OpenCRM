import { useEffect, useState } from "react";

/**
 * Пауза перед тем, как отправить набранное на сервер.
 *
 * 250 мс — это примерно интервал между буквами при обычном наборе. Меньше — и
 * каждая буква уходит отдельным запросом; больше — и человек успевает решить,
 * что поиск не работает.
 */
export const SEARCH_DELAY = 250;

/**
 * Пауза палитры (Ctrl+K) — короче обычной.
 *
 * В палитру приходят за одним конкретным делом и набирают две-три буквы, глядя
 * на выпадающий список; четверть секунды здесь ощущается заминкой. Список к
 * тому же короткий, и запрос дешевле, чем у экрана со всей таблицей.
 */
export const PALETTE_DELAY = 180;

/**
 * Значение, отстающее от набора на паузу.
 *
 * Половина экранов ждала паузу собственным таймером, половина — не ждала вовсе
 * и слала запрос на каждую букву: «Иванов» — шесть запросов к журналу, из них
 * пять никому не нужны. Разница была не решением, а следом того, что экраны
 * писались в разное время.
 *
 * Крючок возвращает значение, а не берёт на себя загрузку: экраны грузятся
 * по-разному — один аргументом, другой парой, третий вместе с фильтром, — и
 * общей у них ровно эта пауза. Всё, что сверх неё, лучше оставить на месте,
 * чем прятать за общим интерфейсом, в который каждый следующий экран не влезет.
 */
export function useDebounced<T>(value: T, delay: number = SEARCH_DELAY): T {
  const [delayed, setDelayed] = useState(value);

  useEffect(() => {
    const timer = window.setTimeout(() => setDelayed(value), delay);
    return () => window.clearTimeout(timer);
  }, [value, delay]);

  return delayed;
}
