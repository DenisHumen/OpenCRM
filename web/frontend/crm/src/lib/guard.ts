import { useCallback, useRef, useState } from "react";

/** Засов: занят ли он сейчас, как его взять и как отпустить. */
export interface Guard {
  /** Для `disabled` на кнопке — то, что видит человек. */
  busy: boolean;
  /** `true` — засов взят этим нажатием; `false` — действие уже идёт. */
  take: () => boolean;
  free: () => void;
}

/**
 * Засов на действие, которое уходит к серверу и заводит запись.
 *
 * Одного состояния React для этого мало, и это проверено нажатием: три вызова
 * подряд в одном тике завели три заявки. `setBusy(true)` меняет значение
 * только к следующему рендеру, а обработчик каждого нажатия читает `busy` из
 * своего замыкания — то есть все трое видят `false`. Человек так жмёт редко,
 * зато сканер, залипшая кнопка мыши и Enter, зажатый на автоповторе, — как раз
 * так.
 *
 * Поэтому решает ref: он меняется в тот же миг. Состояние остаётся рядом
 * только ради `disabled` на кнопке — засов и отклик кнопки это разные вещи, и
 * держать их одним значением значит выбирать между «не сработает» и «не видно».
 *
 * Отпускать нужно только там, где экран остаётся на месте: если после успеха
 * уходят в созданную запись, отпускать засов не у чего и незачем.
 */
export function useGuard(): Guard {
  const held = useRef(false);
  const [busy, setBusy] = useState(false);

  const take = useCallback(() => {
    if (held.current) return false;
    held.current = true;
    setBusy(true);
    return true;
  }, []);

  const free = useCallback(() => {
    held.current = false;
    setBusy(false);
  }, []);

  return { busy, take, free };
}
