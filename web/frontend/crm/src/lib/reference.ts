import { useCallback, useEffect, useState } from "react";

import { api } from "./api";

/** Справочник: список, которым заполняют выпадающий список или врезку. */
export interface Reference<T> {
  /** `null` — ответа ещё нет либо он не пришёл. Пустой массив — «записей нет». */
  items: T[] | null;
  /** Чем сервер отказал. `null` — идёт загрузка или всё удалось. */
  failure: unknown;
  reload: () => void;
}

/**
 * Список для выпадающего списка или врезки: клиенты формы, этапы воронки,
 * должности, бланки заявки.
 *
 * Крючок заведён ради одного различия, которое эти списки теряли все до
 * единого: `[]` означает «записей нет», а отказ сервера не означает ничего.
 * Пока и то и другое сводилось к пустому массиву в `catch(() => undefined)`,
 * экран отвечал на вопрос, которого ему не задавали:
 *
 * - окно новой заявки на упавшем сервере советовало «сначала заведите
 *   клиента» — там, где клиентов двести;
 * - список должностей в карточке сотрудника рисовался из одного пункта «Без
 *   роли», и выбор единственного пункта СНИМАЛ должность по-настоящему;
 * - «что дальше» в заявке оставалось без единой кнопки этапа.
 *
 * Поэтому `items` держится `null`, пока ответа нет, а отказ живёт отдельным
 * полем. Решает вызывающий: показать строку «не загрузилось» с повтором
 * (`LoadFailed`) или просто не рисовать то, чего не знает.
 *
 * Всплывающей подсказки здесь нет намеренно — в отличие от `useFailure`. На
 * одной карточке таких списков до шести, и упавший сервер выдал бы шесть
 * подсказок подряд, из которых не следует ни что случилось, ни где.
 *
 * `path === null` — «спрашивать нечего»: блок выключен или права нет. Это не
 * отказ, и строки об отказе быть не должно.
 *
 * Ответ на прошлый запрос не ложится поверх нового — тем же приёмом, что в
 * отчётах, палитре команд и врезке склада.
 */
export function useReference<T>(path: string | null): Reference<T> {
  const [items, setItems] = useState<T[] | null>(null);
  const [failure, setFailure] = useState<unknown>(null);
  const [attempt, setAttempt] = useState(0);

  useEffect(() => {
    if (path === null) {
      setItems(null);
      setFailure(null);
      return;
    }
    let current = true;
    setFailure(null);
    api
      .get<{ items: T[] }>(path)
      .then((data) => {
        if (current) setItems(data.items);
      })
      .catch((e) => {
        if (current) setFailure(e);
      });
    return () => {
      current = false;
    };
  }, [path, attempt]);

  const reload = useCallback(() => setAttempt((n) => n + 1), []);

  return { items, failure, reload };
}
