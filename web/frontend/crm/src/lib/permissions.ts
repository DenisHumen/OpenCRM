/** Права сотрудника во фронтенде.
 *
 * Здесь только «что показывать». Настоящая проверка стоит в API
 * (`web/api/deps.py`, `require_perm`), и порядок именно такой: интерфейс прячет
 * то, что всё равно получит отказ, а не заменяет собой запрет. Спрятанная
 * кнопка — удобство; закрытый адрес — защита.
 */

import type { User } from "./api";
import { type Gated, moduleOn } from "./modules";

/** Элемент интерфейса, требующий права. Без `perm` — доступен всем. */
export interface Guarded extends Gated {
  perm?: string;
}

/**
 * Есть ли у сотрудника право.
 *
 * Два особых случая, и оба намеренные.
 *
 * Root — всегда да: он не описывается набором прав, и спрашивать у сервера
 * список из полусотни строк, чтобы узнать это, незачем.
 *
 * Набор ещё не приехал (`permissions` не задан) — тоже да. Ровно та же логика,
 * что у `moduleOn`: спрятать в этот момент всё значит показать человеку пустую
 * CRM и оставить гадать, что сломалось. Лишняя кнопка безопаснее — сервер
 * ответит отказом сам. Обратный порядок оставил бы сотрудника перед экраном без
 * единого раздела.
 */
export function can(user: User | null, code: string): boolean {
  if (!user) return false;
  if (user.role === "root") return true;
  if (!user.permissions) return true;
  return user.permissions.includes(code);
}

/** Хотя бы одно из прав. Для разделов, куда ведёт несколько дорог. */
export function canAny(user: User | null, ...codes: string[]): boolean {
  return codes.some((code) => can(user, code));
}

/**
 * Что из списка показывать: пункты выключенных блоков и недоступных прав уходят.
 *
 * Продолжение `shown` из `lib/modules.ts`, а не второй его экземпляр: правило
 * «не показываем то, чего человек всё равно не получит» одно, а мест применения
 * много — меню, настройки, вкладки, командная строка. Пока каждое место
 * расставляло условия по разметке, правило существовало в стольких же
 * экземплярах, и новый раздел забывали закрыть ровно в одном из них.
 *
 * Порядок проверок тот же, что на сервере: сначала блок, потом право. Так пункт
 * выключенного блока исчезает независимо от того, кому какие права выданы.
 */
export function allowed<T extends Guarded>(
  user: User | null,
  modules: Record<string, boolean> | null,
  items: T[],
): T[] {
  return items.filter(
    (item) =>
      (item.module === undefined || moduleOn(modules, item.module)) &&
      (item.perm === undefined || can(user, item.perm)),
  );
}
