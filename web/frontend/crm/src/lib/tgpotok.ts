/**
 * Поток событий мессенджера — одно соединение на вкладку.
 *
 * **Зачем понадобился общий, а не свой у экрана.** Уведомление о письме клиента
 * нужно менеджеру, который сидит в заявках, а не в переписке: тот, кто смотрит
 * в мессенджер, и так всё видит. Значит слушать поток обязана оболочка
 * приложения, а не экран.
 *
 * Но и экрану события нужны — свои, для ленты. Два `EventSource` на одну
 * вкладку означали бы два соединения, два переподключения и два обработчика
 * одного события; на сервере — вдвое больше живых генераторов.
 *
 * Отсюда один источник на модуль и подписчики поверх него. Соединение
 * открывается на первом подписчике и закрывается на последнем: приложение без
 * доступа к мессенджеру не держит соединения вовсе.
 */

export interface SobytieTg {
  type: string;
  chat_id?: number;
  message_id?: number;
  direction?: "in" | "out";
  preview?: string;
  title?: string;
  watchers?: { user_id: number; name: string }[];
}

type Slushatel = (sobytie: SobytieTg) => void;

const slushateli = new Set<Slushatel>();
let istochnik: EventSource | null = null;

/**
 * Поднять соединение заново после того, как браузер его похоронил.
 *
 * Отдельной функцией, потому что зовётся и из обработчика ошибки, и косвенно из
 * `podpisatsya`: слушатели остались, а источника нет.
 */
function vosstanovit(): void {
  if (istochnik !== null || slushateli.size === 0) return;
  const kto_to = [...slushateli][0];
  // Приём тот же, что при первой подписке: `podpisatsya` сама заводит источник,
  // если его нет. Добавляем и тут же убираем — набор слушателей не меняется, а
  // источник появляется.
  const snyat = podpisatsya(kto_to);
  snyat();
}

/**
 * Подписаться на события. Возвращает отписку.
 *
 * Отписка обязательна: без неё соединение живёт после ухода с экрана, а список
 * слушателей растёт на каждом перерисовывании.
 */
export function podpisatsya(slushatel: Slushatel): () => void {
  slushateli.add(slushatel);
  if (istochnik === null) {
    istochnik = new EventSource("/api/v1/telegram/stream");
    istochnik.onmessage = (sobytie) => {
      let dannye: SobytieTg;
      try {
        dannye = JSON.parse(sobytie.data);
      } catch {
        return;
      }
      // Копией, а не самим набором: слушатель вправе отписаться прямо в
      // обработчике, а изменение набора во время обхода — это пропущенный
      // сосед.
      for (const kto of [...slushateli]) {
        try {
          kto(dannye);
        } catch {
          // Упавший слушатель не должен лишать событий остальных.
        }
      }
    };
    istochnik.onerror = () => {
      // Ошибку не показываем: моргание сети `EventSource` переживает сам, а
      // всплывающее окно на каждое такое моргание превратило бы работу в поток
      // жалоб.
      //
      // Но сам он переподключается НЕ ВСЕГДА. Сеть моргнула — переподключится;
      // а вот ответ не тем кодом или не тем типом содержимого (перезапуск
      // приложения отдал страницу вместо потока, посредник вернул 502, режим
      // обслуживания ответил 503) закрывает соединение НАСМЕРТЬ: `readyState`
      // становится `CLOSED`, и браузер больше не пробует.
      //
      // Молча это означает мессенджер, который перестал быть живым: лента
      // замерла, уведомления не приходят, и понять это можно только по тишине.
      // Раньше лечилось перезагрузкой страницы, о которой надо догадаться.
      if (istochnik?.readyState === EventSource.CLOSED) {
        istochnik = null;
        // Ждём, а не бросаемся заново: приложение обычно перезапускается
        // секунды, и очередь мгновенных попыток легла бы на него в самый
        // неудачный момент. Пять секунд — примерно столько живёт перезапуск
        // контейнера.
        if (slushateli.size > 0) setTimeout(vosstanovit, 5000);
      }
    };
  }
  return () => {
    slushateli.delete(slushatel);
    if (slushateli.size === 0 && istochnik !== null) {
      istochnik.close();
      istochnik = null;
    }
  };
}
