"""Вставка строки, у которой есть уникальное поле.

Между «проверили, что такого ещё нет» и «вставили» всегда есть окно, и попадают
в него не злоумышленники, а обычная жизнь: двое приёмщиков у стойки, двойное
нажатие на кнопку, две вкладки с одной формой. Уникальный индекс данные спасает
— двух одинаковых строк не появляется, — но проигравший получает 500, то есть
видит поломку там, где система отработала правильно.

Приём один и тот же, и до этого модуля он был выписан руками в четырёх местах
(бланки, регистрация, роли, артикул склада), каждый раз чуть по-своему. Здесь
он один, и различаются вызовы ровно тем, чем должны: **что значит «проиграл»**.

- `insert_unique` — проигравший узнаёт, что занято. Так с адресом почты,
  названием роли, артикулом: второй такой записи и не должно быть.
- `insert_retrying` — проигравший берёт следующее свободное значение. Так с
  номером бланка: бумаги разные, спор идёт не о них, а о номере.

Взять чужую строку (третий возможный ответ) умеет телефония: событие про один и
тот же звонок приходит дважды, и проигравшему нужна именно та строка, которую
вставил победитель. Сюда это не вынесено — там нужен поиск по своему ключу, а
общего вида у такого поиска нет.

**Чужое нарушение не выдаём за своё.** База отвечает одним и тем же
`IntegrityError` и на занятый артикул, и на потерянный `NOT NULL`, и на ссылку
в никуда. Превращать в «такое имя уже есть» всё подряд — значит однажды отдать
человеку это сообщение вместо настоящей ошибки, и искать её начнут не там.
Поэтому вызывающий обязан сказать, чем именно занято место: если после отказа
занятого не нашлось, ошибка идёт наверх как есть.
"""

from typing import Callable, TypeVar

from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from core import exceptions as errors

Row = TypeVar("Row")

#: Сколько раз пробуем подобрать свободное значение.
#:
#: Три, а не «пока не выйдет»: если не даётся трижды подряд, дело уже не в
#: соседе у стойки, и крутить цикл дальше — прятать настоящую причину.
DEFAULT_ATTEMPTS = 3


def insert_unique(
    db: Session, row: Row, *, taken: Callable[[Row], bool], message: str, code: str
) -> Row:
    """Вставить строку; если такая уже есть — сказать об этом, а не упасть.

    `taken` отвечает на вопрос «место и правда занято?» и вызывается только
    после отказа базы. Обычно это та же проверка, что стояла перед вставкой, —
    и она же отличает свою гонку от чужой поломки.
    """
    if _placed(db, row, taken):
        return row
    raise errors.ConflictError(message, code=code)


def insert_retrying(
    db: Session,
    build: Callable[[], Row],
    *,
    taken: Callable[[Row], bool],
    message: str,
    code: str,
    attempts: int = DEFAULT_ATTEMPTS,
) -> Row:
    """Вставить строку, подбирая свободное значение заново после каждой неудачи.

    `build` вызывается перед каждой попыткой и обязан посчитать значение
    заново — иначе повтор упрётся в то же занятое место. Именно поэтому это
    функция, а не готовый объект.
    """
    for _ in range(attempts):
        row = build()
        if _placed(db, row, taken):
            return row

    raise errors.ConflictError(message, code=code)


def _placed(db: Session, row: Row, taken: Callable[[Row], bool]) -> bool:
    """Вставить строку. True — встала, False — место занято.

    Вставка идёт под точкой отката: откатывается только она, а не весь запрос,
    и сессия остаётся пригодной — вызывающий волен и ответить отказом, и
    попробовать другое значение.
    """
    try:
        with db.begin_nested():
            db.add(row)
            db.flush()
        return True
    except IntegrityError:
        # Откат точки обычно сам выбрасывает добавленное в ней из сессии, но
        # полагаться на это нельзя: останься объект ожидающим вставки —
        # следующий `flush` повторил бы её и упал уже без спасения, посреди
        # чужой операции и без объяснения.
        if row in db:
            db.expunge(row)
        if not taken(row):
            # Нарушено не то ограничение, ради которого всё затевалось. Прятать
            # такое под «занято» нельзя: это чужая поломка, и она должна быть
            # видна там, где случилась.
            raise
        return False
