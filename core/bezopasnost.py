"""Счётчики событий безопасности: кто и как щупает защиту.

**Отчего понадобилось.** Защита от подбора в проекте есть и работает —
скользящее окно на входе, на PIN и на номерах бланков (`core/ratelimit.py`).
Но НАРУЖУ она не рассказывает ничего. Владелец видит на панели время ответа,
долю пятисоток, память и место на диске — и ни одного числа о том, ломятся к
нему или нет. Отсюда два одинаково плохих состояния: подбор идёт неделю и никто
не знает, либо не идёт вовсе, а тревожиться не перестают.

Здесь считается ровно это: сколько раз защита сработала и сколько раз мимо неё
прошли промахом.

**Почему в Redis, а не в памяти процесса.** Prometheus скребёт ОДИН адрес, а за
ним стоит один из нескольких рабочих процессов, выбранный случайно. Счётчик,
живущий в памяти процесса, при четырёх процессах даёт пилу: ряд скачет вверх и
вниз в зависимости от того, к кому попал скребок, и `increase()` показывает
прирост там, где его не было. Ровно на этом уже обожглись однажды — тревога
`RateLimiterUnavailable` переехала со счётчика на состояние по той же причине.
Redis у всех процессов один, и число в нём одно.

**Что счётчик может потерять и почему это терпимо.** У Redis стоит
`maxmemory-policy allkeys-lru`, то есть под нехваткой памяти он выбрасывает
самые давно не тронутые ключи. Ключи этого модуля трогаются на КАЖДОМ событии,
то есть постоянно, и вытесняются последними — раньше уйдут миллионы разовых
ключей вида «этот адрес ошибся паролем». Если всё же уйдут, счётчик начнёт с
нуля; `rate()` и `increase()` умеют читать такой откат как перезапуск и теряют
один промежуток, а не весь ряд. Хуже было бы молчание, притворяющееся нулём.

**Счёт никогда не мешает работе.** Всё здесь под `try/except`: не сосчитанная
попытка входа — это дырка в графике, а упавший из-за счётчика вход — это
человек, который не может работать. Порядок важности именно такой.

**Чего здесь НЕТ и не будет.** Ни адресов, ни почт, ни каких-либо признаков
того, КТО стучался. Проект хэширует IP даже в собственном журнале просмотров, а
в журнал nginx не кладёт его вовсе (`docker/nginx/templates/logging.inc`).
Счётчик отвечает на вопрос «сколько», а не «кто»: на «кто» отвечает журнал
аудита, где для этого есть права доступа.
"""

from __future__ import annotations

from core import redis_client

#: Что считаем и как это называется на панели.
#:
#: Набор закрытый и намеренно маленький. Каждый вид — это отдельный ряд в
#: Prometheus навсегда, и «добавим на всякий случай» здесь стоит места в базе
#: метрик до конца жизни установки.
#:
#: Промах и запрет разделены нарочно, и это главное деление всего модуля.
#: ПРОМАХ — «пароль не подошёл»: один такой в день это опечатка человека, сто в
#: минуту это подбор. ЗАПРЕТ — «дальше не пустили»: он означает, что защита уже
#: сработала. Слитые в одно число, они отвечают на вопрос «плохо ли», но не на
#: вопрос «держит ли защита», а именно второй и нужен ночью.
VIDY: dict[str, str] = {
    "vhod_promah": "неверная пара почта/пароль",
    "vhod_zapert": "вход отказан ограничителем: попытки кончились",
    "pin_promah": "неверный PIN к витрине доски",
    "pin_zapert": "PIN отказан ограничителем: попытки кончились",
    "blank_promah": "номер бланка не найден",
    "blank_zapert": "просмотр бланка отказан ограничителем",
    "klyuch_promah": "неизвестный или просроченный ключ API",
}


def _kluch(vid: str) -> str:
    return f"{redis_client.PREFIX}sec:{vid}"


def otmetit(vid: str) -> None:
    """Отметить событие. Молча ничего не делает, если Redis недоступен.

    Молча — потому что вызывающий стоит на пути живого человека: в `login`, в
    проверке PIN, в открытии бланка. Ему нечего сделать с известием «счётчик не
    сосчитался», кроме как испортить ответ, а испорченный ответ хуже
    несосчитанной попытки.
    """
    if vid not in VIDY:
        # Опечатка в имени вида завела бы ряд-призрак, который никто никогда не
        # выведет на панель, — и сама опечатка осталась бы незамеченной. Пусть
        # лучше не сосчитается: неучтённое событие видно по расхождению с
        # журналом, а призрак не виден никак.
        return
    client = redis_client.get_client()
    if client is None:
        return
    try:
        client.incr(_kluch(vid))
    except Exception:  # noqa: BLE001 — сеть, таймаут, отказ сервера
        return


def snyat() -> dict[str, int]:
    """Все счётчики разом — для отдачи метрик.

    Одним `MGET` по ЗАРАНЕЕ ИЗВЕСТНОМУ списку, а не обходом ключей. `SCAN` по
    боевому Redis на каждом скребке (а это раз в пятнадцать секунд) стоит тем
    дороже, чем больше в нём ключей подбора, — то есть дорожает ровно тогда,
    когда идёт атака и метрики нужнее всего.

    Недоступный Redis даёт нули по всем видам. Это осознанный размен: ряд не
    рвётся, а «Redis лежит» уже сказано отдельной метрикой
    `opencrm_redis_up` — сказать это второй раз, испортив ряды подбора, значит
    потерять и то, и другое.
    """
    pusto = {vid: 0 for vid in VIDY}
    client = redis_client.get_client()
    if client is None:
        return pusto
    try:
        znacheniya = client.mget([_kluch(vid) for vid in VIDY])
    except Exception:  # noqa: BLE001 — сеть, таймаут, отказ сервера
        return pusto
    itog = {}
    for vid, syroe in zip(VIDY, znacheniya):
        try:
            itog[vid] = int(syroe) if syroe is not None else 0
        except (TypeError, ValueError):
            itog[vid] = 0
    return itog


def zabyt() -> None:
    """Обнулить счётчики. Только для тестов.

    В работе не зовётся ниоткуда и звать не должно: счётчик Prometheus обязан
    расти, а обнуление на живой машине читается как перезапуск и съедает
    промежуток на графике.
    """
    client = redis_client.get_client()
    if client is None:
        return
    try:
        client.delete(*[_kluch(vid) for vid in VIDY])
    except Exception:  # noqa: BLE001
        return
