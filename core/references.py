"""Ссылки из запроса: проверить, что указанное существует.

Клиент, заявка, ответственный, фирма — идентификаторы этих записей приходят
числом в теле запроса, и число это выбирает не сервер. Непроверенное доезжает до
вставки и падает нарушением внешнего ключа, то есть **пятисоткой на обычную
опечатку**. Найдено пробой по всем полям такого рода: из тринадцати мест пять
отвечали ошибкой сервера, а одно — сообщением не по делу («укажите клиента» на
запрос, где клиент как раз указан, просто несуществующий).

Проверки собраны здесь по трём причинам:

1. Их много и они одинаковые. Пять сервисов писали бы одно и то же.
2. Ответ должен быть одинаковым везде. «Клиента нет» — это 404 с кодом
   `client_not_found`, а не 422, не 500 и не «укажите клиента».
3. Забыть проверку легче всего в новом блоке, а не в старом. Готовая функция
   рядом с моделью — приглашение ею воспользоваться.

**Пустое значение — это не ошибка.** «Заявка ничья», «задача без клиента»,
«бланк прохожему без карточки» — законные состояния, и решение о том, законны ли
они в конкретном месте, принимает вызывающий, а не эта проверка.

**Удалённое не годится.** Репозитории по умолчанию не отдают мягко удалённых, и
это ровно то, что нужно: привязать новую задачу к клиенту, лежащему в корзине,
значит сделать запись, которую потом никто не найдёт.
"""

from sqlalchemy.orm import Session

from core import exceptions as errors
from database.repositories import clients as clients_repo
from database.repositories import deals as deals_repo
from database.repositories import users as users_repo


def client(db: Session, value) -> int | None:
    """Клиент из запроса. Пусто — None; нет такого — 404."""
    if not value:
        return None
    if clients_repo.get(db, int(value)) is None:
        raise errors.NotFoundError("Client not found", code="client_not_found")
    return int(value)


def deal(db: Session, value) -> int | None:
    """Заявка из запроса. Пусто — None; нет такой — 404."""
    if not value:
        return None
    if deals_repo.get(db, int(value)) is None:
        raise errors.NotFoundError("Deal not found", code="deal_not_found")
    return int(value)


def user(db: Session, value, *, code: str, message: str) -> int | None:
    """Сотрудник из запроса. Код и текст называет вызывающий.

    Ответственный за заявку и исполнитель напоминания — разные роли, и человеку,
    получившему отказ, важно знать, о ком речь. Общего «user_not_found» тут мало.

    Отключённых не запрещаем: человек уволился, а заявки и напоминания, которые
    он вёл, остаются его — переписывать историю ради красоты списка нельзя.
    Выбрать такого в интерфейсе всё равно нельзя, там показывают активных.
    """
    if not value:
        return None
    if users_repo.get_by_id(db, int(value)) is None:
        raise errors.NotFoundError(message, code=code)
    return int(value)
