"""Рост переписки и уборка старого. Решение владельца, а не молчание.

`telegram_messages` растёт быстрее всех таблиц системы: одна фирма с полусотней
диалогов набирает за год больше строк, чем весь склад за всю жизнь. Рано или
поздно с этим что-то придётся делать — и вот как это устроено здесь.

**По умолчанию не делается ничего.** Срок хранения пуст, уборка не запускается,
переписка лежит вечно. Это не «недоделано», это выбранное поведение: переписка с
клиентом бывает доказательством, и молча стереть её нельзя — ни через год, ни
через десять. Молчаливое удаление здесь хуже переполненного диска, потому что
диск виден, а пропавшая переписка нет.

**Уборка включается явно названным сроком.** «Хранить 12 месяцев» — и всё, что
старше, уходит. Сроки выбираются из списка, а не набираются числом, и это
намеренно: экран показывает возле каждого срока, СКОЛЬКО он удалит прямо сейчас
(`ves`). Показать это можно только для тех сроков, о которых спросили базу;
произвольное число означало бы выбор вслепую, то есть ровно то, чего избегаем.

**Что удаляется, а что остаётся — три решения, каждое стоит довода.**

1. **Файлы удаляются вместе со строками.** Место на диске занимают именно они:
   строка сообщения весит сотни байт, картинка — мегабайты. Уборка, оставляющая
   файлы, освободила бы проценты от того, ради чего затевалась, а осиротевшие
   файлы никто уже не нашёл бы — ссылки на них не осталось бы нигде.

   Порядок обратный привычному: строки удаляются и **фиксируются**, и только
   потом стираются файлы. Обрыв между этими шагами оставит файл, на который
   никто не ссылается, — он занимает место и не мешает. Обратный порядок при
   том же обрыве оставил бы сообщение со ссылкой на несуществующий файл, то есть
   дыру посреди переписки с клиентом. Из двух незаживающих состояний выбрано то,
   что дешевле.

2. **Записи в ленте клиента НЕ трогаются.** Привязанный диалог кладёт в ленту
   карточки `ClientNote` вида `telegram` — рядом со звонками и письмами. Уборка
   их не касается, и вот почему:

   - лента принадлежит КАРТОЧКЕ, а не мессенджеру. «Прибрать переписку» и
     «переписать историю клиента» — разные решения, и второго владелец не
     принимал. Сделать его побочным следствием первого значило бы решить за
     него;
   - запись в ленте — это текст до двух тысяч знаков и ни одного файла. Рост,
     ради которого всё затевается, идёт не оттуда: она меньше на порядки;
   - ссылки на `telegram_messages` в ней НЕТ вовсе (такой колонки не
     существует). Значит после уборки ничего не повисает и ничего не ломается:
     запись самодостаточна и читается как была;
   - цена ошибки несимметрична. Оставленная запись стоит килобайт; удалённая
     уносит след разговора из карточки, куда владелец не просил заходить.

   Прямое следствие, и его надо назвать вслух на экране: **после уборки в ленте
   клиента остаётся текстовый след разговора, даже когда сама переписка
   убрана.** Кому нужно обратное — тому нужно удаление клиента, а это другое
   действие с другими последствиями.

3. **Диалоги остаются.** Диалог помнит имя, логин, телефон, метку «откуда
   пришёл» и привязку к карточке, которую ставили руками. Опустевший диалог —
   законное состояние; удалённый означал бы потерю работы человека.

**Прогон ограничен по времени и идёт пачками.** Миллион строк одной транзакцией
кладёт базу: журнал отката держится всё время удаления, и вместе с ним встаёт
всё остальное. Здесь пачка фиксируется отдельно, а прогон прекращается по
исчерпании отпущенных секунд — недоделанное достанется следующему, и он начнёт
с того же дальнего края.

**Каждый прогон оставляет след.** Итог пишется в настройку и показывается на том
же экране, где выбирали срок: когда, за какую границу, сколько строк и файлов,
сколько места освободилось. Уборка, о которой негде прочитать, — это и есть
молчаливое удаление, только по расписанию.
"""

from __future__ import annotations

import calendar
import json
import logging
import time
from datetime import datetime
from pathlib import Path

from sqlalchemy.orm import Session

from config.settings import get_settings
from core import exceptions as errors
from core.services import storage_service
from core.utils import now_utc
from database.repositories import settings as settings_repo
from database.repositories import telegram as telegram_repo

logger = logging.getLogger(__name__)

#: Срок хранения в месяцах. Пусто или «0» — хранить вечно.
#:
#: Под общей приставкой канала (`telegram_`), поэтому уезжает вместе с
#: остальными настройками бота одним чтением.
SETTING_SROK = "telegram_retention_months"

#: След последнего прогона: JSON с числами и границей. Читается экраном.
SETTING_PROGON = "telegram_retention_last_run"

#: Хранить вечно. Значение по умолчанию, и оно же значение «владелец не выбирал».
BEZ_UBORKI = 0

#: Сроки, которые предлагаются владельцу.
#:
#: Список, а не свободное число, потому что экран обязан показать цену каждого:
#: «12 месяцев — уйдёт 3 120 сообщений (890 МБ)». Спросить базу можно только про
#: те сроки, которые названы заранее; свободное число означало бы выбор вслепую.
SROKI = (3, 6, 12, 24, 36)

#: Сколько строк удалять одной транзакцией.
#:
#: Пятьсот. Не «сколько получится»: удаление миллиона строк разом держит журнал
#: отката всё время работы, и на это время встаёт вся база — включая приём
#: сообщений от клиентов, ради которых всё и написано.
PACHKA = 500

#: Сколько секунд отпущено прогону.
#:
#: Минута. Уборка идёт по расписанию раз в сутки, и доделать она обязана не
#: сегодня, а когда-нибудь: недоделанное достанется следующему прогону, потому
#: что пачки берутся с самого старого края и граница движется вперёд.
#:
#: Предел нужен не ради вежливости к базе (об этом заботится размер пачки), а
#: ради предсказуемости расписания: задание, которое иногда идёт три часа,
#: однажды столкнётся с резервной копией и с обновлением.
PREDEL_SEKUND = 60


# --- срок хранения -----------------------------------------------------------


def proverit_srok(syroe) -> int:
    """Разобрать выбранный срок или отказать понятно.

    Пусто, «0» и `None` означают одно и то же — хранить вечно. Три написания у
    одного смысла потому, что приходят они из разных мест: пустое поле формы,
    выбор «Хранить вечно» и отсутствие настройки в базе.
    """
    if syroe is None:
        return BEZ_UBORKI
    tekst = str(syroe).strip()
    if not tekst or tekst == "0":
        return BEZ_UBORKI
    if not tekst.isdigit() or int(tekst) not in SROKI:
        raise errors.ValidationError(
            "Retention must be one of: keep forever, "
            + ", ".join(f"{m} months" for m in SROKI),
            code="bad_retention",
        )
    return int(tekst)


def srok(db: Session) -> int:
    """Сколько месяцев хранить. Ноль — вечно.

    Непонятное значение в базе читается как «вечно», а не как отказ. Настройку
    правят руками при переносах, и опечатка в ней не должна ни ронять экран, ни
    — тем более — обернуться удалением по случайному сроку.
    """
    stroka = settings_repo.get_row(db, SETTING_SROK)
    if stroka is None:
        return BEZ_UBORKI
    try:
        return proverit_srok(stroka.value)
    except errors.ValidationError:
        logger.warning("непонятный срок хранения переписки: %r — считаю «вечно»", stroka.value)
        return BEZ_UBORKI


def zadat_srok(db: Session, syroe) -> int:
    """Записать срок. Проверка — до записи, а не после."""
    mesyatsev = proverit_srok(syroe)
    settings_repo.write(db, SETTING_SROK, str(mesyatsev) if mesyatsev else "")
    return mesyatsev


def granitsa(mesyatsev: int, seychas: datetime | None = None) -> datetime | None:
    """Граница «старее этого убираем». Вечное хранение — `None`.

    Месяцы считаются календарём, а не тридцатью сутками. Разница у «12 месяцев»
    — пять дней, и это те самые пять дней, за которые убираемое расходится с
    обещанным. Владельцу обещали год, а не триста шестьдесят суток.

    День подрезается по длине месяца: 31 марта минус один месяц — это 28 или 29
    февраля, а не несуществующее 31-е.
    """
    if mesyatsev <= 0:
        return None
    tochka = seychas or now_utc().replace(tzinfo=None)
    god, mesyats = tochka.year, tochka.month - mesyatsev
    while mesyats <= 0:
        mesyats += 12
        god -= 1
    den = min(tochka.day, calendar.monthrange(god, mesyats)[1])
    return tochka.replace(year=god, month=mesyats, day=den)


# --- сколько это весит -------------------------------------------------------


def ves(db: Session, seychas: datetime | None = None) -> dict:
    """Чем платит владелец за вечное хранение — числами.

    **Без этих цифр решение принимать не из чего.** «Переписка растёт» — не
    довод ни за, ни против; «сорок тысяч сообщений, из них полторы тысячи
    вложений на 3.2 ГБ, самое старое от марта позапрошлого года» — довод.

    Место на диске названо дважды, и это не описка. `file_bytes` — вес
    вложений, посчитанный по строкам базы; `disk_bytes` — что каталог канала
    занимает на самом деле. Второе больше: там же лежат аватары собеседников, а
    их уборка не трогает. Разойдясь заметно, эти два числа сами скажут, что на
    диске есть лишнее.
    """
    granitsy = {mesyatsev: granitsa(mesyatsev, seychas) for mesyatsev in SROKI}
    itog = telegram_repo.ves_perepiski(db, granitsy)
    # Обход каталога дорог, поэтому с кэшем на минуту — тем же, которым живёт
    # показ занятого места в настройках сайта.
    itog["disk_bytes"] = storage_service.dir_size(
        get_settings().storage_dir / "telegram", cache_key="telegram"
    )
    return itog


def posledniy_progon(db: Session) -> dict | None:
    """Что сделал прошлый прогон. Нет записи — уборка ни разу не ходила."""
    stroka = settings_repo.get_row(db, SETTING_PROGON)
    if stroka is None or not stroka.value:
        return None
    try:
        razobrano = json.loads(stroka.value)
    except ValueError:
        # Испорченную запись показываем как отсутствующую: след прогона —
        # сведение для человека, и ронять из-за него экран настроек незачем.
        logger.warning("след прогона уборки не разобрался: %r", stroka.value[:120])
        return None
    return razobrano if isinstance(razobrano, dict) else None


# --- сама уборка -------------------------------------------------------------


def ubrat(
    db: Session,
    *,
    seychas: datetime | None = None,
    pachka: int = PACHKA,
    predel_sekund: int = PREDEL_SEKUND,
    na_sukho: bool = False,
) -> dict:
    """Убрать переписку старше выбранного срока. Пачками и по часам.

    **Эта функция фиксирует транзакции сама, и потому она не для ручки.** Она
    задание по расписанию: смысл пачек ровно в том, чтобы каждая уходила своей
    транзакцией, а вызванная внутри запроса она зафиксировала бы заодно всё, что
    ручка успела наделать до неё.

    `na_sukho` считает и не удаляет — им отвечают на вопрос «а сколько уйдёт»
    перед первым настоящим прогоном.
    """
    mesyatsev = srok(db)
    if mesyatsev <= 0:
        # Срок не назван — не делаем ничего и следа не оставляем: затирать им
        # запись о настоящем прогоне значило бы терять единственное место, где
        # видно, что и когда убиралось.
        return {
            "status": "off",
            "months": BEZ_UBORKI,
            "cutoff": None,
            "messages": 0,
            "files": 0,
            "bytes": 0,
            "done": True,
        }

    # Срок положителен, значит граница есть; `or` здесь только ради проверяющего
    # типы, которому про эту связь неоткуда узнать.
    do = granitsa(mesyatsev, seychas) or (seychas or now_utc().replace(tzinfo=None))

    if na_sukho:
        return {
            "status": "dry",
            "months": mesyatsev,
            "cutoff": do,
            "messages": telegram_repo.skolko_starykh(db, do),
            "files": 0,
            "bytes": 0,
            "done": True,
        }

    nachalo = time.monotonic()
    udaleno = faylov = osvobozhdeno = 0
    dodelano = True

    while True:
        para = telegram_repo.starye(db, do, pachka)
        if not para:
            break
        ids = [nomer for nomer, _ in para]
        puti = [put for _, put in para if put]

        udaleno += telegram_repo.udalit_soobshcheniya(db, ids)
        # Фиксируем ДО того, как трогать диск: обрыв здесь оставит осиротевший
        # файл (место и ничего больше), а обратный порядок оставил бы сообщение
        # со ссылкой в пустоту — дыру посреди переписки с клиентом.
        db.commit()

        for put in puti:
            razmer = _ubrat_fayl(put)
            if razmer is not None:
                faylov += 1
                osvobozhdeno += razmer

        if time.monotonic() - nachalo >= predel_sekund:
            # Недоделанное достанется следующему прогону: пачки берутся с самого
            # старого края, значит граница за этот прогон продвинулась вперёд.
            dodelano = False
            break

    if faylov:
        # Иначе экран настроек ещё минуту показывал бы прежний вес каталога —
        # ровно тогда, когда человек смотрит, помогла ли уборка.
        storage_service.invalidate_size_cache()

    itog = {
        "status": "done" if dodelano else "partial",
        "months": mesyatsev,
        "cutoff": do,
        "messages": udaleno,
        "files": faylov,
        "bytes": osvobozhdeno,
        "done": dodelano,
    }
    _zapisat_progon(db, itog, seychas)
    db.commit()

    logger.info(
        "уборка переписки: удалено %s сообщений и %s файлов (%s), старше %s, срок %s мес.%s",
        udaleno,
        faylov,
        storage_service.format_bytes(osvobozhdeno),
        do.isoformat(sep=" ", timespec="seconds"),
        mesyatsev,
        "" if dodelano else " — прогон уперся в предел времени, продолжит следующий",
    )
    return itog


def _zapisat_progon(db: Session, itog: dict, seychas: datetime | None = None) -> None:
    """Оставить след прогона там, где его прочтёт владелец.

    В настройке, а не только в журнале службы. Журнал лежит на сервере и
    читается через `journalctl` тем, у кого есть доступ к машине; а решение
    принимал владелец в браузере, и отчитываться перед ним надо там же, где он
    выбирал срок. Прогон, о котором негде прочитать, — это и есть молчаливое
    удаление, только по расписанию.
    """
    kogda = seychas or now_utc().replace(tzinfo=None)
    settings_repo.write(
        db,
        SETTING_PROGON,
        json.dumps(
            {
                "at": kogda.isoformat(timespec="seconds"),
                "cutoff": itog["cutoff"].isoformat(timespec="seconds"),
                "months": itog["months"],
                "messages": itog["messages"],
                "files": itog["files"],
                "bytes": itog["bytes"],
                "done": itog["done"],
            }
        ),
    )


def _ubrat_fayl(otnositelnyy: str) -> int | None:
    """Стереть файл переписки. Возвращает освобождённые байты или `None`.

    **Путь проверяется на выход за пределы каталога канала**, хотя пишем его мы
    сами. Довод тот же, что у отдачи файла наружу: это место стирает файлы по
    строке из базы, а строку в базе однажды поправят руками при переносе. Цена
    проверки — одно сравнение, цена её отсутствия — стёртый файл где угодно на
    диске.

    Пропажа файла — не отказ. Диск чистили, переносили, копию разворачивали
    частично; строка при этом удалена, а её файла уже не было. Считать это
    ошибкой значило бы краснеть расписанием на том, что уже в порядке.
    """
    koren = (get_settings().storage_dir / "telegram").resolve()
    try:
        put = (get_settings().storage_dir / otnositelnyy).resolve()
    except OSError as beda:  # пути бывают и вовсе неразрешимыми
        logger.warning("не разобрал путь файла переписки %r: %r", otnositelnyy, beda)
        return None

    if not put.is_relative_to(koren):
        logger.warning("уборка не тронула путь вне каталога канала: %r", otnositelnyy)
        return None

    try:
        razmer = put.stat().st_size
        put.unlink()
    except FileNotFoundError:
        return None
    except OSError as beda:
        logger.warning("не удалось стереть файл переписки %r: %r", otnositelnyy, beda)
        return None

    _ubrat_pustoy_katalog(put.parent, koren)
    return razmer


def _ubrat_pustoy_katalog(katalog: Path, koren: Path) -> None:
    """Убрать опустевший каталог диалога. Только пустой и только свой.

    `rmdir` отказывается сносить непустой каталог, и это здесь не ограничение, а
    защита: рядом с вложениями лежит аватар собеседника, а его уборка не
    касается. Пока аватар на месте, каталог остаётся — и правильно.
    """
    if katalog == koren or not katalog.is_relative_to(koren):
        return
    try:
        katalog.rmdir()
    except OSError:
        return
