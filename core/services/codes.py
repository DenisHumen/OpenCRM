"""Штрихкод и QR для бланков — оба в SVG, оба встраиваются в страницу.

Почему библиотеки, а не свой код. QR — это Рид-Соломон, маскирование и таблицы
версий; такое в CRM не пишут. Штрихкод Code128 сначала был написан руками:
казалось, что таблица шаблонов и сумма по модулю 103 — дело на сто строк. Но
таблица, набранная по памяти, при первой же структурной проверке (каждый шаблон
обязан складываться в 11 модулей) оказалась битой в четырёх местах и лишней на
две строки. Печатать такой штрихкод — значит выдать клиенту бумагу, которая не
сканируется, и узнать об этом от него же.

SVG, а не PNG: бланк печатают, и вектор остаётся резким на любом принтере,
тогда как растр в 300 dpi пришлось бы генерировать и хранить.
"""

import io
import re

import barcode
import segno
from barcode.writer import SVGWriter

# Номер печатаем под полосками. Это не украшение: сканер не читает мятую или
# залитую кофем бумагу, и тогда приёмщик набирает номер руками — а набрать его
# неоткуда, если под штрихкодом пусто.
#
# Тихая зона (quiet_zone) обязательна: без пустых полей по краям сканер не
# находит начало кода, и красиво свёрстанный впритык штрихкод не читается.
_BARCODE_OPTIONS = {
    "module_height": 8.0,
    "module_width": 0.28,
    "quiet_zone": 3.0,
    "font_size": 8,
    "text_distance": 2.0,
    "write_text": True,
}


#: Штрихкод для наклейки — другая геометрия, чем у бланка.
#:
#: Бланк это лист A4, наклейка — лоскут 58×40 мм, и настройки у них разойтись
#: обязаны. Полоски ниже (на наклейке высота на вес золота), тихая зона уже,
#: цифры библиотека НЕ рисует: их печатает сам шаблон наклейки, потому что там
#: они должны быть заданного размера, а не отмасштабированного вместе с картинкой.
_LABEL_OPTIONS = {
    "module_height": 10.0,
    "module_width": 0.28,
    "quiet_zone": 1.5,
    "write_text": False,
}


def barcode_svg(text: str, *, label: bool = False) -> str:
    """Code128 в виде фрагмента SVG, готового к вставке в HTML.

    `label=True` — вариант для наклейки: ниже, уже поля, без подписи цифрами.
    Флагом, а не свободным словарём настроек: вариантов ровно два (бланк и
    наклейка), и пусть они оба лежат здесь, рядом, чем расползаются по вызовам,
    где однажды разойдутся в мелочах.
    """
    if not text:
        raise ValueError("Barcode text is empty")
    buffer = io.BytesIO()
    options = _LABEL_OPTIONS if label else _BARCODE_OPTIONS
    barcode.get("code128", text, writer=SVGWriter()).write(buffer, options)
    return _s_ramkoy(_inline(buffer.getvalue().decode("utf-8")))


def qr_svg(text: str, scale: float = 2.4) -> str:
    """QR в виде фрагмента SVG.

    Уровень коррекции M: бланк живёт в мастерской, его мнут и пачкают, а M
    переживает потерю примерно 15% изображения. L экономит место, но на
    затёртой бумаге перестаёт читаться первым.
    """
    if not text:
        raise ValueError("QR text is empty")
    # segno пишет байты даже для SVG — StringIO тут падает с TypeError.
    buffer = io.BytesIO()
    segno.make(text, error="m").save(buffer, kind="svg", scale=scale, border=2, xmldecl=False)
    return _s_ramkoy(_inline(buffer.getvalue().decode("utf-8")))


#: Размер картинки в атрибутах SVG. Единицы бывают разные: segno пишет пиксели
#: без единиц, python-barcode — миллиметры.
#: Миллиметр в пользовательских единицах SVG: 96 точек на дюйм, 25,4 мм в дюйме.
MM_V_EDINITSAH = 96 / 25.4

_RAZMER = re.compile(r'width="([\d.]+)(?:mm)?"\s+height="([\d.]+)(?:mm)?"')


def _s_ramkoy(svg: str) -> str:
    """Дописать `viewBox`, если его нет. Без него картинка не ужимается, а вылезает.

    **Найдено живым осмотром наклейки, а не чтением.** Обе библиотеки ставят
    SVG только `width` и `height`. Пока картинку показывают как есть, этого
    хватает — но стоит задать ей размер стилями, и рамка ужимается, а рисунок
    внутри остаётся прежним и просто выходит за неё. Обрезанный штрихкод не
    читается вовсе, а увидеть это можно только на отпечатанной ленте.

    Поймано на двух сразу. QR на наклейке 58×40 вылез за правый край на 3,7 мм.
    А у штрихкода то же самое оказалось ДАВНИМ: шаблон обещает «ширина — во всю
    наклейку» (`.code svg { width: 100% }`), но полоски всё это время печатались
    своей природной шириной 37,4 мм. На рулоне 58 мм это совпало случайно, а на
    30 мм штрихкод выходил за край на 8 мм — то есть на мелких рулонах наклейка
    не работала никогда.

    `viewBox` теми же числами ничего не меняет тем, кто размер не задаёт (бланк,
    страница привязки бота): собственный размер картинки остаётся прежним. Зато
    всякий, кто задаст, получит ужатый рисунок, а не обрезанный.
    """
    if "viewBox" in svg:
        return svg
    razmer = _RAZMER.search(svg)
    if not razmer:
        return svg
    # Единицы `viewBox` — те же, в каких нарисовано СОДЕРЖИМОЕ, а не те, что
    # стоят в `width`. python-barcode пишет размер в миллиметрах, а полоски
    # внутри — тоже в миллиметрах, и миллиметр в пользовательских единицах SVG
    # равен 96/25.4 ≈ 3,78. Поставь мы `viewBox="0 0 37.44 12"` — рисунок вышел
    # бы ровно в 3,78 раза крупнее рамки. Замерено живьём: полоски вылезали за
    # край на 134 пикселя при рамке в 66.
    mnozhitel = MM_V_EDINITSAH if razmer.group(0).count("mm") else 1
    shirina = float(razmer.group(1)) * mnozhitel
    vysota = float(razmer.group(2)) * mnozhitel
    return svg.replace(
        razmer.group(0),
        f'{razmer.group(0)} viewBox="0 0 {shirina:.3f} {vysota:.3f}"',
        1,
    )


def _inline(svg: str) -> str:
    """Убирает пролог и DOCTYPE: внутри HTML они недопустимы и ломают разбор."""
    svg = re.sub(r"<\?xml[^>]*\?>", "", svg)
    svg = re.sub(r"<!DOCTYPE[^>]*>", "", svg, flags=re.IGNORECASE)
    return svg.strip()
