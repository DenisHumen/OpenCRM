#: Самый длинный код в таблице — с него и начинается подбор.
MAX_DLINA_KODA = max(len(kod) for kod in KODY_STRAN)

#: `+7`: Казахстан отличается от России второй цифрой.
SEMYORKA = (("76", "KZ"), ("77", "KZ"), ("7", "RU"))


def strana_po_nomeru(phone_norm: str) -> str:
    """Страна по коду набора. Пусто — «не определилось», и это не ошибка.

    На вход идёт нормализованный номер (`clients.phone_norm`): только цифры, без
    «плюса», с уже дописанным кодом страны, если он настроен. Местный номер без
    кода (`067…`) страну не даёт — и не должен: дописать чужую страну хуже, чем
    не дописать никакой. Тот же довод, что у `normalize_phone`.
    """
    cifry = "".join(ch for ch in (phone_norm or "") if ch.isdigit())
    if not cifry:
        return ""
    for nachalo, strana in SEMYORKA:
        if cifry.startswith(nachalo):
            return strana
    # Подбор от длинного кода к короткому: `380` обязан выиграть у `38`, иначе
    # украинский номер стал бы чужим при первом же расширении таблицы.
    for dlina in range(MAX_DLINA_KODA, 0, -1):
        strana = KODY_STRAN.get(cifry[:dlina])
        if strana:
            return strana
    return ""
