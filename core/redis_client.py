"""Тонкий слой доступа к Redis.

Лежит в `core/`, а не в `database/`, и это не вкус. Граница `database/`
охраняет базу ПРЕДМЕТНОЙ ОБЛАСТИ: клиенты, заявки, деньги — то, что переживает
перезапуск, попадает в резервную копию и сверяется со схемой. Redis здесь не
хранит ничего из этого. В нём живёт счётчик неудачных попыток входа — величина,
которая имеет смысл ровно пятнадцать минут и которую не жалко потерять. Положи
мы его в `database/`, `tests/test_db_boundary.py` пришлось бы учить исключению,
а `schema_check` — молчать про таблицы, которых нет в `Base.metadata`.

--------------------------------------------------------------------------
Почему Redis обязателен, а не «по желанию»
--------------------------------------------------------------------------

База допускает несколько рабочих процессов (`OPENCRM_WORKERS` больше единицы —
см. `config/settings.config_errors`), а с ними отпадает единственное, на чём
держалась защита от подбора: ограничитель попыток жил в памяти процесса. Восемь
процессов — восемь независимых счётчиков, порог умножается на восемь, и
НИКАКОЙ ОШИБКИ при этом не возникает: каждый процесс честно считает свои пять
попыток, а снаружи защита выглядит работающей.

Поэтому Redis — не «ускоритель на будущее», а условие работоспособной защиты.
Служба в compose стоит БЕЗ профиля (в отличие от `db`): «выключенный Redis»
означал бы «ограничителя нет», а этого состояния существовать не должно.

--------------------------------------------------------------------------
Пустой OPENCRM_REDIS_URL
--------------------------------------------------------------------------

Значение по умолчанию пустое, и это единственный способ поднять приложение без
Redis — на ноутбуке разработчика и в наборе тестов, где внешних служб нет
вовсе. Молчаливым ослаблением защиты это не является, потому что пустое
значение отвергается на старте (`config_errors`) в двух случаях сразу:

  * `OPENCRM_ENV=production` — развёрнутая система обязана иметь общий счётчик;
  * `OPENCRM_WORKERS > 1` в любом окружении — именно здесь порог и множился бы.

То есть «без Redis» существует ровно там, где процесс один и окружение не
боевое: в этом сочетании счётчик в памяти процесса и есть общий счётчик.
"""

import threading
from contextlib import contextmanager

from config.settings import get_settings

#: Через сколько секунд считаем Redis недоступным.
#:
#: Секунда, а не десять. Обращение к ограничителю стоит на входе КАЖДОГО
#: запроса к форме входа, и десятисекундное ожидание превратило бы недоступный
#: Redis в лежащий сайт: соединения копились бы быстрее, чем истекали. Секунды
#: с запасом хватает соседнему контейнеру на той же машине, а если не хватило —
#: это и есть «недоступен», и отвечать надо сразу.
TIMEOUT_SECONDS = 1.0

#: Общая приставка ключей. Всё, что пишет приложение, лежит под ней — чтобы
#: базу можно было отличить от чужой, случайно оказавшейся тем же сервером.
PREFIX = "opencrm:"

_client = None
_lock = threading.Lock()


class RedisUnavailable(Exception):
    """Redis не отвечает. Ловится там, где решают, что делать дальше."""


def configured() -> bool:
    """Задан ли адрес Redis. Пустой — работаем без него (см. шапку модуля)."""
    return bool(get_settings().redis_url.strip())


def get_client():
    """Клиент Redis или `None`, если адрес не задан.

    Клиент один на процесс: у redis-py внутри пул соединений, и заводить его
    на каждый вызов значит платить рукопожатием за каждую проверку входа.
    """
    global _client
    if not configured():
        return None
    if _client is not None:
        return _client
    with _lock:
        if _client is None:
            import redis  # локальный импорт: без Redis модуль незачем грузить

            _client = redis.Redis.from_url(
                get_settings().redis_url,
                socket_timeout=TIMEOUT_SECONDS,
                socket_connect_timeout=TIMEOUT_SECONDS,
                # Проверять живость соединения перед выдачей из пула: контейнер
                # Redis перезапускается сам (`restart: unless-stopped`), и без
                # этой строки первый запрос после перезапуска получал бы
                # оборванное соединение из пула вместо ответа.
                health_check_interval=30,
                decode_responses=True,
            )
    return _client


def reset_client() -> None:
    """Забыть клиента. Нужно тестам и смене настроек, в боевом коде не зовётся."""
    global _client
    with _lock:
        if _client is not None:
            try:
                _client.close()
            except Exception:  # noqa: BLE001 — закрываем на всякий случай
                pass
        _client = None


def ping() -> bool:
    """Отвечает ли Redis. Не задан — тоже `False`, вопрос «жив ли» к нему не стоит."""
    client = get_client()
    if client is None:
        return False
    try:
        return bool(client.ping())
    except Exception:  # noqa: BLE001 — любая беда с сетью это «не отвечает»
        return False


@contextmanager
def startup_lock(name: str, ttl_seconds: int = 60):
    """Замок на время посева умолчаний при старте.

    Зачем он нужен: при нескольких рабочих процессах все они поднимаются разом
    и все выполняют посев. Четыре из пяти посевов от соседа защищены
    (`core/uniqueness.insert_or_ignore` и его родня) — они опираются на
    уникальный индекс. Пятый, склад «Основной», защититься так не может:
    уникального индекса на названии склада нет, и `count_alive() > 0` у двух
    процессов отвечает «ноль» обоим. В базе появляются два склада «Основной», и
    инвариант «ровно один основной» дальше выполняется наперегонки.

    Замок здесь честнее уникального индекса на названии: два склада с одним
    именем — это не ошибка данных (филиалы называют одинаково), а вот два
    ПОСЕВА — ошибка. Индекс запретил бы первое ради второго.

    Redis не задан или не отвечает — идём без замка. Это не дыра: без Redis
    процесс ровно один (см. шапку модуля), а гонки между процессами, которого
    нет, не бывает.
    """
    client = get_client()
    if client is None:
        yield
        return
    key = f"{PREFIX}lock:{name}"
    held = False
    try:
        held = bool(client.set(key, "1", nx=True, ex=ttl_seconds))
        if not held:
            # Сосед сеет прямо сейчас. Ждём его, а не пропускаем посев: наш
            # процесс должен увидеть засеянное, а не пустую базу.
            for _ in range(int(ttl_seconds * 10)):
                if client.set(key, "1", nx=True, ex=ttl_seconds):
                    held = True
                    break
                threading.Event().wait(0.1)
    except Exception as exc:  # noqa: BLE001
        print(f"[opencrm] Redis недоступен при посеве умолчаний: {exc}", flush=True)
        yield
        return
    try:
        yield
    finally:
        if held:
            try:
                client.delete(key)
            except Exception:  # noqa: BLE001
                pass
