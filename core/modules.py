"""Реестр блоков системы.

Зачем это отдельной опорой, а не флажком в настройках. CRM должна годиться и
мастерской, и дизайн-студии, и магазину, а нужны им разные вещи: студии не нужен
склад, мастерской — доски с макетами. Выключенный блок обязан исчезать целиком —
из меню, из API, из отчётов — и при этом не задевать остальные. Если такую
возможность прикручивать после того, как блоков станет десять, придётся править
все десять; поэтому реестр появляется раньше самих блоков.

Здесь только описание: что за блоки бывают, какие из них несущие и что от чего
зависит. Включено или выключено — состояние, оно живёт в базе
(core/services/modules_service.py). Разделение важно: код — источник правды о
том, какие блоки существуют, база — только о том, какие из них нужны этому
бизнесу. Иначе строка в базе от снесённого блока продолжала бы «включать» то,
чего в коде уже нет.

Модуль в реестре появляется, когда он написан. Переключатель для того, чего нет,
— обещание, а не функция; поэтому запланированные блоки отмечены `ready=False`,
показываются как «в разработке» и не включаются.
"""

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Module:
    key: str
    #: Несущий блок: на нём держится всё остальное, выключать нечему.
    core: bool = False
    #: Написан и работает. False — блок в планах, показываем, но не включаем.
    ready: bool = True
    #: Включён ли у нового пользователя, если блок необязательный.
    default: bool = True
    #: Блоки, без которых этот не имеет смысла.
    requires: tuple[str, ...] = field(default_factory=tuple)


# Порядок важен: в таком виде блоки показываются в настройках, от несущих к
# необязательным.
MODULES: tuple[Module, ...] = (
    # --- ядро ---
    # Клиент — это тот, ради кого всё остальное. Без него не к чему привязать ни
    # заявку, ни документ, ни письмо.
    Module(key="clients", core=True),
    # Заявка — стержень системы. Именно на ней сходятся этапы, комментарии,
    # документы, а в будущем звонки и письма. Выключить её значит рассыпать
    # систему на несвязанные списки, ради чего всё и затевалось.
    Module(key="deals", core=True, requires=("clients",)),
    # --- необязательные, уже работают ---
    # Свои юрлица. Ни от чего не зависят намеренно: реквизиты нужны и тому, у
    # кого нет ни одной заявки, — счёт выставляют раньше, чем заводят работу.
    # Выключают его те, у кого юрлицо одно и в бумагах оно не участвует.
    Module(key="companies"),
    Module(key="documents", requires=("clients",)),
    # Напоминания ни от чего не зависят: «отвезти документы в банк» — тоже
    # задача, и клиент с заявкой ей не нужны.
    Module(key="tasks"),
    Module(key="boards", default=True),
    # Склад нужен магазину и мастерской, а дизайн-студии нет — поэтому, в
    # отличие от остальных готовых блоков, по умолчанию выключен. Списание идёт
    # под заявку, отсюда зависимость: без заявок остаётся голый учёт остатков,
    # который не отвечает на вопрос «во сколько нам обошлась эта работа».
    Module(key="warehouse", default=False, requires=("deals",)),
    # Наклейки со штрихкодом. Стоят на складе: наклейка на товар без товаров
    # бессмысленна. По умолчанию выключены — термопринтер есть не у всех, а
    # включённый блок без него это кнопка «печать», ведущая в никуда.
    #
    # Выключение прячет печать и сканер, но **не трогает сами коды**: они
    # свойство товара, а не наклейки. Выключили печать — не значит отказались от
    # кодов; включат обратно, и всё на месте. Ровно как выключенные бланки не
    # стирают уже выданные бумаги.
    Module(key="labels", default=False, requires=("warehouse",)),
    # Отчёты считаются по заявкам и их этапам — без заявок считать нечего.
    Module(key="reports", requires=("deals",)),
    # Почта. Выключена у нового пользователя: ящик фирмы есть не у всех, а
    # включённый блок без настроенного ящика — пустой раздел в меню. Стоит на
    # клиентах: письмо привязывается к клиенту по адресу и ложится в его ленту.
    Module(key="mail", default=False, requires=("clients",)),
    # Телефония. Выключена по умолчанию: она бесполезна без настроенной АТС, а
    # пустой журнал звонков в меню у того, у кого станции нет, — обещание, а не
    # функция. Зависит только от клиентов: звонок обязан находить, кому он был,
    # а заявка у звонка бывает не всегда («позвонил спросить про цены»).
    Module(key="telephony", default=False, requires=("clients",)),
)

BY_KEY: dict[str, Module] = {module.key: module for module in MODULES}

KEYS: tuple[str, ...] = tuple(module.key for module in MODULES)


def get(key: str) -> Module | None:
    return BY_KEY.get(key)


def dependents_of(key: str) -> tuple[str, ...]:
    """Кто перестанет иметь смысл, если выключить этот блок."""
    return tuple(m.key for m in MODULES if key in m.requires)
