"""Реестр блоков системы.

Зачем это отдельной опорой, а не флажком в настройках. CRM должна годиться и
мастерской, и дизайн-студии, и магазину, а нужны им разные вещи: студии не нужен
склад, мастерской — доски с макетами. Выключенный блок обязан исчезать целиком —
из меню, из API, из отчётов — и при этом не задевать остальные. Если такую
возможность прикручивать после того, как блоков станет десять, придётся править
все десять; поэтому реестр появляется раньше самих блоков.

Здесь только описание: что за блоки бывают, какие из них несущие и что от чего
зависит. Включено или выключено — состояние, оно живёт в базе
(core/services/modules_service.py). Разделение важно: код — источник правды о
том, какие блоки существуют, база — только о том, какие из них нужны этому
бизнесу. Иначе строка в базе от снесённого блока продолжала бы «включать» то,
чего в коде уже нет.

Модуль в реестре появляется, когда он написан. Переключатель для того, чего нет,
— обещание, а не функция; поэтому запланированные блоки отмечены `ready=False`,
показываются как «в разработке» и не включаются.
"""

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Module:
    key: str
    #: Несущий блок: на нём держится всё остальное, выключать нечему.
    core: bool = False
    #: Написан и работает. False — блок в планах, показываем, но не включаем.
    ready: bool = True
    #: Включён ли у нового пользователя, если блок необязательный.
    default: bool = True
    #: Блоки, без которых этот не имеет смысла.
    requires: tuple[str, ...] = field(default_factory=tuple)


# Порядок важен: в таком виде блоки показываются в настройках, от несущих к
# необязательным.
MODULES: tuple[Module, ...] = (
    # --- ядро ---
    # Клиент — это тот, ради кого всё остальное. Без него не к чему привязать ни
    # заявку, ни документ, ни письмо.
    Module(key="clients", core=True),
    # Заявка — стержень системы. Именно на ней сходятся этапы, комментарии,
    # документы, а в будущем звонки и письма. Выключить её значит рассыпать
    # систему на несвязанные списки, ради чего всё и затевалось.
    Module(key="deals", core=True, requires=("clients",)),
    # --- необязательные, уже работают ---
    # Свои юрлица. Ни от чего не зависят намеренно: реквизиты нужны и тому, у
    # кого нет ни одной заявки, — счёт выставляют раньше, чем заводят работу.
    # Выключают его те, у кого юрлицо одно и в бумагах оно не участвует.
    Module(key="companies"),
    Module(key="documents", requires=("clients",)),
    # Напоминания ни от чего не зависят: «отвезти документы в банк» — тоже
    # задача, и клиент с заявкой ей не нужны.
    Module(key="tasks"),
    Module(key="boards", default=True),
    # Склад нужен магазину и мастерской, а дизайн-студии нет — поэтому, в
    # отличие от остальных готовых блоков, по умолчанию выключен. Списание идёт
    # под заявку, отсюда зависимость: без заявок остаётся голый учёт остатков,
    # который не отвечает на вопрос «во сколько нам обошлась эта работа».
    Module(key="warehouse", default=False, requires=("deals",)),
    # Наклейки со штрихкодом. Стоят на складе: наклейка на товар без товаров
    # бессмысленна. По умолчанию выключены — термопринтер есть не у всех, а
    # включённый блок без него это кнопка «печать», ведущая в никуда.
    #
    # Выключение прячет печать и сканер, но **не трогает сами коды**: они
    # свойство товара, а не наклейки. Выключили печать — не значит отказались от
    # кодов; включат обратно, и всё на месте. Ровно как выключенные бланки не
    # стирают уже выданные бумаги.
    Module(key="labels", default=False, requires=("warehouse",)),
    # Заказы: перечень позиций, резерв, отгрузка. Стоят на бланках, потому что
    # заказ — это вид бланка (номер, статусы, печать, поиск сканом берутся
    # оттуда готовыми).
    #
    # Со складом связь **мягкая**: заказ на услуги складу не нужен, и объявлять
    # зависимость жёсткой значило бы запретить заказы тому, у кого склада нет.
    # Выражается это проверкой `is_enabled` в коде (см. `order_service`): в
    # реестре `requires` означает «без этого не работает», и размывать понятие
    # ради одного случая дороже, чем написать проверку.
    Module(key="orders", default=False, requires=("documents",)),
    # Отчёты считаются по заявкам и их этапам — без заявок считать нечего.
    Module(key="reports", requires=("deals",)),
    # Почта. Выключена у нового пользователя: ящик фирмы есть не у всех, а
    # включённый блок без настроенного ящика — пустой раздел в меню. Стоит на
    # клиентах: письмо привязывается к клиенту по адресу и ложится в его ленту.
    Module(key="mail", default=False, requires=("clients",)),
    # Телефония. Выключена по умолчанию: она бесполезна без настроенной АТС, а
    # пустой журнал звонков в меню у того, у кого станции нет, — обещание, а не
    # функция. Зависит только от клиентов: звонок обязан находить, кому он был,
    # а заявка у звонка бывает не всегда («позвонил спросить про цены»).
    Module(key="telephony", default=False, requires=("clients",)),
    # Деньги предприятия: приход и расход по статьям, планы, прибыль.
    #
    # Без `requires` намеренно. Строка «Аренда за август» не относится ни к
    # какой заявке и ни к какому клиенту — связи с ними у операции есть, но
    # необязательные. Поставить зависимость значило бы запретить вести расходы
    # тому, кто не ведёт заявок, а это ровно тот случай, ради которого блок и
    # включают отдельно.
    Module(key="finance", default=False),
)

BY_KEY: dict[str, Module] = {module.key: module for module in MODULES}

KEYS: tuple[str, ...] = tuple(module.key for module in MODULES)


def get(key: str) -> Module | None:
    return BY_KEY.get(key)


def dependents_of(key: str) -> tuple[str, ...]:
    """Кто перестанет иметь смысл, если выключить этот блок. Только прямые."""
    return tuple(m.key for m in MODULES if key in m.requires)


def dependents_tree(key: str) -> tuple[str, ...]:
    """Все, кто уйдёт следом за этим блоком, — включая зависимых от зависимых.

    Цепочки длиннее одного звена уже есть: наклейки стоят на складе, склад на
    заявках. Выключить склад, погасив наклейки, но не тронув то, что стоит на
    наклейках, значит оставить раздел, которому не на что опереться, — ровно то,
    ради чего зависимости и заводились.

    Порядок — от дальних к ближним: гасить надо снизу вверх, иначе на середине
    цепочки окажется блок, чьё основание уже погасили.
    """
    order: list[str] = []
    seen = {key}

    def walk(current: str) -> None:
        for dependent in dependents_of(current):
            if dependent in seen:
                continue
            seen.add(dependent)
            walk(dependent)
            order.append(dependent)

    walk(key)
    return tuple(order)


def requirements_tree(key: str) -> tuple[str, ...]:
    """Всё, что должно быть включено, чтобы этот блок имел смысл.

    Порядок — от дальних к ближним: включать надо сверху вниз, основание
    раньше того, что на нём стоит.
    """
    order: list[str] = []
    seen = {key}

    def walk(current: str) -> None:
        module = BY_KEY.get(current)
        if module is None:
            return
        for required in module.requires:
            if required in seen:
                continue
            seen.add(required)
            walk(required)
            order.append(required)

    walk(key)
    return tuple(order)


# --- наборы блоков под тип дела ----------------------------------------------
#
# Человек, только что поставивший CRM, не знает, что ему нужно: он видит десяток
# переключателей с незнакомыми словами и закрывает вкладку. Тот же довод, по
# которому у воронки сделаны пресеты, а не пустой редактор.
#
# **Набор — точка отсчёта, а не режим работы.** Система НЕ запоминает тип дела и
# ничего по нему больше не решает: выбор набора — это нажатие пяти
# переключателей за один раз, и только. Заведи мы «режим розницы», и через
# полгода в коде будет тридцать развилок `if тип == ...`, каждая из которых —
# место, где система ведёт себя по-разному без очевидной причины.
#
# Состав лежит здесь, рядом с реестром блоков, а не во фронтенде: список ключей
# в `.tsx` разошёлся бы с реестром на первом же новом блоке, и заметить это было
# бы некому — ровно так однажды разошлись значки блоков между меню и настройками.


@dataclass(frozen=True)
class Preset:
    """Чем занимается бизнес — и что ему для этого включить."""

    key: str
    #: Блоки сверх несущих. Порядок не важен: включает их `modules_service`, и
    #: он же поднимает то, на чём они стоят.
    modules: tuple[str, ...]
    #: Пресет воронки из `pipeline_service.PRESETS`.
    pipeline: str
    #: Как называть заявку: `deal | order | request | booking` (см.
    #: `database/models/settings.py`). У розницы это «заказ», у мастерской —
    #: «заявка», и подписи по всей системе меняются вслед за словом.
    deal_term: str


#: Порядок — как показывать карточки при первом входе: от самого частого.
PRESETS: tuple[Preset, ...] = (
    Preset(
        key="services",
        modules=("documents", "warehouse", "tasks", "telephony", "finance"),
        pipeline="services",
        deal_term="request",
    ),
    Preset(
        key="retail",
        modules=("warehouse", "labels", "orders", "documents", "finance"),
        pipeline="shop",
        deal_term="order",
    ),
    Preset(
        key="wholesale",
        modules=("warehouse", "labels", "orders", "documents", "companies", "mail", "finance"),
        pipeline="shop",
        deal_term="order",
    ),
    Preset(
        key="production",
        modules=("warehouse", "labels", "orders", "documents", "companies", "finance"),
        pipeline="universal",
        deal_term="order",
    ),
    Preset(
        key="agency",
        modules=("boards", "tasks", "mail", "finance"),
        pipeline="agency",
        deal_term="deal",
    ),
)

PRESETS_BY_KEY: dict[str, Preset] = {preset.key: preset for preset in PRESETS}


def preset(key: str) -> Preset | None:
    return PRESETS_BY_KEY.get(key)
