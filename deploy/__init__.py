"""Автообновление боевого сайта: следит за веткой на GitHub и передеплоивает.

Пакет живёт **вне приложения** и намеренно не импортирует ни `core`, ни `web`,
ни `config`: обновляющий не может зависеть от того, что он обновляет. Он
работает на хосте, снаружи контейнеров (внутри его бы перезапустили на середине
деплоя), и обязан подняться даже тогда, когда приложение не собирается вовсе.
Отсюда же правило «только стандартная библиотека» — ни pydantic, ни httpx: на
сервере может не быть ни venv проекта, ни рабочего образа.

Слои:

* `config`  — что и куда обновляем (переменные окружения `OPENCRM_UPDATE_*`);
* `github`  — какой коммит сейчас в ветке (условный GET по ETag);
* `journal` — что развёрнуто и чем кончались прошлые попытки;
* `runner`  — запуск команд и HTTP-проверки (подменяются в тестах);
* `notify`  — сообщение в Telegram об исходе;
* `updater` — сам сценарий: проверки → бэкап → деплой → health → откат.

Точка входа для человека и cron/systemd — `scripts/autoupdate.py`.
"""
