#!/bin/sh
# Ежедневный бэкап OpenCRM: база, файлы, ключ шифрования — и проверка того,
# что получилось.
#
# Хранение: 7 ежедневных + 4 еженедельных (воскресные).
# Cron (на хосте):  0 3 * * *  /path/to/OpenCRM/scripts/backup.sh
# Для Docker-томов запускать внутри контейнера app либо примонтировав тома.
#
# **База копируется дампом `mysqldump --single-transaction`** — с одного
# согласованного снимка и без блокировки работы.
#
# **Копия включает ключ шифрования, и это осознанно.** Без OPENCRM_SECRET_KEY
# восстановленная база наполовину мертва: пароли почтовых ящиков зашифрованы им
# и не выводятся из данных (core/security/secretbox.py). Ключ, оставшийся только
# в config/.env на сгоревшем сервере, — это потеря навсегда, а не неудобство.
# Файл кладётся с правами 600 и ровно с тем, чего нельзя восстановить иначе.
#
# **Копия проверяется сразу после снятия.** Копии, которые никто не проверял, —
# это не копии, а надежда: `.backup`, оборванный на полном диске, оставляет
# файл, который выглядит как база и читается до первой битой страницы. Оборванный
# дамп MySQL выглядит ещё безобиднее — это обычный текстовый файл, и «негодность»
# у него не видна ничем, кроме отсутствующего хвоста. Узнавать об этом в день,
# когда база понадобилась, — слишком поздно.
#
# **Копия закрыта от посторонних.** Дамп базы — это вся система в одном файле:
# клиенты, хэши паролей, шифротексты почтовых ящиков. Скрипт всегда прятал файл
# ключа (600) и оставлял рядом дамп с правами 0644 — то есть читаемый любым
# пользователем машины. Проверено на стенде, поэтому маска стоит ЗДЕСЬ, до
# первого созданного файла, и под неё попадает всё: дамп, архив storage, ключ,
# отчёт проверки и сами каталоги.
set -eu
umask 077

DB_URL="${OPENCRM_DB_URL:-}"
STORAGE_DIR="${OPENCRM_STORAGE_DIR:-/app/storage}"
BACKUP_DIR="${OPENCRM_BACKUP_DIR:-/app/data/backups}"

STAMP="$(date +%Y-%m-%d)"
DOW="$(date +%u)"   # 7 = воскресенье
mkdir -p "$BACKUP_DIR/daily" "$BACKUP_DIR/weekly"

# Дамп MySQL в указанный файл.
#
# Клиента `mysqldump` в образе приложения нет: он лежит в образе базы. Поэтому
# `./opencrm.sh backup` снимает дамп заходом в контейнер базы и передаёт сюда
# уже готовый файл через OPENCRM_DB_DUMP — а имя по дате, ротацию и проверку
# годности по-прежнему делает этот скрипт, в одном месте для обеих баз. Там, где
# клиент есть (cron на хосте, стенд, машина администратора), скрипт справляется
# сам и ничего снаружи не требует.
snyat_dump() {
    _cel=$1

    if [ -n "${OPENCRM_DB_DUMP:-}" ]; then
        # Пустой файл — это оборванное снятие, а не копия. Пропустить его сюда
        # значит получить «копию» размером в ноль, о негодности которой скажет
        # только проверка, а до неё ещё дойти надо.
        [ -s "$OPENCRM_DB_DUMP" ] || {
            echo "дамп $OPENCRM_DB_DUMP пуст или отсутствует — копия не снята" >&2
            exit 1
        }
        mv "$OPENCRM_DB_DUMP" "$_cel"
        # Права — свои, а не унаследованные снаружи: `mv` переносит режим
        # исходного файла, и умаска на него уже не действует. Дамп, снятый
        # `./opencrm.sh backup` через перенаправление на хосте, приезжал бы
        # сюда с 0644.
        chmod 600 "$_cel"
        return 0
    fi

    command -v mysqldump >/dev/null 2>&1 || {
        echo "OPENCRM_DB_URL ведёт на MySQL, а клиента mysqldump здесь нет." >&2
        echo "Запускайте копирование через ./opencrm.sh backup — он снимает дамп" >&2
        echo "в контейнере базы, где клиент есть, и передаёт его сюда." >&2
        exit 1
    }

    # Разбор URL вида mysql+pymysql://user:pass@host:port/base?charset=utf8mb4
    # средствами самой оболочки: ни python, ни sed здесь не нужны, а лишняя
    # зависимость в скрипте, который зовут из cron, — лишний повод не сработать.
    #
    # Пароли для этой установки генерирует opencrm.sh в алфавите A-Za-z0-9
    # (gen_secret) именно затем, чтобы разбор был возможен: `@`, `:` и `/` в
    # пароле разрезали бы URL не там, а знак процента потребовал бы раскодировки.
    _bez_shemy=${DB_URL#*://}
    _uchetka=${_bez_shemy%%@*}
    _hvost=${_bez_shemy#*@}
    _user=${_uchetka%%:*}
    case "$_uchetka" in
        *:*) _pass=${_uchetka#*:} ;;
        *)   _pass="" ;;
    esac
    _adres=${_hvost%%/*}
    _baza=${_hvost#*/}
    _baza=${_baza%%\?*}
    _host=${_adres%%:*}
    case "$_adres" in
        *:*) _port=${_adres#*:} ;;
        *)   _port=3306 ;;
    esac

    # Пароль уходит в файл, а не в командную строку: аргументы процесса видит
    # любой пользователь машины через `ps`, и `-pПАРОЛЬ` раздал бы доступ к базе
    # всем, кто оказался рядом в момент снятия копии. Файл создаётся с правами
    # 600 и удаляется сразу, а `--defaults-extra-file` обязан идти первым
    # аргументом — иначе mysqldump его не заметит.
    _cnf=$(mktemp)
    chmod 600 "$_cnf"
    printf '[client]\nuser=%s\npassword="%s"\nhost=%s\nport=%s\n' \
        "$_user" "$_pass" "$_host" "$_port" > "$_cnf"

    # --single-transaction — то, ради чего всё это: дамп снимается с одного
    # согласованного снимка данных и НЕ блокирует работу. Без него mysqldump
    # берёт блокировку чтения на все таблицы, и сайт на время копии встаёт.
    #
    # Пайпа здесь намеренно нет (`mysqldump ... > файл`, а не `... | gzip > ...`):
    # в POSIX sh код возврата из середины пайпа не достать, и упавший на полпути
    # mysqldump выглядел бы как успешное снятие копии.
    if ! mysqldump --defaults-extra-file="$_cnf" \
        --single-transaction --routines --triggers --no-tablespaces \
        --default-character-set=utf8mb4 "$_baza" > "$_cel"; then
        rm -f "$_cnf"
        echo "mysqldump не справился — копия не снята" >&2
        exit 1
    fi
    rm -f "$_cnf"
    # Перенаправление в УЖЕ существующий файл (вчерашняя копия за тот же день)
    # сохраняет его прежние права, поэтому не полагаемся на одну умаску.
    chmod 600 "$_cel"
}

# 1) база — дампом. База одна, и ветка одна.
DB_COPY="$BACKUP_DIR/daily/db-$STAMP.sql"
snyat_dump "$DB_COPY"

# 2) storage: полный архив (файлы неизменяемые, дельта не критична для MVP)
tar -czf "$BACKUP_DIR/daily/storage-$STAMP.tar.gz" -C "$STORAGE_DIR" .

# 3) ключ шифрования и соль хэша IP — то, чего нет в базе и что не выводится
#    из неё ничем. Соль нужна, чтобы после восстановления просмотры витрины
#    считались теми же людьми, а не начались с чистого листа.
SECRET_FILE="$BACKUP_DIR/daily/secret-$STAMP.env"
{
    echo "# Ключи OpenCRM на $STAMP. Без них восстановление неполное:"
    echo "# пароли почтовых ящиков зашифрованы OPENCRM_SECRET_KEY и без него"
    echo "# не расшифровываются НИКОГДА."
    echo "OPENCRM_SECRET_KEY=${OPENCRM_SECRET_KEY:-}"
    echo "OPENCRM_IP_HASH_SALT=${OPENCRM_IP_HASH_SALT:-}"
} > "$SECRET_FILE"
chmod 600 "$SECRET_FILE"

# 4) воскресный бэкап дублируем в weekly
if [ "$DOW" = "7" ]; then
    cp "$DB_COPY" "$BACKUP_DIR/weekly/"
    cp "$BACKUP_DIR/daily/storage-$STAMP.tar.gz" "$BACKUP_DIR/weekly/"
    cp "$SECRET_FILE" "$BACKUP_DIR/weekly/"
fi

# 5) ротация: daily > 7 дней, weekly > 28 дней
find "$BACKUP_DIR/daily" -type f -mtime +7 -delete
find "$BACKUP_DIR/weekly" -type f -mtime +28 -delete

# `db-before-restore-*.sql` кладёт рядом scripts/restore.sh — это полный дамп
# базы ПЕРЕД заливкой, единственный путь назад из неудачного восстановления.
# Ротации у него не было вовсе: каждое восстановление оставляло на диске ещё
# одну полную базу навсегда. Место кончается тихо, а кончившееся место — ровно
# то, из-за чего обрывается следующий дамп. Держим месяц: откат неудачного
# восстановления делают в тот же день, а не через год.
find "$BACKUP_DIR" -maxdepth 1 -type f -name 'db-before-restore-*.sql' -mtime +28 -delete

# Права у ВСЕХ копий, а не только у сегодняшних: каталог мог накопить файлы от
# прежних версий скрипта, снятых с прежней умаской, и «дамп базы читает кто
# угодно» — это не то, что чинится только для новых файлов.
#
# **Но только у СВОИХ файлов, и падать из-за чужих нельзя.**
#
# Копии в этом каталоге бывают двух владельцев, и это не поломка установки, а
# устройство: `./opencrm.sh backup` создаёт дамп НА ХОСТЕ (там же и закрывает
# его правами 600), а этот скрипт работает ВНУТРИ контейнера под `opencrm` и
# переносит готовый файл в `daily/`. Перенос владельца не меняет. Значит уже со
# второго захода `chmod` встречает файлы прошлых заходов, которые ему не
# подчиняются:
#
#     chmod: changing permissions of '/app/data/backups/daily/db-2026-08-23.sql':
#            Operation not permitted
#
# Само по себе это пустяк — файлы и так лежат с правами 600. Беда в том, что
# было дальше: при `set -eu` ненулевой код `find` ОБРЫВАЛ ВЕСЬ СКРИПТ прямо
# здесь, а следующим шагом идёт проверка годности копии. То есть каждая копия,
# кроме самой первой, оставалась НЕПРОВЕРЕННОЙ — ровно то состояние, которое
# шапка этого файла объявляет недопустимым: «копии, которые никто не проверял,
# — это не копии, а надежда». Найдено по журналу боевого сервера: семь ошибок
# `chmod` и сразу приглашение оболочки, без строки `backup done`.
#
# Гигиена прав не имеет права стоить проверки копии. Поэтому: правим своё,
# чужое не трогаем, о чужом молчим — если оно и так закрыто.
find "$BACKUP_DIR/daily" "$BACKUP_DIR/weekly" \
    -type f -user "$(id -u)" -exec chmod 600 {} + || true

# А вот если чужой файл вправду открыт наружу — сказать надо, и с числом.
#
# Молчать здесь нельзя: дамп базы, читаемый любым пользователем машины, — это
# вся система в одном файле. Но и падать нельзя: поправить его мы всё равно не
# можем, а копия уже снята и ждёт проверки.
_otkrytyh=$(find "$BACKUP_DIR/daily" "$BACKUP_DIR/weekly" \
    -type f ! -user "$(id -u)" -perm /0077 2>/dev/null | wc -l)
if [ "$_otkrytyh" -gt 0 ]; then
    echo "backup: $_otkrytyh копий чужого владельца открыты на чтение посторонним." >&2
    echo "backup: поправьте на хосте — chmod 600 <каталог копий>/daily/* weekly/*" >&2
fi

# 6) проверка того, что получилось. Отказ здесь — отказ всего скрипта: копия,
#    о негодности которой не сказали, хуже отсутствия копии, потому что на неё
#    рассчитывают. Проверка сама разбирается, файл перед ней или дамп.
python -m scripts.verify_backup \
    "$DB_COPY" \
    "$BACKUP_DIR/daily/storage-$STAMP.tar.gz" \
    "$SECRET_FILE"

# 7) «копию давно не забирали».
#
# Все копии, снятые выше, лежат на ТОМ ЖЕ ДИСКЕ, что и база. От ошибки человека
# они спасают, от смерти диска, пожара и шифровальщика — нет: то и другое унесёт
# их вместе с базой. Пока увоз ручной (ни S3, ни чужого облака мы не заводим —
# разбор в docs/15-backup-encryption.md), единственная защита — сказать вслух, и
# сказать заранее, а не в день аварии.
#
# Отметка увоза — mtime файла `last-export`: сам увоз следа не оставляет, а
# скачавший копию человек (или строка выгрузки ниже) обязан отметиться. Молчание
# здесь означало бы «всё хорошо», чего мы как раз не знаем.
UVOZ_DNEY="${OPENCRM_BACKUP_EXPORT_DAYS:-7}"
OTMETKA_UVOZA="$BACKUP_DIR/last-export"
if [ ! -e "$OTMETKA_UVOZA" ]; then
    echo "backup: копии с этой машины не забирали НИ РАЗУ — все они лежат на том" >&2
    echo "backup: же диске, что и база, и умрут вместе с ним." >&2
    echo "backup: заберите копию себе и отметьте увоз: touch $OTMETKA_UVOZA" >&2
elif [ -n "$(find "$OTMETKA_UVOZA" -maxdepth 0 -mtime "+$UVOZ_DNEY" 2>/dev/null || true)" ]; then
    echo "backup: копию не забирали больше $UVOZ_DNEY дней — на диске рядом с базой" >&2
    echo "backup: она защищает только от ошибки человека, но не от гибели машины." >&2
    echo "backup: заберите копию себе и отметьте увоз: touch $OTMETKA_UVOZA" >&2
fi

# 8) (опционально) выгрузка наружу — раскомментировать и настроить.
#    Наружу уезжает только ЗАШИФРОВАННОЕ: дамп — вся система в одном файле, и
#    едущий рядом secret-*.env расшифровывает остальное. Файл ключа копии
#    заводится один раз (`--sozdat-klyuch`) и хранится НЕ ЗДЕСЬ: потерянный
#    вместе с диском ключ означает потерянную копию.
# python -m scripts.verify_backup --zashifrovat \
#     "$DB_COPY" "/tmp/$(basename "$DB_COPY").enc" \
#     --klyuch-fayl "$OPENCRM_BACKUP_KEY_FILE"
# rclone copy "/tmp/$(basename "$DB_COPY").enc" remote:opencrm-backups/
# touch "$OTMETKA_UVOZA"   # без этой строки предупреждение выше не замолчит

echo "backup done: $STAMP"
