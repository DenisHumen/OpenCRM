"""Отправить утреннюю сводку. Точка входа для расписания и для человека.

Запускается так:

    docker compose exec -T app python -m scripts.svodka

**Почему изнутри контейнера приложения, а не с машины.** Цифры считаются
репозиториями — тем же кодом, что отвечает экранам. Второй счёт «снаружи»
означал бы два места, где считается одно и то же, и разошлись бы они молча:
сводка показывала бы одно, отчёт другое, и какое из двух верно, спросить было
бы не у кого.

**Почему отдельным процессом, а не по расписанию внутри веб-сервера.** Тогда
расписание жило бы в памяти рабочего процесса и умножалось бы на их число:
двое рабочих — две сводки. Отдельный запуск по часам решает это без единой
строки согласования.

Свойство, ради которого всё это существует, простое: **молчание сводки — уже
тревога**. Пришла — значит жив и сервер, и база, и бот; не пришла — значит
что-то из этого нет, и узнать об этом иначе неоткуда.
"""

from __future__ import annotations

import logging
import sys

from core.services import svodka_service
from database.session import SessionLocal

logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")


def main() -> int:
    with SessionLocal() as db:
        itog = svodka_service.otpravit(db)

    if itog["status"] == "sent":
        # Разделы, которые не сосчитались, называем в выводе: расписание пишет
        # его в журнал, и там это единственное место, где такое видно.
        if itog.get("otkazy"):
            print("сводка ушла, но не всё сосчиталось: " + ", ".join(itog["otkazy"]))
        else:
            print("сводка ушла")
        return 0

    if itog["status"] == "skipped":
        # Не настроено — не отказ. Расписание не должно краснеть у того, кто
        # телеграмом не пользуется.
        print(f"сводка не отправлялась: {itog['reason']}")
        return 0

    print(f"сводка не ушла: {itog.get('error', 'причина неизвестна')}", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
