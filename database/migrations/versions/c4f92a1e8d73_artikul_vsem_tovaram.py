"""Артикул выдаётся всем товарам и становится обязательным.

До этой ревизии `products.sku` был `nullable`, и в модели стоял довод: «два
товара без артикула — норма». Владелец правило отменил (разбор —
`docs/19-sborka-zakaza.md` §Р1): артикула без товара не бывает, потому что по
нему товар ищут сканом, называют по телефону и складывают в строку заявки.

**Что здесь опасного.** Колонку с `UNIQUE` нельзя просто объявить `NOT NULL` на
населённой базе: у существующих товаров артикула нет, и первая же такая строка
положит миграцию. Причём заполнить их одним значением тоже нельзя — оно обязано
быть РАЗНЫМ у каждого. Отсюда порядок: посчитать, с какого номера продолжать →
один `UPDATE` с оконной функцией → ужесточение.

**Почему одним запросом, а не обходом через ORM.** Обход означал бы по одному
round-trip'у на товар внутри окна обновления, когда сайт уже не отвечает.
`ROW_NUMBER() OVER (ORDER BY id)` выдаёт разные номера всем строкам за один
проход, и порядок по `id` делает выдачу повторяемой: перезапуск миграции на той
же базе даст те же артикулы тем же товарам.

**Откуда берётся начальный номер.** Ручной артикул `A-000123` уже мог быть
заведён руками, и продолжать с единицы значило бы упереться в него уникальным
индексом посреди `UPDATE`. Поэтому счёт продолжается с максимума среди
подходящих под наш вид — ровно та же выборка, что у `warehouse_repo.max_vydannogo_sku`:
диапазон между `A-000000` и `A-999999` при побайтном сравнении (`utf8mb4_bin`)
не пропускает ни `ZX-9`, ни `A-B00000`.

**Проверено на НАСЕЛЁННОЙ базе.** Набор тестов поднимает схему с нуля и
наполняет её после, то есть `UPDATE` там идёт по нулю строк и не доказывает
ничего. Отдельный прогон: MySQL 8, база на предыдущей ревизии, 50 000 товаров
без артикула плюс четыре ручных — `A-000123` (наш вид), `ZX-9` (чужой),
`A-777` (короткий) и `A-B00000` (буква вместо цифры):

    накат            7,4 с (вместе с запуском alembic)
    строк            50 004 было → 50 004 стало, ни одной потерянной
    пустых           ноль — колонка вправду NOT NULL
    уникальность     50 004 разных артикула на 50 004 строки
    выдано           A-000124 … A-050123 — счёт продолжился ПОСЛЕ ручного
    ручные           все четыре на месте, ни один не переписан
    сравнение        utf8mb4_bin уцелело после ALTER
    откат            колонка снова nullable, все 50 004 артикула на месте

Три ручных из четырёх (`ZX-9`, `A-777`, `A-B00000`) счётчик не сдвинули, и это
главное, что доказывает прогон: похожий на наш, но не наш артикул не должен
уводить нумерацию — иначе `A-777` превратил бы следующий выданный в `A-000778`.

**Откат не стирает артикулы.** `downgrade` возвращает колонке `nullable` и на
этом останавливается: выданные артикулы уже наклеены на коробки в углу склада, и
откат схемы не должен сдирать наклейки. Цена — после отката и повторного наката
номера не выдадутся заново, они уже стоят; это ровно то, чего мы хотим.

Revision ID: c4f92a1e8d73
Revises: b8d41f7a2c95
"""

