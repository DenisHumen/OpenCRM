"""Артикул выдаётся всем товарам и становится обязательным.

До этой ревизии `products.sku` был `nullable`, и в модели стоял довод: «два
товара без артикула — норма». Владелец правило отменил (разбор —
`docs/19-sborka-zakaza.md` §Р1): артикула без товара не бывает, потому что по
нему товар ищут сканом, называют по телефону и складывают в строку заявки.

**Что здесь опасного.** Колонку с `UNIQUE` нельзя просто объявить `NOT NULL` на
населённой базе: у существующих товаров артикула нет, и первая же такая строка
положит миграцию. Причём заполнить их одним значением тоже нельзя — оно обязано
быть РАЗНЫМ у каждого. Отсюда порядок: посчитать, с какого номера продолжать →
один `UPDATE` с оконной функцией → ужесточение.

**Почему одним запросом, а не обходом через ORM.** Обход означал бы по одному
round-trip'у на товар внутри окна обновления, когда сайт уже не отвечает.
`ROW_NUMBER() OVER (ORDER BY id)` выдаёт разные номера всем строкам за один
проход, и порядок по `id` делает выдачу повторяемой: перезапуск миграции на той
же базе даст те же артикулы тем же товарам.

**Откуда берётся начальный номер.** Ручной артикул `A-000123` уже мог быть
заведён руками, и продолжать с единицы значило бы упереться в него уникальным
индексом посреди `UPDATE`. Поэтому счёт продолжается с максимума среди
подходящих под наш вид, и вид этот задан образцом — та же примета, что у
`warehouse_repo.max_vydannogo_sku`. Ни `ZX-9`, ни `A-777`, ни `A-0000420` под
неё не подходят и счёт не двигают.

**Проверено на НАСЕЛЁННОЙ базе.** Набор тестов поднимает схему с нуля и
наполняет её после, то есть `UPDATE` там идёт по нулю строк и не доказывает
ничего. Отдельный прогон: MySQL 8, база на предыдущей ревизии, 50 000 товаров
без артикула плюс четыре ручных — `A-000123` (наш вид), `ZX-9` (чужой),
`A-777` (короткий) и `A-B00000` (буква вместо цифры):

    накат            7,4 с (вместе с запуском alembic)
    строк            50 004 было → 50 004 стало, ни одной потерянной
    пустых           ноль — колонка вправду NOT NULL
    уникальность     50 004 разных артикула на 50 004 строки
    выдано           A-000124 … A-050123 — счёт продолжился ПОСЛЕ ручного
    ручные           все четыре на месте, ни один не переписан
    сравнение        utf8mb4_bin уцелело после ALTER
    откат            колонка снова nullable, все 50 004 артикула на месте

Три ручных из четырёх (`ZX-9`, `A-777`, `A-B00000`) счётчик не сдвинули, и это
главное, что доказывает прогон: похожий на наш, но не наш артикул не должен
уводить нумерацию — иначе `A-777` превратил бы следующий выданный в `A-000778`.

**Откат не стирает артикулы.** `downgrade` возвращает колонке `nullable` и на
этом останавливается: выданные артикулы уже наклеены на коробки в углу склада, и
откат схемы не должен сдирать наклейки. Цена — после отката и повторного наката
номера не выдадутся заново, они уже стоят; это ровно то, чего мы хотим.

Revision ID: c4f92a1e8d73
Revises: b8d41f7a2c95
"""

from typing import Sequence, Union

import sqlalchemy as sa
from alembic import op

from database.types import ExactString

revision: str = "c4f92a1e8d73"
down_revision: Union[str, None] = "b8d41f7a2c95"
branch_labels: Union[str, Sequence[str], None] = None
depends_on: Union[str, Sequence[str], None] = None

#: Приставка и длина номера — те же, что у `warehouse_service`. Продублированы
#: сознательно: миграция обязана работать и тогда, когда код сервиса уехал
#: вперёд, а база откатилась назад.
PRISTAVKA = "A-"
ZNAKOV = 6


def upgrade() -> None:
    svyaz = op.get_bind()

    # 1. С какого номера продолжать. Образцом, а не «верхние полсотни строк
    #    диапазона»: `A-0000420` — семь цифр вместо шести — при побайтном
    #    сравнении стоит ВЫШЕ любого нашего и остаётся в диапазоне. Полсотни
    #    таких заслонили бы настоящий максимум, счёт пошёл бы с единицы и первый
    #    же `UPDATE` упёрся бы в уникальный индекс — то есть обновление боевого
    #    сервера откатилось бы посреди миграции.
    ot_kakogo = (
        svyaz.execute(
            sa.text(
                "SELECT MAX(CAST(SUBSTRING(sku, :ot) AS UNSIGNED)) FROM products"
                f" WHERE sku REGEXP '^{PRISTAVKA}[0-9]{{{ZNAKOV}}}$'"
            ),
            {"ot": len(PRISTAVKA) + 1},
        ).scalar()
        or 0
    )

    # 2. Хватит ли диапазона. `LPAD` строку ДЛИННЕЕ заданной длины не дополняет,
    #    а ОБРЕЗАЕТ: `LPAD('1000000', 6, '0')` = `'100000'`, и следующий номер
    #    даёт то же самое. Значит переполнение вылезло бы не отказом, а
    #    `Duplicate entry` посреди наката — с половиной товаров, уже получивших
    #    артикул. Спрашиваем заранее и называем виновника: сам по себе
    #    `sku_exhausted` не подсказывает, где искать.
    bez_sku = (
        svyaz.execute(sa.text("SELECT COUNT(*) FROM products WHERE sku IS NULL")).scalar()
        or 0
    )
    potolok = 10**ZNAKOV - 1
    if ot_kakogo + bez_sku > potolok:
        raise RuntimeError(
            f"диапазон артикулов не вмещает выдачу: счёт пошёл бы с {ot_kakogo + 1}, "
            f"товаров без артикула {bez_sku}, потолок {PRISTAVKA}{potolok}. "
            f"Обычная причина — артикул нашего вида, набранный руками у верхней границы: "
            f"SELECT id, sku FROM products WHERE sku REGEXP '^{PRISTAVKA}[0-9]{{{ZNAKOV}}}$' "
            f"ORDER BY sku DESC LIMIT 5; — переименуйте его и повторите обновление"
        )

    # 3. Один `UPDATE` на всех. `LPAD` даёт ту же ширину номера, что и сервис:
    #    артикул сортируется как число, пока ширина одна.
    op.execute(
        sa.text(
            "UPDATE products p"
            " JOIN (SELECT id, ROW_NUMBER() OVER (ORDER BY id) AS n"
            "       FROM products WHERE sku IS NULL) t ON t.id = p.id"
            f" SET p.sku = CONCAT('{PRISTAVKA}', LPAD(t.n + {ot_kakogo}, {ZNAKOV}, '0'))"
        )
    )

    # 4. Ужесточаем по уже заполненным данным. Тип повторён точь-в-точь: MySQL
    #    пересоздаёт колонку целиком, и `String(64)` вместо `ExactString(64)`
    #    молча вернул бы регистронезависимое сравнение — `ABC` и `abc` слились
    #    бы в один артикул, а уникальный индекс начал бы отвергать законно
    #    разные.
    with op.batch_alter_table("products") as batch:
        batch.alter_column("sku", existing_type=ExactString(64), nullable=False)


def downgrade() -> None:
    # Только послабление. Выданные артикулы остаются: см. шапку файла.
    with op.batch_alter_table("products") as batch:
        batch.alter_column("sku", existing_type=ExactString(64), nullable=True)
