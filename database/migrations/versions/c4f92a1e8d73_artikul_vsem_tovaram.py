#: Приставка и длина номера — те же, что у `warehouse_service`. Продублированы
#: сознательно: миграция обязана работать и тогда, когда код сервиса уехал
#: вперёд, а база откатилась назад.
PRISTAVKA = "A-"
ZNAKOV = 6


def upgrade() -> None:
    svyaz = op.get_bind()

    # 1. С какого номера продолжать. Диапазон, а не образец: сравнение побайтное,
    #    и всё между `A-000000` и `A-999999` — либо наш номер, либо ручная
    #    подделка под него, которую отсеет проверка на цифры.
    nizhniy, verhniy = PRISTAVKA + "0" * ZNAKOV, PRISTAVKA + "9" * ZNAKOV
    vydannye = svyaz.execute(
        sa.text(
            "SELECT sku FROM products WHERE sku >= :n AND sku <= :v"
            " ORDER BY sku DESC LIMIT 50"
        ),
        {"n": nizhniy, "v": verhniy},
    ).scalars()
    ot_kakogo = 0
    for sku in vydannye:
        hvost = sku[len(PRISTAVKA):]
        if len(hvost) == ZNAKOV and hvost.isdigit():
            ot_kakogo = int(hvost)
            break

    # 2. Один `UPDATE` на всех. `LPAD` даёт ту же ширину номера, что и сервис:
    #    артикул сортируется как число, пока ширина одна.
    op.execute(
        sa.text(
            "UPDATE products p"
            " JOIN (SELECT id, ROW_NUMBER() OVER (ORDER BY id) AS n"
            "       FROM products WHERE sku IS NULL) t ON t.id = p.id"
            f" SET p.sku = CONCAT('{PRISTAVKA}', LPAD(t.n + {ot_kakogo}, {ZNAKOV}, '0'))"
        )
    )

    # 3. Ужесточаем по уже заполненным данным. Тип повторён точь-в-точь: MySQL
    #    пересоздаёт колонку целиком, и `String(64)` вместо `ExactString(64)`
    #    молча вернул бы регистронезависимое сравнение — `ABC` и `abc` слились
    #    бы в один артикул, а уникальный индекс начал бы отвергать законно
    #    разные.
    with op.batch_alter_table("products") as batch:
        batch.alter_column("sku", existing_type=ExactString(64), nullable=False)


