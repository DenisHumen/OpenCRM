"""Типы колонок, у которых поведение MySQL надо задать явно.

Три места MySQL решает по-своему, и каждое молчаливо портит данные или ломает
защиту: сравнение строк (регистр и хвостовые пробелы), длина ключа под индексом,
умолчание у TEXT. Здесь они собраны одним списком, чтобы это было свойством
схемы, а не памяти того, кто её пишет.
"""

from sqlalchemy import DateTime, String, Text, text
from sqlalchemy.dialects import mysql
from sqlalchemy.ext.compiler import compiles

#: Строка, которую сравнивают ПОБАЙТНО. Для токенов и хэшей.
#:
#: **Это не про аккуратность, а про доступ.** Сравнение строк в MySQL по
#: умолчанию регистронезависимо (`utf8mb4_0900_ai_ci`), а токен сессии и токен
#: ссылки на витрину — случайные строки в base64, где регистр значащий. С
#: регистронезависимым сравнением `AbC` и `abc` становятся одним значением:
#: во-первых, `UNIQUE` отвергает законно разные токены, во-вторых — и это
#: хуже — поиск сессии по токену находит ЧУЖУЮ, отличающуюся только регистром.
#: Перебор при этом дешевеет в 2^N раз по числу букв.
#:
#: Побайтное сравнение — иначе MySQL считает «Иванов» и «ИВАНОВ» одной строкой.
def ExactString(length: int):  # noqa: N802 — имя типа, а не функции
    return String(length).with_variant(
        mysql.VARCHAR(length, collation="utf8mb4_bin"), "mysql"
    )


#: Длинный текст: тела писем, снимки для печати, вложенный JSON.
#:
#: `TEXT` в MySQL — 65 535 **байт**, а не символов: кириллица в utf8mb4 занимает
#: два байта, эмодзи четыре. Письмо на 40 тысяч знаков русского текста уже не
#: помещается, и MySQL либо отвечает «Data too long», либо (в нестрогом режиме)
#: **молча обрезает** — и обрезает посреди HTML, отчего письмо перестаёт
#: открываться. `MEDIUMTEXT` даёт 16 МБ, чего хватает с запасом.
LongText = Text().with_variant(mysql.MEDIUMTEXT(), "mysql")


#: Время с долями секунды — правило для ВСЕХ колонок сразу.
#:
#: `DATETIME` в MySQL без указания точности хранит целые секунды и **округляет**
#: доли, причём вверх: событие в 12:00:00.7 ложится как 12:00:01, то есть в
#: будущее. Две записи одной секунды получают одинаковое время, и лента событий
#: — которую читают именно как последовательность — выстраивается случайно.
#:
#: Правило объявлено один раз для типа, а не расставлено по колонкам. Колонок с
#: временем под сотню в двадцати файлах моделей и двух десятках миграций;
#: расставленное руками правило живёт до первой новой колонки, про которую
#: забудут, а забытая колонка ничем себя не проявляет — она просто тихо теряет
#: доли секунды. Здесь же его нельзя забыть: оно применяется к типу.
#:
#: Объявлено вариантом диалекта: в схеме видно, что правило именно про MySQL.
@compiles(DateTime, "mysql")
def _datetime_s_mikrosekundami(type_, compiler, **kw):
    return "DATETIME(6)"



def text_default(value: str = ""):
    """`server_default` для колонки TEXT — в форме, которую MySQL принимает.

    MySQL **запрещает** обычный `DEFAULT` у TEXT/BLOB: `TEXT NOT NULL DEFAULT ''`
    отвергается с ошибкой 1101, и миграция обрывается на середине. Форму же
    `DEFAULT ('')` — значение по умолчанию как выражение — MySQL 8.0.13 и новее
    принимает, и в `CREATE TABLE`, и в `ALTER TABLE ADD COLUMN`.

    Проверено на MySQL 8.0.46: вставка без колонки даёт пустую строку.
    """
    return text("('{}')".format(value.replace("'", "''")))
