"""Что база может рассказать о себе самой: размер, движок.

Здесь, а не в `web/`, по той же причине, что и всё остальное: запросы живут
только в `database/` (CLAUDE.md, раздел 3). Прежде размер базы собирался прямо в
`web/api/routes/metrics.py` — и только как `stat()` по файлу базы, потому что
спросить о размере сервер было нечем: запрос в маршруте нарушил бы границу.

Из-за этого метрика `opencrm_database_size_bytes` просто ИСЧЕЗАЛА: файла нет —
и точки на графике нет. Молчание само по себе выбрано осознанно (ноль выглядит
как «база исчезла»), но молчать всегда — значит не следить за ростом базы вовсе.
"""

from sqlalchemy import func, select, text
from sqlalchemy.orm import Session


def database_size_bytes(db: Session) -> int | None:
    """Сколько места занимает база вместе с индексами. `None` — не спросить.

    **Ответ спрашивается у сервера.** Отсюда и проверка движка ниже: она стоит
    не ради выбора между базами — выбора нет, — а ради того, чтобы запрос про
    `information_schema` не улетел в сессию, привязанную к чему-то другому.
    Метрики собираются в фоне, и отказ там замечают последним, а «не спросить»
    — законный исход этой функции, описанный ниже.

    Числа `information_schema` — оценка, а не замер: InnoDB считает их по
    выборке страниц, и разойтись с `du` они могут заметно. Для метрики этого
    достаточно — смотрят на неё ради ТЕНДЕНЦИИ («база выросла вдвое за неделю»),
    а не ради точного числа байтов. Точный ответ стоил бы `ANALYZE TABLE` по
    всем таблицам, то есть блокировок на боевом сервере ради графика.

    `None` вместо нуля намеренно: ноль на графике неотличим от «база исчезла», а
    отсутствие точки видно как отсутствие.
    """
    if db.bind.dialect.name != "mysql":
        return None
    # DATABASE() — та база, к которой мы подключены: имя не подставляется из
    # настроек, и подставить туда чужое имя неоткуда.
    zapros = select(
        func.coalesce(func.sum(text("data_length + index_length")), 0)
    ).select_from(text("information_schema.tables")).where(
        text("table_schema = DATABASE()")
    )
    razmer = db.scalar(zapros)
    return int(razmer) if razmer else None
