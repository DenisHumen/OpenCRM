"""Финансы: статьи, операции, бюджеты.

Главное решение блока — **прибыль не хранится**. Её нет ни в статье, ни в
бюджете, ни отдельной таблицей «итоги месяца»: прибыль равна сумме операций за
период и считается запросом (`database/repositories/finance.py`). Довод тот же,
что у остатка склада: хранимый итог однажды разойдётся с историей — из-за
отката транзакции, из-за операции задним числом, из-за второго процесса, — и
сойтись обратно не сможет, потому что неоткуда узнать, какая из двух цифр
правильная. Сумма операций неверной быть не может по построению.

То же правило распространяется на всё производное: факт по бюджету, разбивку по
статьям, налоговую и зарплатную части. Ни одно из этих чисел не лежит в базе.

**Знак живёт на операции, направление — на статье.** Это два разных сведения, и
путать их нельзя:

- `finance_categories.direction` отвечает, к чему относится статья: «Выручка» —
  доход, «Аренда» — расход. Это свойство справочника, оно не меняется от строки
  к строке.
- `finance_operations.amount_minor` — знаковое: доход хранится плюсом, расход
  минусом. Тогда прибыль за период это `SUM(amount_minor)` — одно выражение без
  единого `CASE`, ровно как остаток склада.

Знак обычной операции задаёт направление её статьи (ставит его сервис), но
совпадать они обязаны не всегда: возврат по расходной статье — это плюс по
расходу, а не доход. Поэтому «сколько потрачено» считается по направлению
СТАТЬИ, а не по знаку суммы; иначе первый же возврат аренды уехал бы в выручку.
Приём тот же, что у склада: вид движения — свойство операции, а знак задаёт само
движение.
"""

from datetime import date, datetime

from sqlalchemy import (
    Date,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column
from sqlalchemy.sql import func

from database.session import Base
from database.types import text_default

#: Направление статьи. Ключи стабильные — уходят в базу и в фильтры, подписи
#: переводятся на фронтенде.
DIRECTION_INCOME = "income"
DIRECTION_EXPENSE = "expense"
DIRECTIONS = (DIRECTION_INCOME, DIRECTION_EXPENSE)

#: Особый род статьи: налоги и зарплата.
#:
#: Одним полем с тремя значениями, а не двумя булевыми признаками. Два флажка
#: разрешают состояние «и налог, и зарплата», которого не бывает, — и первый же
#: отчёт, разложивший расходы на «налоги / зарплата / прочее», посчитал бы такую
#: статью дважды. Взаимоисключающие свойства описываются одним полем.
PURPOSE_GENERAL = "general"
PURPOSE_TAX = "tax"
PURPOSE_SALARY = "salary"
PURPOSES = (PURPOSE_GENERAL, PURPOSE_TAX, PURPOSE_SALARY)

#: Потолок одной суммы в минорных единицах — двадцать миллионов в валюте счёта.
#:
#: Число взято не с потолка и не из представлений о том, сколько бывает денег:
#: это то, что помещается в колонку. В SQLite INTEGER — до 8 байт, а в MySQL
#: INT — **4 байта**, то есть 2 147 483 647 минорных единиц. Операция крупнее
#: туда просто не влезет, и узнать об этом на переезде, а не сейчас, было бы
#: худшим из вариантов.
#:
#: Итог при этом не ограничен: `SUM` в MySQL расширяется до BIGINT сам, поэтому
#: годовая прибыль складывается без потолка — предел стоит на отдельной строке.
#: Понадобится больше на одну операцию — колонку расширяют до BigInteger, и это
#: обычная добавочная миграция.
MAX_AMOUNT_MINOR = 2_000_000_000


class FinanceCategory(Base):
    """Статья доходов или расходов: «Выручка», «Аренда», «Зарплата», «Налоги».

    Статья — единственная ось, по которой прибыль вообще можно разложить.
    Поэтому она обязательна у каждой операции: операция без статьи попадала бы в
    итог, но выпадала из разбивки, и сумма строк не сходилась бы с числом сверху.
    Расхождение двух чисел на одном экране — самый быстрый способ перестать
    верить отчёту целиком.

    **Удаление мягкое.** На статью ссылаются операции и бюджеты, а история денег
    не должна исчезать вместе со строкой справочника. Статью с операциями не
    удаляют, а закрывают — как склад.

    Уникальности имени здесь нет намеренно. Обычный `UNIQUE` запретил бы завести
    «Аренду» заново после того, как прошлую закрыли, — то есть запретил бы
    нормальный случай; а «уникально среди незакрытых» — это частичный индекс,
    которого в MySQL не существует (тот же довод, что у основной фирмы и
    основного склада). Разбирается это на уровне здравого смысла в интерфейсе, а
    не запретом в схеме.
    """

    __tablename__ = "finance_categories"

    id: Mapped[int] = mapped_column(primary_key=True)
    name: Mapped[str] = mapped_column(String(200))
    #: `income` | `expense` — см. DIRECTIONS.
    direction: Mapped[str] = mapped_column(String(16))
    #: `general` | `tax` | `salary` — см. PURPOSES.
    purpose: Mapped[str] = mapped_column(
        String(16), default=PURPOSE_GENERAL, server_default=PURPOSE_GENERAL
    )
    note: Mapped[str] = mapped_column(Text, default="", server_default=text_default())
    created_at: Mapped[datetime] = mapped_column(DateTime, server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(
        DateTime, server_default=func.now(), onupdate=func.now()
    )
    #: Мягкое удаление: закрытая статья пропадает из выбора, но её прошлые
    #: операции остаются и продолжают считаться в прибыли за прошлые периоды.
    deleted_at: Mapped[datetime | None] = mapped_column(DateTime, nullable=True, index=True)

    __table_args__ = (
        # Справочник читают ровно одним способом: сначала доходные статьи, потом
        # расходные, внутри — по алфавиту. Составной индекс отдаёт список уже
        # разложенным, отдельный индекс по имени такого не умеет.
        Index("ix_finance_categories_direction_name", "direction", "name"),
    )


class FinanceOperation(Base):
    """Одна операция: пришли деньги или ушли. Складывая их, получаем прибыль.

    **Операция не правится и не удаляется.** Ошибку исправляют обратной
    операцией — суммой с противоположным знаком по той же статье. Правка задним
    числом означала бы, что прибыль за прошлый квартал зависит от того, когда её
    спросили: сегодня отчёт показал одно, завтра — другое, и объяснить это
    нечем. Ровно то же правило и по той же причине действует у движений склада.

    Отсюда же следует, чего в блоке нет: `finance.edit` и `finance.delete` не
    объявлены вовсе (`core/permissions.py`), потому что права, которые ничего не
    дают, хуже их отсутствия. Справочник статей и бюджеты правятся под
    `finance.manage`.

    Связи с заявкой, клиентом и фирмой необязательны, и это не недоделка.
    «Аренда за август» не относится ни к какой заявке и ни к какому клиенту;
    требовать их значило бы заставлять выдумывать привязку, а выдуманная связь
    хуже отсутствующей — по ней потом строят отчёт.
    """

    __tablename__ = "finance_operations"

    id: Mapped[int] = mapped_column(primary_key=True)
    # RESTRICT: статья — это то, во что операция попадает в отчёте, и удалить
    # её вместе с операциями значит бесшумно переписать прибыль за прошлые
    # периоды. Штатный путь — закрытие статьи (`deleted_at`); ключ здесь стоит
    # на случай прямого DELETE в базе.
    category_id: Mapped[int] = mapped_column(
        ForeignKey("finance_categories.id", ondelete="RESTRICT")
    )
    # Знаковое: доход +, расход −. Прибыль = SUM(amount_minor), поэтому вычитать
    # при чтении ничего не нужно и перепутать знак негде. Деньги — целые в
    # минорных единицах (копейки/центы) и через float не проходят ни на секунду.
    amount_minor: Mapped[int] = mapped_column(Integer)
    comment: Mapped[str] = mapped_column(Text, default="", server_default=text_default())
    # Когда деньги двинулись на самом деле — и отдельно когда о них узнала база.
    # Финансы заполняют пачкой в конце недели, и период отчёта обязан считаться
    # по первой дате, иначе выручка пятницы уедет в следующий месяц.
    happened_at: Mapped[datetime] = mapped_column(DateTime, server_default=func.now())
    created_at: Mapped[datetime] = mapped_column(DateTime, server_default=func.now())
    # SET NULL у всех трёх связей: деньги получены или потрачены, и удаление
    # карточки этого не отменяет. CASCADE унёс бы операцию вместе с заявкой, и
    # прибыль за прошлый месяц изменилась бы сама собой.
    deal_id: Mapped[int | None] = mapped_column(
        ForeignKey("deals.id", ondelete="SET NULL"), nullable=True, index=True
    )
    client_id: Mapped[int | None] = mapped_column(
        ForeignKey("clients.id", ondelete="SET NULL"), nullable=True, index=True
    )
    company_id: Mapped[int | None] = mapped_column(
        ForeignKey("companies.id", ondelete="SET NULL"), nullable=True, index=True
    )
    author_id: Mapped[int | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"), nullable=True, index=True
    )

    __table_args__ = (
        # Разбивка прибыли по статьям — это `SUM(amount_minor) GROUP BY
        # category_id` в границах периода, и сумма обязана лежать в самом
        # индексе. Иначе база проходит операции по статье, но за каждым числом
        # лезет в таблицу: сто тысяч случайных чтений ради одной строки отчёта.
        Index(
            "ix_finance_ops_category_happened",
            "category_id",
            "happened_at",
            "amount_minor",
        ),
        # Прибыль целиком и журнал за период — тот же довод, но без статьи:
        # отбор идёт по дате, а сумма и здесь читается прямо из индекса.
        Index("ix_finance_ops_happened_amount", "happened_at", "amount_minor"),
    )


class FinanceBudget(Base):
    """План по статье на период. Факт рядом с ним НЕ хранится — он считается.

    Соблазн держать здесь вторую колонку «сколько вышло» велик и ломает то же
    самое, что хранимый остаток: заведённая задним числом операция не поправит
    её, и человек увидит «план 50 000, факт 30 000» там, где по операциям
    выходит 44 000. Факт приходит из того же агрегата, что и прибыль
    (`repositories/finance.by_category`), — из одного запроса, чтобы разойтись
    было нечему.

    План хранится **в терминах своей статьи и всегда положительным**: у
    расходной статьи «50 000» значит «потратить не больше пятидесяти тысяч», а
    не «минус пятьдесят». Знак — свойство операции, а не намерения; складывать
    план с фактом напрямую никто не будет, их сравнивают.

    Период — пара дат, а не «месяц строкой». Месяц закрывает девять случаев из
    десяти, а десятый — квартал, полугодие, «до конца проекта» — не описывается
    им вовсе, и добавлять его потом пришлось бы новой колонкой рядом со старой.
    """

    __tablename__ = "finance_budgets"

    id: Mapped[int] = mapped_column(primary_key=True)
    # RESTRICT по той же причине, что у операции: бюджет — это история решений,
    # и удаление статьи не должно уносить её молча.
    category_id: Mapped[int] = mapped_column(
        ForeignKey("finance_categories.id", ondelete="RESTRICT")
    )
    # Границы включительные, обе. Полуоткрытый интервал правильнее для моментов
    # времени (см. `report_service.parse_period`), но здесь границы — это ДАТЫ
    # из календаря, которые человек набирает руками: «с 1 августа по 31
    # августа». Показать в форме 1 сентября как конец августа значит сбивать с
    # толку каждый раз ради стройности внутри.
    period_start: Mapped[date] = mapped_column(Date)
    period_end: Mapped[date] = mapped_column(Date)
    # Имя с «amount» намеренно: ревизор схемы (`tests/test_schema_conventions`)
    # ищет денежные колонки по имени и не даст сделать её дробной. Колонка,
    # названная `planned`, прошла бы мимо него молча.
    planned_amount_minor: Mapped[int] = mapped_column(Integer)
    note: Mapped[str] = mapped_column(Text, default="", server_default=text_default())
    created_at: Mapped[datetime] = mapped_column(DateTime, server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(
        DateTime, server_default=func.now(), onupdate=func.now()
    )

    __table_args__ = (
        # Один план на статью в периоде — и это тот редкий инвариант «ровно
        # один», который держит СУБД, а не запрос. Разница с основной фирмой и
        # основным складом в том, что здесь не нужна частичность: мягкого
        # удаления у бюджета нет, а значит и закрытых строк, мешающих обычному
        # UNIQUE, тоже. Второй план на тот же август — не «ещё один взгляд», а
        # два ответа на один вопрос, и выбирать между ними было бы нечем.
        UniqueConstraint(
            "category_id", "period_start", "period_end", name="uq_finance_budget_period"
        ),
        # Экран бюджетов открывают периодом («покажи август»), а не статьёй.
        Index("ix_finance_budgets_period", "period_start", "period_end"),
    )
