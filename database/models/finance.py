#:
#: `reversal` — отмена: проведение заказа отыграли назад, начисленное
#: сторнируется зеркальной операцией.
#: `adjustment` — поправка суммы на месте: упаковка вышла дороже, в карточке
#: поменяли 80 на 140.
#:
#: Одним полем с двумя значениями, а не двумя флажками: «и отмена, и поправка» —
