# Виды бланков.
#
# **Заказ — это вид бланка, а не отдельная сущность.** Соблазн завести таблицу
# `orders` со своими номерами, статусами и печатью велик и означает написать
# второй раз всё, что здесь уже выстрадано: сквозной номер в году вместе с
# починенной гонкой его выдачи (двое у стойки), смену статуса условием «пока он
# тот, что прочитали», снимок для печати, три языка, QR со штрихкодом, поиск
# сканом, публичную страницу и связь с заявкой. Из этого списка гонку номеров
# ловили живым прогоном, где 13 из 20 одновременных выдач отвечали 500.
KIND_INTAKE = "intake"
#: Заказ покупателя: клиент просит товар, мы откладываем и отгружаем.
KIND_SALES_ORDER = "sales_order"
#: Заказ поставщику: мы просим товар, потом принимаем на склад.
KIND_PURCHASE_ORDER = "purchase_order"
#: Акт выполненных работ: работа закончена, бумага её закрывает.
#:
#: Виду бланка, а не своей сущности, по той же причине, что и заказу (разбор
#: выше). Но у акта есть и собственный довод: он ровно та бумага, которую
#: клиенту показывают в паре с квитанцией — «приняли по этой, отдаём по этой».
#: Разные номера у двух половин одной работы означали бы, что связать их можно
#: только памятью приёмщика.
#:
#: Отличие акта от заказа — не в содержании, а в том, что он делает при
#: проведении. Заказ двигает склад и на этом заканчивается; акт закрывает
#: работу целиком: списывает израсходованное, фиксирует сделанное и переводит
#: заявку дальше по воронке. Три действия объявлены **одним**, потому что
#: раздельно они расходятся: списание прошло, этап не сменился — и восстановить,
#: что имелось в виду, потом уже неоткуда.
KIND_ACT = "act"
#: Расходная накладная: товар физически уезжает со склада.
#:
#: Опять вид бланка, а не своя сущность, и довод тот же, что у заказа и акта, —
#: но у накладной есть и собственный. Накладная и заказ различаются НЕ
#: содержанием (перечень позиций у них один и тот же, `document_lines`), а тем,
#: что заказ обещает, а накладная отдаёт. Заведи мы им разные таблицы строк, и
#: получилось бы два места, где считаются деньги; разъезжаются такие пары не
#: сразу, а постепенно — сначала в округлении, потом в скидке, потом в налоге.
#:
#: Отличие от заказа — в моменте движения склада. Заказ держит РЕЗЕРВ:
#: обещанное числится за клиентом, но лежит на полке. Накладная списывает: с
#: полки товар ушёл. Поэтому у неё есть черновик, которого нет ни у одного
#: другого вида (разбор — в `KIND_STATUSES` ниже).
KIND_WAYBILL_OUT = "waybill_out"
#: Приходная накладная: товар принят на склад.
KIND_WAYBILL_IN = "waybill_in"
DOCUMENT_KINDS = (
    KIND_INTAKE,
    KIND_SALES_ORDER,
    KIND_PURCHASE_ORDER,
    KIND_ACT,
    KIND_WAYBILL_OUT,
    KIND_WAYBILL_IN,
)

#: Виды заказа: покупателю и поставщику.
ORDER_KINDS = (KIND_SALES_ORDER, KIND_PURCHASE_ORDER)

#: Виды накладной: расходная и приходная.
WAYBILL_KINDS = (KIND_WAYBILL_OUT, KIND_WAYBILL_IN)

#: Виды, которые двигают склад САМИ, своим путём проведения.
#:
#: Список существует ради одной проверки — `document_service.tolko_blank`.
#: Общая ручка смены статуса меняет статус и пишет переход, а склада не
#: касается; пропусти она сюда бумагу, которая обязана двигать остаток, — и
#: бумага закроется, а товар останется на полке. Расхождение всплывёт на
#: инвентаризации через месяц, когда концов уже не найти.
#:
#: Заказы попали сюда после того, как это ровно так и работало: `POST
#: /documents/{id}/status` с правом `documents.issue` закрывал заказ мимо
#: `orders.issue` и мимо склада. Накладная добавлена в тот же список сразу, а не
#: после такого же случая.
SKLADSKIE_KINDS = ORDER_KINDS + WAYBILL_KINDS

#: Виды, у которых есть перечень позиций (`document_lines`).
#:
#: Акт стоит здесь наравне с заказами и пользуется той же таблицей строк —
#: почему именно так, разобрано в докстроке `DocumentLine`.
LINE_KINDS = ORDER_KINDS + (KIND_ACT,) + WAYBILL_KINDS

# Состояния документа. Отдельно от этапа сделки намеренно: сделка живёт в
# воронке, которую каждый бизнес настраивает под себя, а документ — бумага с
# коротким и общим для всех жизненным циклом. Смешай их — и скан квитанции
# начнёт двигать сделку по чужой воронке.
STATUS_ISSUED = "issued"
STATUS_IN_PROGRESS = "in_progress"
STATUS_READY = "ready"
STATUS_CLOSED = "closed"
STATUS_CANCELLED = "cancelled"
#: Черновик: бумага набирается и ещё ничего не сделала.
#:
#: **Есть только у накладной**, и это не прихоть. Квитанцию печатают целиком за
#: один заход у стойки — набирать там нечего. Накладную СОБИРАЮТ: кладовщик
#: ходит по складу со сканером, позиции появляются по одной, что-то не находится
#: и заменяется. Заставить его завести бумагу и тут же провести её значит либо
#: провести неполную, либо держать перечень в голове, пока не соберётся весь.
#:
#: Черновик — единственное состояние накладной, в котором её МОЖНО править.
#: После проведения бумага неизменяема (разбор — в `waybill_service`).
STATUS_DRAFT = "draft"
DOCUMENT_STATUSES = (
    STATUS_DRAFT,
    STATUS_ISSUED,
    STATUS_IN_PROGRESS,
    STATUS_READY,
    STATUS_CLOSED,
    STATUS_CANCELLED,
)

#: Статусы квитанции. Раньше здесь стояла `DOCUMENT_STATUSES` целиком, и это
#: было одно и то же — до появления черновика. Разводить их пришлось потому, что
#: `DOCUMENT_STATUSES` означает «все статусы, какие бывают», а квитанция
#: черновиком не бывает: её печатают за один заход.
INTAKE_STATUSES = (
    STATUS_ISSUED,
    STATUS_IN_PROGRESS,
    STATUS_READY,
    STATUS_CLOSED,
    STATUS_CANCELLED,
)

DOCUMENT_LOCALES = ("ru", "en", "uk")

#: Какие состояния осмысленны у какого вида.
#:
#: Новых состояний заказу не понадобилось, и это не экономия, а признак того,
#: что бланк и заказ — действительно одно и то же с разным содержанием:
#:
#: - `issued` у заказа покупателя означает «принят, товар отложен» (то есть
#:   зарезервирован), у заказа поставщику — «отправлен поставщику»;
#: - `ready` — «собран» и «приехало, ждёт приёмки»;
#: - `closed` — «отгружен» и «принят на склад». Именно на переходе в него
#:   случается движение склада, и только тогда;
#: - `cancelled` — резерв снялся, склад не тронут.
#:
#: `in_progress` заказу не нужен: между «принят» и «собран» у него нет
#: состояния, которое кто-то захотел бы увидеть отдельно.
#:
#: У акта состояний три, и это не урезание набора, а его существо. `issued` —
#: «набирается»: работа идёт, позиции дописывают по ходу. `closed` — «проведён»:
#: тот единственный переход, на котором случается всё сразу. `cancelled` —
#: передумали до проведения, ничего не случилось вовсе.
#:
#: `in_progress` и `ready` у акта отсутствуют намеренно. Акт не проходит путь —
#: путь проходит РАБОТА, и её состояние живёт в этапе заявки. Заведи мы у акта
#: «готов», и у одной работы стало бы два состояния сразу: этап заявки и статус
#: бумаги. Расходиться они начали бы на первой же неудачной попытке провести.
#: У накладной состояний четыре, и черновик из них главный (разбор — у
#: `STATUS_DRAFT`). `issued` — «проведена»: склад двинулся, бумага ушла с
#: товаром. `closed` — «получатель подтвердил приёмку»; он ничего не двигает и
#: нужен ровно затем, что «отгружено» и «принято» — разные факты, а спор «вы нам
#: не привозили» решается записью с временем, а не текущим состоянием.
#: `cancelled` — передумали до проведения; после проведения отменять нечего,
#: там сторнирование.
#:
#: `in_progress` и `ready` у накладной отсутствуют по той же причине, что и у
#: акта: путь проходит не бумага, а поставка, и её состояние живёт в заявке.
KIND_STATUSES: dict[str, tuple[str, ...]] = {
    KIND_INTAKE: INTAKE_STATUSES,
    KIND_SALES_ORDER: (STATUS_ISSUED, STATUS_READY, STATUS_CLOSED, STATUS_CANCELLED),
    KIND_PURCHASE_ORDER: (STATUS_ISSUED, STATUS_READY, STATUS_CLOSED, STATUS_CANCELLED),
    KIND_ACT: (STATUS_ISSUED, STATUS_CLOSED, STATUS_CANCELLED),
    KIND_WAYBILL_OUT: (STATUS_DRAFT, STATUS_ISSUED, STATUS_CLOSED, STATUS_CANCELLED),
    KIND_WAYBILL_IN: (STATUS_DRAFT, STATUS_ISSUED, STATUS_CLOSED, STATUS_CANCELLED),
}


def statuses_for(kind: str) -> tuple[str, ...]:
    """Какие статусы осмысленны у этого вида.

    **Раньше `KIND_STATUSES` не читал никто.** Словарь стоял в модели как
    описание и ни на что не влиял: единственная проверка статуса
    (`document_service.set_status`) сверялась с `DOCUMENT_STATUSES`, то есть со
    всеми статусами разом. Пока набор совпадал у всех видов, разницы не было.

    С появлением черновика она появилась: `draft` попал в общий набор, и без
    этой функции квитанцию можно было бы отправить в черновик — состояние, для
    неё бессмысленное и ничем не предусмотренное. Описание, которое ничего не
    ограничивает, тем и опасно: выглядит как правило.
    """
    return KIND_STATUSES.get(kind, DOCUMENT_STATUSES)

