"""Приёмы, общие для всех запросов: страницы и поиск по подстроке.

Здесь лежит то, что в каждом репозитории было выписано заново и одинаково.
Смысл не в экономии строк — их немного, — а в том, что **расхождения между
SQLite и MySQL собраны в одном месте**. Пока эти выражения размазаны по девяти
файлам, переезд на MySQL означает проверить девять файлов и не забыть ни одного;
после переезда то же самое повторится с каждым новым блоком.

Что здесь чинится по существу:

**Отрицательное смещение.** `offset((page - 1) * per_page)` при `page = 0` даёт
`OFFSET -50`. SQLite такое прощает и молча отдаёт первую страницу, MySQL
отвечает синтаксической ошибкой — то есть пятисоткой. Сейчас снаружи не
пройдёт: каждый маршрут объявляет `page` как `ge=1`. Но это защита в двадцати
четырёх местах, и держится она на том, что автор следующего маршрута про неё
вспомнит. Здесь её забыть нельзя.

**Шаблон в том, что ввёл человек.** `%` и `_` в LIKE — не буквы, а «что угодно»
и «любой один символ», и в поисковую строку они попадают как есть. Проверено:
поиск «тест_один» находил и «тестХодин», а поиск по одному знаку `%` возвращал
**всю** таблицу — на большой базе это выгрузка всех карточек по случайному
нажатию. Экранируем сами, знаком `/`: обратная косая на MySQL сама по себе
служит экранированием внутри строки, и `ESCAPE '\\'` читается по-разному в
зависимости от режима сервера. Проверено сборкой под оба движка: `/` даёт
одинаковый `ESCAPE '/'` и там, и там.
"""

from typing import TypeVar

from sqlalchemy import Select, func, select
from sqlalchemy.orm import Session

Row = TypeVar("Row")

#: Потолок размера страницы.
#:
#: Маршруты объявляют свои пределы (100–200) и этого потолка не касаются. Он
#: нужен для вызовов изнутри, где числа берутся не из запроса: «покажи ленту,
#: `per_page=200`» легко превращается в «покажи всё», а «всё» на базе, которая
#: росла три года, — это разом в память.
MAX_PER_PAGE = 500

#: Знак экранирования в LIKE. Про выбор — в докстроке модуля.
LIKE_ESCAPE = "/"


def page_of(
    db: Session, stmt: "Select[tuple[Row]]", *, page: int, per_page: int
) -> tuple[list[Row], int]:
    """Одна страница выдачи и общее число строк.

    Порядок задаёт вызывающий — до вызова, через `order_by`: сортировка это
    знание о предметной области («свежее сверху», «сначала неоплаченные»), и
    общему коду его взять неоткуда.

    Считаем по подзапросу от того же `stmt`, а не собираем условия второй раз:
    два выражения одного отбора однажды разъедутся, и счётчик начнёт врать —
    «найдено 40» при семи строках на экране.
    """
    total = db.scalar(select(func.count()).select_from(stmt.subquery())) or 0
    rows = db.scalars(stmt.offset(offset_for(page, per_page)).limit(clamp_per_page(per_page)))
    return list(rows), total


def clamp_per_page(per_page: int) -> int:
    """Размер страницы в разумных пределах: не меньше одной строки, не больше потолка."""
    return max(1, min(int(per_page), MAX_PER_PAGE))


def offset_for(page: int, per_page: int) -> int:
    """Смещение страницы. Никогда не отрицательное — почему, см. докстроку модуля."""
    return max(0, (int(page) - 1) * clamp_per_page(per_page))


def contains(column, needle: str):
    """«В этом поле встречается такая подстрока» — без сюрпризов от `%` и `_`.

    Регистр не важен: `ilike` на SQLite опирается на `lower()`, подменённый в
    `database/session.py` на понимающий кириллицу, а на MySQL нечувствительность
    даёт сравнение по умолчанию. Обе дороги ведут к одному, и обе — не здесь.
    """
    return column.ilike(f"%{escape_like(needle)}%", escape=LIKE_ESCAPE)


def escape_like(value: str) -> str:
    """Обезвредить в строке знаки, которые LIKE считает шаблоном.

    Сам знак экранирования — первым: иначе `/` из введённого станет
    экранированием для следующей буквы и съест её.
    """
    return (
        str(value)
        .replace(LIKE_ESCAPE, LIKE_ESCAPE * 2)
        .replace("%", f"{LIKE_ESCAPE}%")
        .replace("_", f"{LIKE_ESCAPE}_")
    )
