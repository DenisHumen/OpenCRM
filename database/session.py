from contextlib import contextmanager

from sqlalchemy import create_engine, event, func, select
from sqlalchemy.orm import DeclarativeBase, Session, sessionmaker

from config.settings import get_settings


class Base(DeclarativeBase):
    pass


#: Сколько соединений к базе безопасно занять ВСЕМ приложением сразу.
#:
#: У mysql:8.0 из коробки `max_connections=151`. Оставляем запас на разовые
#: заходы — снятие дампа перед миграциями, `alembic`, сверку схемы, клиента
#: `mysql` при откате, сборщик метрик, — потому что упирается в потолок не
#: приложение, а тот, кто пришёл чинить: «Too many connections» ровно в момент
#: разбора аварии.
BYUDZHET_SOEDINENIY = 100

#: Наименьшее число одновременных обработчиков, ниже которого опускаться нельзя.
#:
#: Восемь — это «страница с картинками грузится, и в это время можно ещё
#: работать». Меньше — и одна пачка плиток занимает приложение целиком.
MINIMUM_ODNOVREMENNYH = 8


def razmer_pula(workers: int) -> tuple[int, int]:
    """`pool_size` и `max_overflow` на ОДИН рабочий процесс.

    Считаем от бюджета соединений и числа воркеров, а не берём числом: числом
    оно уже стояло, и стояло вразрез с тем, сколько запросов приложение
    выполняет одновременно (разбор — у вызывающего).

    Делим поровну: `pool_size` держится постоянно, `max_overflow` заводится под
    всплеск и закрывается после. Постоянно держать весь бюджет незачем — база
    платит памятью за каждое соединение.
    """
    workers = max(1, int(workers or 1))
    na_vorkera = max(MINIMUM_ODNOVREMENNYH, BYUDZHET_SOEDINENIY // workers)
    postoyanno = na_vorkera // 2
    return postoyanno, na_vorkera - postoyanno


def predel_odnovremennyh(workers: int) -> int:
    """Сколько запросов приложению позволено выполнять разом в одном процессе.

    Ровно столько, сколько у процесса соединений к базе. Больше — и лишние
    обработчики стоят в очереди за соединением до `pool_timeout`, после чего
    отдают пятисотую вместо медленного ответа. Меньше — соединения простаивают.
    """
    postoyanno, sverh = razmer_pula(workers)
    return postoyanno + sverh


def _make_engine():
    settings = get_settings()
    url = settings.db_url
    kwargs: dict = {"pool_pre_ping": True}
    if url.startswith("mysql"):
        # Потолок соединений на ПРОЦЕСС, а не на систему, — и считать надо
        # именно так. Пул заводится в каждом рабочем процессе отдельно, а
        # переезд на MySQL как раз и разрешает их несколько: при умолчаниях
        # SQLAlchemy (5 + 10 сверх) восемь воркеров дают до 120 соединений
        # против `max_connections=151` у mysql:8.0 из коробки. Оставшийся
        # десяток съедают разовые заходы — снятие дампа, `alembic`, сверка
        # переезда, — и упирается в потолок не приложение, а тот, кто пришёл
        # чинить: «Too many connections» ровно в момент разбора аварии.
        #
        # **Размер считается от числа воркеров, а не задан числом.** Пять и пять
        # стояли здесь как «восемь воркеров укладываются в 80» — расчёт верный,
        # но не тот: он считал ПОТОЛОК и не считал, сколько запросов приложение
        # берётся выполнять ОДНОВРЕМЕННО.
        #
        # А берётся оно за сорок. Ручки у нас синхронные (`def`, не `async def`),
        # и Starlette уводит такую в поток; предел потоков anyio по умолчанию —
        # сорок. То есть сорок обработчиков разом просят соединение из пула на
        # десять. Кто не дождался за `pool_timeout` (тридцать секунд по
        # умолчанию), получает не медленный ответ, а `QueuePool limit ... reached`
        # и пятисотую.
        #
        # **Так и вышло на боевом сервере 24 августа 2026.** Витрина доски с
        # тремя десятками плиток — это пачка запросов `/media/<uid>/thumb.webp`
        # разом, а каждая плитка стоит трёх вопросов к базе (блок включён? свой
        # ли пришёл? витрина публична?), потому что `/media/` проксируется в
        # приложение, а не раздаётся nginx. Ответ сайта вырос до восьми секунд —
        # это те, кто соединение всё же дождался, — а часть плиток отдала
        # пятисотую. Само прошло, когда пачка кончилась.
        #
        # Отсюда правило: **соединений не меньше, чем одновременных
        # обработчиков.** Держит его `web.main` — он же выставляет предел потоков
        # ровно по этому числу, — а сверяет `tests/test_pool_sizing.py`.
        kwargs["pool_size"], kwargs["max_overflow"] = razmer_pula(settings.workers)
        # READ COMMITTED вместо REPEATABLE READ, и это не тонкая настройка, а
        # условие правильности.
        #
        # Приём «вставили, получили отказ, перечитали — правда ли занято»
        # (core/uniqueness.py) держит на себе четыре места: регистрация,
        # название должности, артикул склада, номер бланка. Перечитывание
        # обязано увидеть соседа, который только что зафиксировал свою строку.
        #
        # При REPEATABLE READ оно его НЕ ВИДИТ: снимок транзакции сделан до
        # чужой фиксации, и повторное чтение отдаёт прежнюю картину. Значит
        # `taken` отвечает «свободно», отказ базы уходит наверх как чужая
        # поломка, и человек получает 500 там, где система отработала верно.
        #
        # Поймано делом: пока набор тестов гонялся на файловой базе, проверка
        # двойного нажатия «Запросить доступ» проходила, а на MySQL падала с
        # `Duplicate entry ... for key users.ix_users_email`. То есть на боевом
        # сервере это уже работало именно так, и не видел этого только набор.
        kwargs["isolation_level"] = "READ COMMITTED"
    engine = create_engine(url, **kwargs)

    if url.startswith("mysql"):
        @event.listens_for(engine, "connect")
        def _prepare_mysql(dbapi_connection, _record):
            """Часовой пояс сессии — UTC. Это не настройка, а условие правильности.

            Весь проект хранит **наивный UTC**: `now_utc()` пишет время без
            смещения, и колонки объявлены `DateTime` без часового пояса.

            А `NOW()` в MySQL возвращает **местное время сессии**. Оставь мы это
            как есть — часть времён легла бы UTC (те, что пишет Python), часть
            местным (те, что ставит `server_default=func.now()` и `onupdate`), и
            **различить их постфактум было бы нечем**: в колонке лежит голое
            число без пояса. Journал действий, время движения склада, отметка
            «когда клиент позвонил» — всё это разъехалось бы на величину
            смещения и молча.

            Одна строка на соединение закрывает разом все двадцать пять колонок
            с `func.now()` и все `onupdate` — переписывать каждую было бы и
            дороже, и ненадёжнее: забытая колонка не проявляется ничем.
            """
            cursor = dbapi_connection.cursor()
            cursor.execute("SET time_zone = '+00:00'")
            cursor.close()

    return engine


engine = _make_engine()
SessionLocal = sessionmaker(bind=engine, expire_on_commit=False)


def get_session() -> Session:
    """Новая сессия БД (для фоновых задач и скриптов). В веб-слое — через Depends."""
    return SessionLocal()


@contextmanager
def tochka_otkata(db: Session):
    """Точка отката: вложенная транзакция вокруг записи, которая может не выйти.

    Ставится там и только там, где сейчас будет запись, чей отказ надо поймать,
    не потеряв остальную транзакцию: приём «вставили, получили отказ, перечитали»
    (`core/uniqueness.py`), приём почты, события АТС.
    """
    with db.begin_nested() as savepoint:
        yield savepoint


#: Ключ, под которым сессия помнит взятые ею именованные замки.
ZAMKI = "imenovannye_zamki"


def zapomnit_zamok(db: Session, imya: str) -> None:
    """Записать взятый замок, чтобы граница запроса его сняла.

    Именованный замок MySQL держится за СОЕДИНЕНИЕМ и не снимается ни
    `COMMIT`, ни `ROLLBACK`, ни `Session.close()` — та возвращает соединение в
    пул, а не закрывает его. Значит снять обязан тот, кто взял; забытый замок
    уезжает в пул вместе с соединением и заставляет следующего ждать впустую.
    """
    db.info.setdefault(ZAMKI, []).append(imya)


def snyat_zamki(db: Session) -> None:
    """Снять всё, что сессия успела занять. Зовётся на границе запроса.

    ПОСЛЕ фиксации, а не до неё, и это не мелочь порядка. Замок здесь стоит
    ровно затем, чтобы соперник не прошёл раньше, чем чужая запись станет
    видимой; сними его до `COMMIT` — и соперник получит очередь, увидит пустоту
    и сделает ровно то, от чего замок заводился. Проверено дуэлью: со снятием
    внутри сервиса форма с сайта по-прежнему заводила две карточки.

    Отказ на снятии проглатывается намеренно. Эта функция работает в `finally`
    рядом с закрытием сессии, в том числе когда запрос уже падает; исключение
    отсюда подменило бы настоящую причину отказа своей. А сам замок в худшем
    случае уйдёт с соединением: MySQL снимает именованные замки, когда
    соединение обрывается, и пул однажды его переоткроет.
    """
    imena = db.info.pop(ZAMKI, None)
    if not imena:
        return
    for imya in imena:
        try:
            db.execute(select(func.release_lock(imya)))
        except Exception:  # noqa: BLE001 — снятие замка не должно прятать причину отказа
            pass
