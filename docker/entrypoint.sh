#!/bin/sh
set -e

# Страховочная копия перед миграциями — та, к которой возвращаются, если
# миграция испортила данные.
#
# **Копия именуется ревизией, с которой уходим, и не перезаписывается.** Раньше
# файл был один (`.pre-migrate`) и обновлялся на КАЖДОМ старте контейнера —
# включая перезапуски, перезагрузку машины и цикл рестартов после падения.
# Схема такая: миграция что-то испортила, контейнер перезапустился (сам или
# руками), и копия, снятая ДО миграции, затёрлась состоянием ПОСЛЕ неё. К
# моменту, когда беду замечали, возвращаться было уже не к чему.
#
# Теперь копия снимается только когда есть куда мигрировать, называется по
# текущей ревизии и, если такая уже есть, не трогается: повторный старт на той
# же ревизии ничего не переписывает.
DB_FILE="${OPENCRM_DB_FILE:-/app/data/opencrm.db}"
DB_DIR="$(dirname "$DB_FILE")"

# --- ход обновления для страницы обслуживания ---------------------------------
#
# Пока идёт обновление, приложения нет по определению: заглушку отдаёт nginx, и
# спросить «на каком мы шаге» ему не у кого. Значит шаги надо положить в ФАЙЛ,
# который nginx отдаст сам, статикой, без единого запроса в приложение.
#
# Файл кладётся в storage/branding — тот самый каталог, который любой уже
# развёрнутый nginx раздаёт по адресу /branding/ (docker/nginx/templates/
# locations.inc). Заводить под это свой `location` нельзя, и не из
# аккуратности: конфиг nginx примонтирован из чекаута, а работающий nginx
# держит в памяти тот, что прочитал при своём запуске (об этом же — _reload_nginx
# в deploy/updater.py). Новый location начал бы действовать только со СЛЕДУЮЩЕГО
# обновления — то есть на том обновлении, которое эту страницу и привозит, ход
# был бы не виден. Ровно то же и с новым томом: docker-compose.yml перечитывается
# только на `up`, а каталог данных в nginx не примонтирован вовсе.
#
# Тот же файл с хоста пишет deploy/updater.py (PROGRESS_NAME), читает его
# встроенный скрипт docker/nginx/maintenance/maintenance.html. Ни один из троих
# не импортирует остальных — за согласием следит tests/test_update_progress.py.
STATE_DIR="${OPENCRM_STORAGE_DIR:-/app/storage}/branding"
STATE_FILE="$STATE_DIR/update-state.json"

# В JSON не бывает ни кавычек, ни обратных слэшей, ни переводов строк, а сюда
# приезжает хвост чужого вывода. Длину режем заодно (столько же отрезает
# PROGRESS_ERROR_LIMIT в deploy/updater.py): файл по устройству публичен — его
# читает страница, за которой нет ни сессии, ни приложения, поэтому в нём место
# короткой причине, а не простыне из лога.
#
# `cut -c` в GNU coreutils считает БАЙТЫ, а не символы, и на кириллице предел
# может прийтись на середину буквы. Страшного в этом нет: браузер декодирует
# UTF-8 снисходительно и ставит на месте огрызка знак замены — теряется один
# символ причины, а не весь файл. Городить ради этого iconv или python внутри
# точки входа — цена выше пользы.
json_escape() {
    printf '%s' "$1" | tr -d '\\"' | tr '\n\r\t' '   ' | cut -c1-200
}

# Ход — удобство, а не часть запуска. Наверху `set -e`, и упавшая запись (свой
# монтаж storage, чужие права на каталоге) уронила бы контейнер вместо того,
# чтобы просто не показать шаг. Поэтому здесь прикрыта каждая команда, а выход
# всегда нулевой.
write_state() {   # фаза шаг причина
    mkdir -p "$STATE_DIR" 2>/dev/null || return 0
    [ -w "$STATE_DIR" ] || return 0

    # Отсчёт времени принадлежит тому, кто обновление затеял. Контейнер
    # стартует уже посреди процесса и начала не знает — забираем его из того,
    # что уже записано, но только пока обновление ИДЁТ. У законченного и у
    # упавшего отсчёт начинается заново, иначе на странице висело бы время
    # позапрошлого обновления.
    _started=""
    # Обычный перезапуск контейнера — это не обновление: ни образа не собирали,
    # ни копии базы с хоста не снимали, и показывать эти шаги пройденными
    # значило бы врать.
    #
    # Чьё это дело, наследуем, а не выводим заново. Вывод «раз состояние ещё
    # идёт, значит его начал обновлятор» неверен ровно на нас самих: свой же
    # предыдущий шаг («миграции») выглядит для следующего («старт») точно так
    # же, и обычный перезапуск на втором шаге объявил бы себя обновлением. На
    # запуске с подставными python и sqlite3 он это и делал.
    _scope="restart"
    if grep -q '"phase"[[:space:]]*:[[:space:]]*"running"' "$STATE_FILE" 2>/dev/null; then
        _started=$(sed -n 's/.*"started_at"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' \
            "$STATE_FILE" 2>/dev/null | head -n1) || _started=""
        if grep -q '"scope"[[:space:]]*:[[:space:]]*"update"' "$STATE_FILE" 2>/dev/null; then
            _scope="update"
        fi
    fi
    [ -n "$_started" ] || _started="$(date -u +%Y-%m-%dT%H:%M:%SZ)"

    # Через временный файл: страницу открывают в любой момент, и половина
    # записи разобралась бы у неё как испорченный JSON.
    printf '{"scope":"%s","phase":"%s","step":"%s","started_at":"%s","error":"%s"}' \
        "$_scope" "$1" "$2" "$_started" "$(json_escape "$3")" \
        >"$STATE_FILE.tmp" 2>/dev/null && mv -f "$STATE_FILE.tmp" "$STATE_FILE" 2>/dev/null
    return 0
}

# Каталог данных обязан быть доступен на запись ТОМУ пользователю, от которого
# работает приложение (в образе это `opencrm`, uid 1000).
#
# Проверяем это отдельной строкой и говорим прямо, потому что иначе беда
# выглядит как что угодно, только не как права. Каталог подключён снаружи
# (bind mount), и если его создал root — а именно так и выходит, когда
# `docker compose` запускают из-под root, а каталога ещё нет, — то Docker
# сделает его root:root 755. Приложение внутри читать сможет, а писать нет.
# Дальше всё рассыпается по очереди и невнятно: снимок перед миграциями не
# снимается с сообщением `Error: cannot open "..."`, `set -e` роняет запуск,
# контейнер уходит в цикл перезапуска, а в логе — одна строка про какой-то
# файл. Настоящая причина в ней не названа ни словом.
#
# Проверено на стенде: ровно этот цикл и был, и по логу он читался как поломка
# резервного копирования, хотя копирование было ни при чём.
if [ ! -w "$DB_DIR" ]; then
    echo "Каталог данных $DB_DIR недоступен на запись пользователю $(id -un) (uid $(id -u))." >&2
    echo "" >&2
    # shellcheck disable=SC2012  # путь один и известен заранее, разбора списка нет
    echo "Сейчас он принадлежит: $(ls -ld "$DB_DIR" | awk '{print $3":"$4, $1}')" >&2
    echo "" >&2
    echo "Приложение не сможет ни писать в базу, ни снять копию перед миграциями." >&2
    echo "Чинить надо на СЕРВЕРЕ, а не в контейнере: $DB_DIR — это путь ВНУТРИ" >&2
    echo "контейнера, снаружи тот же каталог лежит в домашней папке установки" >&2
    echo "(по умолчанию ~/opencrm/data, иначе \$OPENCRM_HOME/data):" >&2
    echo "" >&2
    echo "    sudo chown -R 1000:1000 \"\${OPENCRM_HOME:-\$HOME/opencrm}\"" >&2
    # Именно этот отказ выглядит снаружи как бесконечный цикл перезапусков, а
    # значит как лежащий сайт без объяснений. Пишем его на страницу: storage —
    # другой том, и он обычно доступен, даже когда каталог данных нет.
    write_state failed migrate "каталог данных $DB_DIR недоступен на запись — см. логи контейнера"
    exit 1
fi

# Снимок перед миграциями существует только ради миграций, поэтому на странице
# он часть их шага, а не отдельная строка. Объявляем шаг до снимка: с этого
# момента и до старта приложения посетитель видит именно «обновляем базу».
write_state running migrate ""

WORKERS="${OPENCRM_WORKERS:-1}"
DB_URL="${OPENCRM_DB_URL:-sqlite}"
REDIS_URL="${OPENCRM_REDIS_URL:-}"

# Копию снимаем ПО ТОМУ АДРЕСУ, ПО КОТОРОМУ РАБОТАЕМ, а не по наличию файла.
#
# Прежде здесь стояло `if [ -f "$DB_FILE" ]`, и на установке, переехавшей на
# MySQL, это давало худший из возможных исходов: файл SQLite после переезда
# остаётся лежать на месте (его нарочно не трогают), поэтому условие
# срабатывало — и снималась копия БАЗЫ, КОТОРОЙ НИКТО НЕ ПОЛЬЗУЕТСЯ, а следом
# шли миграции по MySQL. Ровно это и видно в журнале запуска стенда. Копии
# рабочей базы при этом не было вовсе, то есть неудачное обновление откатывало
# код, а базу откатывать было нечем.
case "$DB_URL" in
    mysql*)
        # Ревизию и дамп берёт python: клиента MySQL в этом образе нет и не
        # будет (обоснование — в шапке scripts/snapshot_db.py), а `sqlite3`
        # здесь бесполезен по очевидной причине.
        CURRENT="$(python -m scripts.snapshot_db revision 2>/dev/null || echo none)"
        [ -n "$CURRENT" ] || CURRENT=none
        SNAPSHOT="$DB_DIR/mysql.pre-migrate-$CURRENT.sql"
        if [ -f "$SNAPSHOT" ]; then
            echo "[opencrm] копия перед миграциями уже есть: $SNAPSHOT"
        else
            # Через временный файл: дамп, оборванный на полпути (кончилось
            # место, убили контейнер), — это обычный текстовый файл, и от
            # готовой копии он неотличим ничем, кроме отсутствующего хвоста.
            # Пока он называется `.part`, следующий старт его не примет.
            if python -m scripts.snapshot_db dump "$SNAPSHOT.part"; then
                mv -f "$SNAPSHOT.part" "$SNAPSHOT"
                echo "[opencrm] снята копия перед миграциями: $SNAPSHOT"
            else
                rm -f "$SNAPSHOT.part"
                echo "[opencrm] не удалось снять копию базы перед миграциями." >&2
                echo "Дальше идти нельзя: миграции вперёд необратимы, и откатывать" >&2
                echo "неудачное обновление было бы нечем." >&2
                write_state failed migrate "копия базы перед миграциями не снялась — см. логи контейнера"
                exit 1
            fi
        fi
        # shellcheck disable=SC2012  # имена копий делает этот же скрипт: ревизия
        # alembic, то есть буквы и цифры. Ни пробелов, ни переводов строки.
        ls -1t "$DB_DIR"/mysql.pre-migrate-*.sql 2>/dev/null | tail -n +6 | xargs -r rm -f
        ;;
    *)
        if [ -f "$DB_FILE" ]; then
            # Ревизию читаем прямо из базы, а не через `alembic current`: тот
            # поднимает всё окружение приложения ради одной строки, а здесь
            # важна скорость старта.
            CURRENT="$(sqlite3 "$DB_FILE" "SELECT version_num FROM alembic_version" 2>/dev/null || echo none)"
            [ -n "$CURRENT" ] || CURRENT=none
            SNAPSHOT="$DB_FILE.pre-migrate-$CURRENT"
            if [ -f "$SNAPSHOT" ]; then
                echo "[opencrm] копия перед миграциями уже есть: $SNAPSHOT"
            else
                sqlite3 "$DB_FILE" ".backup '$SNAPSHOT'"
                echo "[opencrm] снята копия перед миграциями: $SNAPSHOT"
            fi
            # Держим последние пять: копии тяжёлые, а нужны только недавние — к
            # позапрошлогодней ревизии никто не возвращается.
            # shellcheck disable=SC2012  # имена копий делает этот же скрипт: ревизия alembic,
            # то есть буквы и цифры. Ни пробелов, ни переводов строки в них не бывает, а
            # `find -printf`, которым обычно советуют заменять, есть только у GNU.
            ls -1t "$DB_FILE".pre-migrate-* 2>/dev/null | tail -n +6 | xargs -r rm -f
        fi
        ;;
esac

# Несколько рабочих процессов на SQLite не работают: писатель у неё один на всю
# базу, и два процесса не поднимаются вовсе — падают на создании схемы и посеве
# умолчаний с «database is locked». Проверено живьём. Приложение говорит об этом
# и само, но здесь значение известно точно, а сказать лучше до миграций, чем
# после трёх минут ожидания.
if [ "$WORKERS" -gt 1 ] 2>/dev/null; then
    case "$DB_URL" in
        sqlite*)
            echo "OPENCRM_WORKERS=$WORKERS с базой SQLite не работает: SQLite допускает" >&2
            echo "одного писателя, и процессы не поднимутся. Оставьте OPENCRM_WORKERS=1" >&2
            echo "или переезжайте на MySQL (scripts/migrate_to_mysql.py)." >&2
            write_state failed migrate "OPENCRM_WORKERS=$WORKERS не работает с SQLite — см. логи контейнера"
            exit 1
            ;;
    esac
    # Второе условие, и оно НЕ выводится из первого.
    #
    # Пока проверялся один префикс URL, переезд на MySQL разрешал восемь
    # процессов разом — и вместе с запретом снимал единственное, на чём
    # держалась защита от подбора: счётчик попыток жил в памяти процесса.
    # Восемь процессов дают восемь независимых счётчиков, порог умножается на
    # восемь, и НИКАКОЙ ОШИБКИ при этом не возникает. Отсюда отказ здесь: чтобы
    # ухудшение защиты нельзя было получить молча.
    if [ -z "$REDIS_URL" ]; then
        echo "OPENCRM_WORKERS=$WORKERS без OPENCRM_REDIS_URL: счётчик попыток входа лежал бы" >&2
        echo "в памяти каждого процесса отдельно, и порог защиты от подбора пароля и PIN" >&2
        echo "стал бы в $WORKERS раз выше заявленного — без единой ошибки. Задайте" >&2
        echo "OPENCRM_REDIS_URL или оставьте OPENCRM_WORKERS=1." >&2
        write_state failed migrate "OPENCRM_WORKERS=$WORKERS без OPENCRM_REDIS_URL — см. логи контейнера"
        exit 1
    fi
fi

# Вывод миграций собираем в файл, а не пускаем сразу в лог: упавшую миграцию
# надо не только оставить в `docker logs`, но и НАЗВАТЬ на странице
# обслуживания. Иначе посетитель видит вечное «обновляем базу», а контейнер
# крутится в перезапусках и не поднимется уже никогда — самый дорогой из
# случаев, ради которых страница вообще показывает ход.
#
# Лог кладём рядом с базой, а не в /tmp: про этот каталог мы только что
# проверили, что он доступен на запись, а неудачное перенаправление увело бы
# нас в ветку «миграции упали», хотя они бы даже не запускались.
MIGRATE_LOG="$DB_DIR/.migrate.log"
# Код возврата снимаем через `|| MIGRATE_CODE=$?`, а не из `$?` в ветке `else`:
# после условия `if` этот `$?` принадлежит условию, читается двусмысленно и
# ровно за это ругается shellcheck, который у нас стоит на воротах (SC2319).
MIGRATE_CODE=0
python -m alembic upgrade head >"$MIGRATE_LOG" 2>&1 || MIGRATE_CODE=$?
if [ "$MIGRATE_CODE" -eq 0 ]; then
    cat "$MIGRATE_LOG"
else
    cat "$MIGRATE_LOG" >&2
    write_state failed migrate "$(tail -n 3 "$MIGRATE_LOG")"
    exit "$MIGRATE_CODE"
fi

write_state running start ""

# --no-proxy-headers: uvicorn НЕ переписывает client по X-Forwarded-For. Определение
# IP клиента (rate-limit подбора PIN, хэш IP просмотров) целиком за приложением
# (core client_ip + OPENCRM_TRUSTED_PROXY_HOPS) — иначе заголовок клиента подделывается.
exec python -m uvicorn web.main:app --host 0.0.0.0 --port 8000 \
    --no-proxy-headers --workers "$WORKERS"
