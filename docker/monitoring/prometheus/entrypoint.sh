#!/bin/sh
# Точка входа Prometheus: подставляет в конфиг адрес, по которому проверяется
# сайт СНАРУЖИ.
#
# Зачем шаблон вообще. Адрес сайта известен только этой установке и лежит в
# `docker/.env` (`OPENCRM_MONITOR_URL`, пишет `./opencrm.sh`). Prometheus
# переменные окружения в конфиге не раскрывает вовсе — ни в targets, ни в
# labels, — поэтому подстановка делается до его запуска. Приём тот же, что у
# nginx в этом же проекте (docker/nginx/entrypoint.sh): шаблон в репозитории,
# готовый конфиг рождается при старте.
#
# Внешний адрес — не педантизм. Проверка изнутри сети ходила бы к контейнеру
# nginx напрямую и была бы зелёной ровно в том случае, который однажды и
# случился: приложение отвечает на localhost, nginx не поднялся, 443 не слушает
# никто, сайта нет. Поэтому по умолчанию проверяется публичный адрес, а падение
# на внутренний сопровождается громким предупреждением в лог.
set -e

TEMPLATE=/etc/prometheus/prometheus.yml.template
TARGET=/tmp/prometheus.yml

URL="${OPENCRM_MONITOR_URL:-}"
if [ -z "$URL" ]; then
    URL="http://nginx"
    echo "[opencrm-prometheus] ВНИМАНИЕ: OPENCRM_MONITOR_URL не задан."
    echo "[opencrm-prometheus] Проверяю сайт ИЗНУТРИ сети ($URL) — это не то же самое,"
    echo "[opencrm-prometheus] что проверка снаружи: непроверенными остаются 443, сертификат"
    echo "[opencrm-prometheus] и публикация портов. Задать адрес: ./opencrm.sh monitoring"
else
    echo "[opencrm-prometheus] сайт проверяется снаружи: $URL"
fi

# Разделитель `|`, а не `/`: в адресе слэшей полно, а вертикальной черты в URL
# не бывает.
render() {
    sed -e "s|__SITE_URL__|$URL|g" "$TEMPLATE" > "$TARGET"
}
render

# Перечитывание конфига и правил раз в пять минут — тот же приём, что у nginx в
# этом проекте, и по той же причине.
#
# Файлы правил примонтированы из чекаута, и `git checkout` меняет их на диске
# мгновенно. Но `docker compose up -d --build` пересоздаёт только те службы, у
# которых изменилось описание или образ, — у Prometheus не меняется ни то, ни
# другое, и он остаётся работать с правилами, прочитанными при своём запуске.
# То есть **новое правило после обновления не действует вовсе**, и узнать об
# этом можно только по несработавшей тревоге, то есть в самый неподходящий
# момент. Сам Prometheus за файлами не следит.
#
# Пять минут — период опроса автообновления: правило начинает действовать не
# позже, чем через один такой такт после деплоя.
(
    while :; do
        sleep 300
        render
        # Prometheus после `exec` — первый процесс контейнера. SIGHUP заставляет
        # его перечитать и конфиг, и все файлы правил.
        kill -HUP 1 2>/dev/null || true
    done
) &

exec /bin/prometheus --config.file="$TARGET" "$@"
