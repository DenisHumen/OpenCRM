#!/bin/sh
# Перечитать конфиг nginx — С ПОВТОРНЫМ РЕНДЕРОМ шаблона и БЕЗ остановки сайта.
#
# Зачем отдельный файл, если `nginx -s reload` — одна команда.
#
# Рабочий конфиг nginx не лежит в репозитории: он рождается из шаблона
# (`http.conf.template` / `https.conf.template`) подстановкой домена. А
# `nginx -s reload` перечитывает УЖЕ ОТРЕНДЕРЕННЫЙ `/etc/nginx/conf.d/default.conf`
# и его include-файлы — заново рендерить шаблон он не умеет и не должен.
# Отсюда ровно та беда, которая пять суток держала боевой сервер:
#
#   * правки шаблонов не применялись НИКОГДА — ни `reload`-ом раз в шесть часов,
#     ни шагом `nginx-reload` при обновлении. Только пересозданием контейнера,
#     а его не делает никто, кроме выпуска сертификата (раз в жизни установки);
#   * коммит 027f2be добавил `access_log … opencrm_json` в locations.inc (это
#     include, подхватывается сразу) и `include logging.inc` в оба шаблона (это
#     шаблон, не подхватывается вовсе). Получилась комбинация «новый include
#     ссылается на формат, которого в загруженном конфиге нет» — и nginx стал
#     ОТВЕРГАТЬ конфиг целиком на каждом reload. Молча: все три места, которые
#     его зовут, ошибку глушили;
#   * появившийся сертификат тоже не подхватывался: выбор шаблона делался
#     только при старте контейнера.
#
# Поэтому здесь то же самое, что в docker/monitoring/prometheus/entrypoint.sh:
# СНАЧАЛА РЕНДЕР, ПОТОМ СИГНАЛ. Асимметрия между nginx и Prometheus и была
# причиной инцидента.
#
# Почему перечитывание, а не перезапуск — цена названа вслух:
#
#   `docker compose restart nginx` шлёт PID 1 (это сам nginx) SIGTERM, а для
#   nginx SIGTERM — это FAST SHUTDOWN: рабочие процессы гибнут немедленно, не
#   доигрывая запросы. Снаружи это 1-3 секунды НЕ страницы обслуживания, а
#   отказа соединения — заглушку отдаёт сам nginx, и пока его нет, отдавать её
#   некому. Рвутся начатые загрузки (лимит тела 220 МБ), теряется кэш сессий
#   TLS. И главное: `nginx -t` в entrypoint стоит под `set -e`, а у службы
#   `restart: unless-stopped` — неудачный конфиг превращается не в «изменения не
#   применились», а в лежащий сайт и цикл перезапусков.
#
#   `nginx -s reload` — это SIGHUP мастеру: новые рабочие поднимаются, старые
#   ДОРАБАТЫВАЮТ начатые запросы, слушающие сокеты не переоткрываются. Простоя
#   нет, ни одно соединение не рвётся. Плохой конфиг = reload отменён, работает
#   прежний. То есть при равном результате цена ошибки различается как «ничего
#   не изменилось» против «сайт лежит».
#
# Проверка идёт ДО сигнала и на настоящем месте: отрендеренный файл кладётся в
# `default.conf`, `nginx -t` разбирает его вместе с include-ами (именно этой
# связки не хватало — файл по отдельности проверку проходил), и только при
# зелёном тесте посылается сигнал. При красном прежний файл возвращается на
# место, а код возврата — ненулевой: вызывающий обязан об этом сказать вслух.
#
# Режимы:
#   render       отрендерить и проверить, сигнал НЕ слать (старт контейнера:
#                nginx ещё не запущен, слать некому)
#   reload       отрендерить, проверить, перечитать — всегда (умолчание;
#                отсюда зовут opencrm.sh и обновление)
#   if-changed   то же, но сигнал только если конфиг или include-ы изменились
#                (фоновый цикл раз в пять минут: 288 перезагрузок в сутки на
#                ровном месте никому не нужны)
set -e

MODE="${1:-reload}"

DOMAIN="${OPENCRM_DOMAIN:-_}"
LIVE_DIR="/etc/letsencrypt/live/${DOMAIN}"
TEMPLATES="/opencrm/templates"
TARGET="/etc/nginx/conf.d/default.conf"
# Расширения `.new` и `.previous` выбраны не для красоты: главный конфиг nginx
# подключает `conf.d/*.conf`, и файл со ЛЮБЫМ другим окончанием он не подхватит.
# Назови мы их `default-new.conf`, nginx поднял бы два одинаковых server-блока.
STAGE="${TARGET}.new"
BACKUP="${TARGET}.previous"
# Отпечаток последнего УДАВШЕГОСЯ применения. В /tmp намеренно: он про
# конкретный запущенный процесс nginx, а не про диск, и пересоздание контейнера
# обязано его забыть.
STAMP="/tmp/opencrm-nginx.applied"

note() { echo "[opencrm-nginx] $*"; }

# Выбор шаблона — по НАЛИЧИЮ ФАЙЛА сертификата, ровно как при старте. Это и
# делает подхват продлённого (и впервые выпущенного) сертификата бесплатным:
# раньше его замечал только перезапуск контейнера.
if [ "$DOMAIN" != "_" ] && [ -f "${LIVE_DIR}/fullchain.pem" ]; then
    TEMPLATE="${TEMPLATES}/https.conf.template"
else
    TEMPLATE="${TEMPLATES}/http.conf.template"
fi

# Одинарные кавычки обязательны и не опечатка: envsubst принимает СПИСОК
# переменных, которые ему разрешено подставлять. Раскрой его оболочка — список
# стал бы пустым, и envsubst заменил бы вообще всё, включая $host и $uri из
# конфига nginx.
# shellcheck disable=SC2016
envsubst '${OPENCRM_DOMAIN}' < "$TEMPLATE" > "$STAGE"

# Отпечаток берётся с трёх вещей, и каждая нужна.
#
# 1. Отрендеренный конфиг — правки шаблонов.
# 2. Include-файлы: правка locations.inc не меняет `default.conf` ни на байт, а
#    применить её надо.
# 3. САМ СЕРТИФИКАТ — иначе продление проходит мимо. Это не запас на будущее:
#    прежний цикл слал сигнал раз в шесть часов БЕЗУСЛОВНО и тем самым подхватывал
#    новый файл сам. Заменив безусловный сигнал на «только если изменилось», мы
#    обязаны считать изменением и продление — иначе nginx продолжит отдавать
#    старый сертификат до перезапуска контейнера, то есть примерно три месяца, и
#    браузеры покажут посетителям красный экран.
#
#    Берётся содержимое, а не время правки: certbot переписывает файл целиком, а
#    время в контейнере может отличаться от хостового.
if [ -f "${LIVE_DIR}/fullchain.pem" ]; then
    NOW=$(cat "$STAGE" "$TEMPLATES"/*.inc "${LIVE_DIR}/fullchain.pem" | md5sum | cut -d' ' -f1)
else
    NOW=$(cat "$STAGE" "$TEMPLATES"/*.inc | md5sum | cut -d' ' -f1)
fi

if [ "$MODE" = "if-changed" ] && [ -f "$STAMP" ] && [ "$NOW" = "$(cat "$STAMP")" ]; then
    rm -f "$STAGE"
    exit 0
fi

# APPLIED=0 значит «прежний конфиг ещё надо вернуть». Взводится сразу после
# зелёного `nginx -t`: с этого момента на диске лежит проверенный файл, и
# откатывать его нельзя даже если сигнал не дошёл.
APPLIED=0
if [ -f "$TARGET" ]; then
    cp "$TARGET" "$BACKUP"
fi
trap 'if [ "$APPLIED" = "0" ] && [ -f "$BACKUP" ]; then cp "$BACKUP" "$TARGET"; fi; rm -f "$STAGE" "$BACKUP"' EXIT
cp "$STAGE" "$TARGET"

if ! nginx -t; then
    note "конфиг не прошёл проверку — оставляю работать прежний, ничего не менял"
    exit 1
fi
APPLIED=1

if [ "$MODE" != "render" ]; then
    nginx -s reload
    note "конфиг перечитан (шаблон: $(basename "$TEMPLATE"))"
fi

printf '%s\n' "$NOW" > "$STAMP"
