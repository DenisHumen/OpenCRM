"""Проверка настроек в отрыве от запуска приложения.

**Зачем.** Настройки проверяются на старте (`web/main.py`), и это правильное
место: несошедшийся конфиг обязан остановить запуск, а не работать вполсилы. Но
у обновления это же место — худшее из возможных. Обновление идёт так: собрать
образ, снять копию базы, **подменить контейнер**, дождаться `/healthz`. Если
новый код требует настройку, которой на машине нет, отказ случается уже ПОСЛЕ
подмены: сайт лежит, health-check возвращает 502, обновление откатывает код и
базу. Так и вышло на боевом сервере, когда Redis стал обязательным: обновление
падало кругами, а причина — одна недописанная строка в `config/.env`.

Отказ по конфигу дешёвый и заранее известный: его видно, не трогая живой сайт.
Этот модуль и есть тот же самый разбор, вынесенный отдельно, чтобы обновление
могло спросить «а новый код на этой машине вообще поднимется?» до сборки и
подмены.

Проверка ровно одна на оба места — `Settings.config_errors()`. Второй список
требований завёл бы расхождение: код требовал бы одного, обновление проверяло
другое, и молчащая проверка хуже отсутствующей.

Запускается внутри образа с настоящим `config/.env`, потому что важно не «что
написано в файле», а «что увидит приложение»: часть значений приходит из
`docker/.env` через `environment`, а `OPENCRM_DEPLOYED` вшит в образ и снаружи
не задаётся вовсе.

    python -m config.selfcheck

Код возврата: 0 — поднимется, 1 — не поднимется, и на stdout сказано почему.
"""

import sys

from config.settings import get_settings


def main() -> int:
    settings = get_settings()

    errors = settings.config_errors()
    for message in settings.config_warnings():
        print(f"ВНИМАНИЕ: {message}")
    if not errors:
        print("настройки сошлись")
        return 0

    print("настройки не сошлись, приложение не поднимется:")
    for message in errors:
        print(f"  - {message}")
    return 1


if __name__ == "__main__":
    sys.exit(main())
